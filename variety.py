# -*- coding: utf-8 -*-
"""Контроль однообразия плана - гейт перед утверждением партии.

**Зачем это не вкусовщина.** Механика внутри гипотезы повторяется намеренно:
без четырех роликов решение принять не на чем. Но если у этих четырех совпадут
кадр и хук, мы поставили **не четыре опыта, а один опыт четыре раза** - и получим
уверенную цифру ни о чем. То есть разнообразие внутри гипотезы это **условие
измеримости**, а не украшение ленты.

**Пороги замерены, а не назначены.** На плане партии 1 (15 строк, 105 пар):
медиана сходства 0,017, максимум 0,227. Пороги стоят между ними - иначе проверка
либо молчит всегда, либо кричит всегда. При смене способа писать хуки пороги
надо перемерить: они верны ровно настолько, насколько верна выборка, на которой сняты.

🔴 **Граница проверки, которую нельзя замалчивать.** Она видит **сходство слов**
и не видит **сходство смысла**. Живой пример из партии 1: «Обещание заменить пять
вещей одной» и «Один предмет вместо трех» - одно обещание разными словами,
лексическое сходство почти нулевое, проверка молчит. Поэтому отчет всегда
заканчивается тем, чего он не проверял, и слепой разбор человеком остается
обязательным, а не «на всякий случай».
"""
import io
import itertools
import re

# 🔴 Пороги РАЗНЫЕ у хука и кадра, и это не придирка. Замер на партии 1, 105 пар:
#
#   хуки  (в среднем  35 символов): медиана 0,017, максимум 0,227 - разделение ×13
#   кадры (в среднем 132 символа):  медиана 0,104, максимум 0,226 - разделение ×2
#
# Длинный русский текст про домашнюю сцену неизбежно делит с другим таким же
# предлоги, «ребенок», «мама». Порог хука, поставленный кадру, дал 33 находки
# из 39 - гейт, который кричит всегда, перестают читать на второй раз.
SIMILAR = 0.12          # для хуков: в семь раз выше типичной пары
WATCH = 0.08            # стоит взглянуть; для соседних дней хватает и этого
# ⚠️ У кадров сигнал слабый по своей природе: между типичной парой и самой
# похожей всего вдвое. Порог стоит у самого верха замера - ловим только явное,
# остальное отдаем глазу.
FRAME_SIMILAR = 0.20

MIN_ROWS_FOR_TYPE = 5   # на четырех строках доля типа - шум, а не однообразие
TYPE_SHARE = 0.7        # доля одного типа, после которой это однообразие

COL_HOOK = "Смысл хука"
COL_FRAME = "Что в кадре"
COL_DATE = "Дата в эфир"
COL_ID = "ID"

# Товары FOXLIK. Нужны, чтобы поймать витрину: один и тот же предмет подряд.
GOODS = {
    "световой стол": ("светов",),
    "столик": ("столик", "стол "),
    "стульчик": ("стульчик", "стульч"),
    "полочка": ("полочк", "полк"),
    "песочница": ("песочниц", "песок", "песк"),
    "планшет": ("планшет",),
    "доска": ("доска", "доск"),
}

# Слова, которыми хук ОПИСЫВАЮТ, а не произносят. Смесь двух жанров в одной
# колонке - тоже находка: часть строк говорит зрителю, часть говорит про прием.
META_WORDS = ("вопрос", "обещание", "инструкц", "прием", "подмена", "формулировк",
              "счет, который", "спорный")

QUESTION_STARTS = ("как", "что", "почему", "зачем", "сколько", "когда", "где", "кто")


def normalize(text):
    """К общему виду: регистр, ё, только буквы и цифры."""
    t = (text or "").lower().replace("ё", "е")
    return re.sub(r"\s+", " ", re.sub(r"[^а-яa-z0-9 ]", " ", t)).strip()


def _trigrams(text):
    t = " " + normalize(text) + " "
    return {t[i:i + 3] for i in range(len(t) - 2)} if len(t) > 2 else set()


def similar(a, b):
    """Сходство по трехбуквенным кусочкам.

    Взяты именно они, а не слова: русский меняет окончания, и «вопрос маме»
    против «вопросы мамам» по словам не совпадет вовсе, а по кусочкам совпадет.
    """
    A, B = _trigrams(a), _trigrams(b)
    if not A or not B:
        return 0.0
    return len(A & B) / float(len(A | B))


def hook_type(text):
    """Вопрос, побуждение или утверждение - грубо, но воспроизводимо."""
    t = normalize(text)
    if not t:
        return "пусто"
    if "?" in (text or "") or t.split()[0] in QUESTION_STARTS or "вопрос" in t:
        return "вопрос"
    if any(w in t for w in ("сделайте", "попробуйте", "сохраняйте", "смотрите")):
        return "побуждение"
    return "утверждение"


def goods_in(text):
    t = normalize(text)
    return {name for name, keys in GOODS.items() if any(k in t for k in keys)}


def _days_apart(a, b):
    import datetime
    try:
        d1 = datetime.date(*[int(x) for x in str(a)[:10].split("-")])
        d2 = datetime.date(*[int(x) for x in str(b)[:10].split("-")])
        return abs((d1 - d2).days)
    except Exception:
        return 99


def check(plan):
    """Находки по плану. Каждая - словарь: вид, строки, что и почему.

    Порядок находок не зависит от порядка строк на входе: гейт, который каждый
    раз отвечает по-разному, доверия не стоит.
    """
    rows = [r for r in plan if str(r.get(COL_ID) or "").strip()]
    if not rows:
        return []
    # 🔴 Порядок фиксируется СРАЗУ, а не только при выдаче. Проверка поймала:
    # находки «один тип хука» и «два жанра» перечисляли строки в порядке входа,
    # и отчет менялся от перестановки строк в таблице. Гейт с плавающим ответом
    # доверия не стоит - его перестают читать.
    rows = sorted(rows, key=lambda r: str(r.get(COL_ID)))
    filled = [r for r in rows if normalize(r.get(COL_HOOK))]
    out = []
    if len(filled) < 2:
        out.append({"вид": "план не заполнен",
                    "строки": [r[COL_ID] for r in rows],
                    "что": "колонка «смысл хука» пуста - проверять нечего",
                    "почему": "это скелет от генератора; содержание вписывает человек"})
        return out

    # --- попарное сходство хуков и кадров ---
    for a, b in itertools.combinations(filled, 2):
        s_hook = similar(a.get(COL_HOOK), b.get(COL_HOOK))
        near = _days_apart(a.get(COL_DATE), b.get(COL_DATE)) <= 1
        if near and s_hook >= WATCH:
            out.append({"вид": "соседние дни похожи", "строки": [a[COL_ID], b[COL_ID]],
                        "что": "хуки соседних дней похожи на %.0f%%" % (s_hook * 100),
                        "почему": "именно соседние ролики зритель сравнивает между собой"})
        elif s_hook >= SIMILAR:
            out.append({"вид": "похожие хуки", "строки": [a[COL_ID], b[COL_ID]],
                        "что": "хуки похожи на %.0f%%" % (s_hook * 100),
                        "почему": "два ролика проверяют одно и то же - опыт "
                                  "повторяется, а не набирается"})
        s_frame = similar(a.get(COL_FRAME), b.get(COL_FRAME))
        if s_frame >= FRAME_SIMILAR and a.get(COL_FRAME):
            out.append({"вид": "похожие кадры", "строки": [a[COL_ID], b[COL_ID]],
                        "что": "описания кадра похожи на %.0f%%" % (s_frame * 100),
                        "почему": "план задается кадром: одинаковый кадр обнуляет замер"})

    # --- один тип хука на всю партию ---
    if len(filled) >= MIN_ROWS_FOR_TYPE:
        from collections import Counter
        types = Counter(hook_type(r.get(COL_HOOK)) for r in filled)
        top, n = types.most_common(1)[0]
        if n >= TYPE_SHARE * len(filled):
            out.append({"вид": "один тип хука", "строки": [r[COL_ID] for r in filled],
                        "что": "%d из %d хуков одного типа: %s" % (n, len(filled), top),
                        "почему": "не проверяется, работает ли другой тип вообще"})

    # --- один товар несколько дней подряд ---
    # 🔴 Два дефекта, найденные на живом плане партии 1:
    #   1. соседство считалось по порядку в списке, а не по датам - пропуск дня
    #      выдавался за «подряд»;
    #   2. серия обрывалась на третьем ролике, и шесть дней одного товара
    #      показывались как два куска по три. Занижение хуже пропуска: цифра
    #      есть, и она успокаивает.
    by_date = sorted(filled, key=lambda r: (str(r.get(COL_DATE) or ""), str(r[COL_ID])))
    run, common = [], set()
    for r in by_date:
        g = goods_in(r.get(COL_FRAME)) or goods_in(r.get(COL_HOOK))
        adjacent = bool(run) and _days_apart(run[-1].get(COL_DATE), r.get(COL_DATE)) == 1
        if run and adjacent and (common & g):
            run.append(r)
            common = common & g
        else:
            if len(run) >= 3 and common:
                out.append(_goods_finding(run, common))
            run, common = [r], set(g)
    if len(run) >= 3 and common:
        out.append(_goods_finding(run, common))

    # --- колонка заполнена в двух жанрах ---
    meta = [r for r in filled if any(w in normalize(r.get(COL_HOOK)) for w in META_WORDS)]
    if meta and len(meta) < len(filled):
        out.append({"вид": "два жанра в колонке", "строки": [r[COL_ID] for r in meta],
                    "что": "%d хуков из %d описывают ПРИЕМ, остальные произносят ФРАЗУ"
                           % (len(meta), len(filled)),
                    "почему": "колонка значит разное в разных строках - креатор "
                              "прочтет ее по-разному, и сравнивать будет нечего"})

    out.sort(key=lambda f: (f["вид"], tuple(f["строки"])))
    return out


def _goods_finding(run, goods):
    return {"вид": "товар подряд", "строки": [x[COL_ID] for x in run],
            "что": "один товар %d дней подряд (%s - %s): %s"
                   % (len(run), run[0].get(COL_DATE), run[-1].get(COL_DATE),
                      ", ".join(sorted(goods))),
            "почему": "лента становится витриной, а не историями"}


LIMITS = ("🔴 Чего эта проверка НЕ видит: сходство СМЫСЛА при разных словах. "
          "Живой пример из партии 1: «Обещание заменить пять вещей одной» и "
          "«Один предмет вместо трех» - одно обещание, разные слова, проверка молчит. "
          "Поэтому слепой разбор человеком обязателен, а не «на всякий случай».")


def report(findings):
    """Отчет владельцу. Всегда заканчивается тем, чего проверка не видит."""
    if not findings:
        lines = ["✅ Однообразия по словам не найдено."]
    else:
        lines = ["Найдено к разбору: %d" % len(findings), ""]
        for f in findings:
            lines.append("· [%s] %s" % (f["вид"], ", ".join(f["строки"])))
            lines.append("  %s" % f["что"])
            lines.append("  почему важно: %s" % f["почему"])
    lines += ["", LIMITS]
    return "\n".join(lines)


def read_tsv(path):
    """План из TSV - тот же файл, которым его заливают в таблицу."""
    rows = [l.rstrip("\n").split("\t")
            for l in io.open(path, encoding="utf-8-sig") if l.strip()]
    return [dict(zip(rows[0], r)) for r in rows[1:]]


