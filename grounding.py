"""Гейт обоснованности - третий перед утверждением партии.

**Зачем.** Аудит 29.08 показал дыру: содержание ролика - «что в кадре» и «смысл
хука» - агент писал из головы. При этом в проекте с 22.07 лежал разбор
**4 277 отзывов** с языком мам и тринадцатью готовыми сюжетами, и он не
открывался ни разу. План партии 1 совпал с этими сюжетами в 4-5 строках
из 15, и то случайно.

**Что делает гейт.** Не выдумывает содержание - спрашивает у каждой строки,
**на чем она стоит**:

| Находка | Что значит |
|---|---|
| ценности нет в справочнике | строка ни на что не опирается, это догадка |
| запрет по возрасту | обещание, которое отзывы прямо запрещают давать |
| стоп-фраза | то же, но словами в кадре или хуке |
| создание спроса | ценность верная, но мамы так не думают - придется учить |

**Где граница.** Гейт видит **ярлык** ценности, а не смысл сцены. Строка может
называть верную ценность и не показывать ее - это ловит только человек.
Ровно так же `variety.py` видит сходство слов и не видит сходства смысла.

Справочник - `data/ценности.tsv`, у каждой строки обязателен источник.

    python grounding.py <план> <ценности> <креаторы> [товары] [сегменты]
"""
