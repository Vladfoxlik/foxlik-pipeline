def report(findings, plan=None, values=None, segments=None):
    if not findings:
        lines = ["✅ Необоснованных строк не найдено."]
    else:
        lines = ["🔴 Строк, у которых с обоснованием непорядок: %d"
                 % len({f["строки"][0] for f in findings}), ""]
        for f in findings:
            lines.append("· [%s] %s" % (f["вид"], ", ".join(f["строки"])))
            lines.append("  %s" % f["что"])
            lines.append("  почему важно: %s" % f["почему"])

    # 🔴 Покрытие. Сильнейшая ценность может стоять в плане один раз, а слабая -
    # шесть. Само по себе это не ошибка, но увидеть перекос надо до съемки.
    if plan and values:
        счет = {}
        for r in plan:
            v = _norm(r.get(COL_VALUE))
            if v:
                счет[v] = счет.get(v, 0) + 1
        if счет:
            lines += ["", "Покрытие ценностей в партии:"]
            for v in sorted(счет, key=lambda x: -счет[x]):
                d = values.get(v)
                метка = d["статус"] if d else "нет в справочнике"
                lines.append("  %-28s %d  (%s)" % (v, счет[v], метка))
            неиспользованные = [v for v, d in values.items()
                                if d["статус"] == LIVES and v not in счет]
            if неиспользованные:
                lines.append("  не использованы, хотя подтверждены: %s"
                             % ", ".join(sorted(неиспользованные)))

    # 🔴 Покрытие сегментов. Партия может целиком говорить с одной аудиторией,
    # и это не видно, пока не посчитаешь: в партии 1 все пятнадцать строк были
    # написаны для мамы, которая покупает себе, при том что 40% столов берут
    # в подарок. Сквозные мотивы в счет не идут - они не аудитория.
    if plan and segments:
        счет_сег = {}
        for r in plan:
            v = _norm(r.get("Сегмент"))
            if v:
                счет_сег[v] = счет_сег.get(v, 0) + 1
        адресуемые = [s for s, d in segments.items()
                      if CROSS_CUTTING not in _norm(d.get("вес"))]
        lines += ["", "Покрытие сегментов:"]
        for s in sorted(адресуемые, key=lambda x: -счет_сег.get(x, 0)):
            lines.append("  %-26s %d  (%s)" % (s, счет_сег.get(s, 0),
                                               segments[s].get("вес") or "-"))
        пустые = [s for s in адресуемые if not счет_сег.get(s)]
        if пустые:
            lines.append("  🔴 не адресован ни один ролик: %s" % ", ".join(sorted(пустые)))
    lines += ["", LIMITS]
    return "\n".join(lines)


