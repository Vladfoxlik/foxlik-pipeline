import os
import sys

COL_ID = "ID"
COL_VALUE = "Ценность"
COL_CREATOR = "Креатор"
COL_FRAME = "Что в кадре"
COL_HOOK = "Хук"
COL_GOODS = "Товар"

# Статусы справочника
LIVES = "живет"
DEMAND = "создание спроса"
NOT_TERM = "не термин"
UNVERIFIED = "не проверено"


def _norm(text):
    return (text or "").strip().lower().replace("ё", "е")


def read_values(stream):
    """Справочник ценностей из TSV. Ключ - имя ценности в нижнем регистре."""
    rows = [line.rstrip("\n").split("\t") for line in stream if line.strip()]
    head = [c.strip() for c in rows[0]]
    out = {}
    for raw in rows[1:]:
        item = dict(zip(head, [c.strip() for c in raw]))
        имя = _norm(item.get("Ценность"))
        if not имя:
            continue
        возраст = item.get("Возраст от", "")
        try:
            возраст = int(возраст)
        except ValueError:
            возраст = None
        out[имя] = {
            "свойство": item.get("Свойство товара", ""),
            "меняет": item.get("Что меняет в дне мамы", ""),
            "статус": _norm(item.get("Статус")),
            "возраст": возраст,
            "ограничение": item.get("Ограничение", ""),
            # 🔴 Отдельно от «Ограничения» (30.08). Ограничение адресовано нам:
            # оно про обещание в тексте поста. Это - про то, чего нельзя делать
            # в кадре, и уходит креатору в карточку. Пусто - значит по кадру
            # ограничений нет, и выдумывать их нельзя.
            "запрет креатору": item.get("Запрет креатору", ""),
            "источник": item.get("Источник", ""),
        }
    return out


def read_goods(stream):
    """Справочник товаров: {ценность: {товары, которые ее дают}}.

    🔴 Зачем. Полка не дает анти-гаджет: у нее нет ни подсветки, ни песка.
    Строка с таким сочетанием обещает то, чего предмет не умеет, и через
    партию вывод «анти-гаджет не работает» будет о чем угодно, кроме него.
    """
    rows = [line.rstrip("\n").split("\t") for line in stream if line.strip()]
    head = [c.strip() for c in rows[0]]
    out = {}
    for raw in rows[1:]:
        item = dict(zip(head, [c.strip() for c in raw]))
        ценность = _norm(item.get("Ценность"))
        товар = _norm(item.get("Товар"))
        if ценность and товар:
            out.setdefault(ценность, set()).add(товар)
    return out


CROSS_CUTTING = "сквозной мотив"


def read_segments(stream):
    """Справочник сегментов: кому адресован ролик.

    🔴 Зачем. Живой случай 29.08: в партии 1 все пятнадцать строк написаны
    для мамы, которая покупает себе, а **40% столов покупают в подарок**.
    Целый сегмент с другой болью не звали вовсе, и увидеть это было нечем.

    Сегменты не выдуманы - они размечены на 4 277 отзывах (ОТЗЫВЫ_WB §1).
    Один из них - «мама-сборщик» - помечен как **сквозной мотив**: он живет
    внутри других сегментов, адресовать ролик ему нельзя.
    """
    rows = [line.rstrip("\n").split("\t") for line in stream if line.strip()]
    head = [c.strip() for c in rows[0]]
    out = {}
    for raw in rows[1:]:
        item = dict(zip(head, [c.strip() for c in raw]))
        имя = _norm(item.get("Сегмент"))
        if not имя:
            continue
        out[имя] = {
            "кто": item.get("Кто это", ""),
            "боль": item.get("Его боль", ""),
            "ценно": item.get("Что для него ценно", ""),
            "вес": item.get("Вес", ""),
            "осторожно": item.get("Осторожно", ""),
            "источник": item.get("Источник", ""),
        }
    return out


def _признак_в(признак, текст):
    """Есть ли стоп-признак в тексте сцены. Не голая подстрока.

    🔴 Замер 30.08 на живом плане: признак «на пол» сработал на сцене «папа
    переставляет книги НА ПОЛку». Ложная находка выбивает годную строку, а
    правка под нее рождает новое нарушение - тот самый цикл, из которого мы
    вылезали, перенося ограничения на вход.

    Правило простое и держится на форме самого признака:
    - признак из НЕСКОЛЬКИХ слов («на пол», «вешает полку») - это фраза,
      и справа от нее обязана быть граница слова;
    - признак из одного слова («сверл», «дюбел») - это основа, он нарочно
      написан без окончания, чтобы ловить «сверлит» и «сверлил».
    """
    if not признак or признак not in текст:
        return False
    if " " not in признак:
        return True                    # основа: окончание дописывает язык
    конец = текст.index(признак) + len(признак)
    return конец >= len(текст) or not текст[конец].isalpha()


def read_stops(stream):
    """Справочник стоп-действий: чего нельзя требовать от человека дома.

    🔴 Замер владельца 30.08 по двум строкам плана. «Папа сверлит стену и вешает
    полку» - это дыры в его собственной квартире, где полка уже висит; второй
    раз он сверлить не пойдет. «Папа щелкает фиксатором, меняя высоту стола» -
    физически неверно: высота перекручивается ОТВЕРТКОЙ, крепления развинчиваются,
    это разборка на минуты, а не жест на две секунды.

    Общий класс: **сцена бывает невыполнима не по возрасту ребенка и не по
    правдивости обещания, а по цене съемки** - инструмент, деньги, время, чужое
    жилье. До 30.08 система про это не знала ничего: и `feasibility`, и
    `grounding` спрашивали, что у креатора ЕСТЬ, и не спрашивали, чего это
    стоит. Список - данные, а не код: он будет расти от каждого «так не выйдет».
    """
    rows = [line.rstrip("\n").split("\t") for line in stream if line.strip()]
    if not rows:
        return []
    head = [c.strip() for c in rows[0]]
    out = []
    for raw in rows[1:]:
        item = dict(zip(head, [c.strip() for c in raw]))
        слова = [_norm(w) for w in (item.get("Слова-признаки") or "").split(",")
                 if w.strip()]
        if not слова:
            continue
        out.append({"действие": item.get("Действие", ""),
                    "слова": слова,
                    # 🔴 Товар (31.08): стоп-действие бывает верным только для
                    # одного предмета. «Корзина» на книжной полке - ошибка,
                    # корзина на полу рядом со столом - обычная жизнь. Пустой
                    # товар means «ко всем строкам», как было до 31.08.
                    "товар": _norm(item.get("Товар", "")),
                    "класс": item.get("Класс", ""),
                    "почему": item.get("Почему нельзя требовать", ""),
                    "вместо": item.get("Что вместо", ""),
                    "источник": item.get("Источник", "")})
    return out


def read_profiles(stream):
    """Профили креаторов - те же, что читает feasibility, но нужен только возраст.

    🔴 Одна строка файла = один РЕБЕНОК. Возвращаем список пар (кто, возраст):
    без «кто» невозможно проверить строку плана, где в кадре занят конкретный
    ребенок, а не «любой из детей креатора».
    """
    rows = [line.rstrip("\n").split("\t") for line in stream if line.strip()]
    head = [c.strip() for c in rows[0]]
    out = {}
    for raw in rows[1:]:
        item = dict(zip(head, [c.strip() for c in raw]))
        имя = item.get("Креатор", "")
        if not имя:
            continue
        try:
            возраст = int(item.get("Возраст месяцев", ""))
        except ValueError:
            возраст = None
        out.setdefault(имя, []).append((item.get("Ребенок", ""), возраст))
    return out


def кто_в_кадре(дети, названный):
    """Чей возраст проверять: названного ребенка или самого младшего.

    🔴 Правило перевернуто после слепой приемки 29.08. Было: «подойдет ли
    ХОТЬ КТО-ТО из детей креатора» - и старшая дочь 48 мес. закрывала собой
    младшего сына 18 мес., который единственный был в кадре. Стало: пока
    строка не назвала ребенка, судим по САМОМУ МЛАДШЕМУ. Ошибаться безопаснее
    в сторону запрета: лишняя находка стоит вопроса креатору, пропущенная -
    испорченного ролика и вранья в обещании.

    Возвращает (список подходящих, ошибка). Ошибка - если названного ребенка
    у креатора нет вовсе.
    """
    if not дети:
        return [], None
    if названный:
        # 🔴 В кадре может быть двое: «сын, дочь». Тогда обещание меряется
        # по младшему из названных - он в сцене тоже участвует.
        имена = [и.strip() for и in названный.replace(";", ",").split(",") if и.strip()]
        свои = [d for d in дети if d[0] and d[0] in имена]
        чужие = [и for и in имена if not any(d[0] == и for d in дети)]
        if чужие:
            return свои, ", ".join(чужие)
        return свои, None
    возрасты = [d for d in дети if d[1] is not None]
    if not возрасты:
        return дети, None
    младший = min(возрасты, key=lambda d: d[1])
    return [младший], None


