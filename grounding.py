def взрослый_в_кадре(текст):
    """Есть ли в описании кадра хоть один взрослый - хотя бы руками.

    Руки считаются: «рука взрослого забирает телефон» - это присутствие,
    даже если лица нет. Отсутствие взрослого при малыше - отдельная находка.
    """
    t = _norm(текст)
    if any(п in t for п in NO_ADULT):
        return False
    return any(w in t for w in ADULT_WORDS)


