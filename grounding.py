def check(plan, values, profiles, goods=None, segments=None, stops=None):
    """Находки: на чем стоит строка плана и не обещает ли она запрещенного."""
    goods = goods or {}
    segments = segments or {}
    stops = stops or []
    out = []
    for r in plan:
        vid = r.get(COL_ID, "")
        ценность = _norm(r.get(COL_VALUE))
        текст = _norm((r.get(COL_FRAME) or "") + " " + (r.get(COL_HOOK) or ""))
        кто = (r.get(COL_CREATOR) or "").strip()

        # --- цена съемки: сцена может быть невыполнима не по возрасту ---
        # 🔴 Проверяется по «что в кадре», а не по ценности: дорогое действие
        # прячется именно в описании сцены. Находка обязана нести замену -
        # запрет без «а как тогда» возвращает строку в тот же тупик.
        for стоп in stops:
            свой = (стоп.get("товар") or "").strip()
            if свой and свой not in _norm(r.get(COL_GOODS) or ""):
                continue          # правило про другой товар - эта строка не про него
            попало = [w for w in стоп["слова"] if _признак_в(w, текст)]
            if попало:
                # 🔴 Источник в тексте находки обязателен. Часть строк
                # справочника - замеры владельца, часть выведена мной и
                # у креаторов не спрашивалась. Без пометки догадка выбивает
                # строку плана наравне с фактом, и это ровно то, что запрещает
                # правило закрытой двери.
                out.append({"вид": "цена съемки", "строки": [vid],
                            "что": "сцена требует: %s (нашлось «%s»)"
                                   % (стоп["действие"], попало[0]),
                            "почему": "%s Вместо: %s [основание: %s]"
                                      % (стоп["почему"], стоп["вместо"],
                                         стоп["источник"] or "не указано")})
                break        # одного класса на строку достаточно

        # --- стоп-фразы: проверяем всегда, даже если ценность в порядке ---
        for фраза, почему in STOP_PHRASES.items():
            if фраза in текст:
                out.append({"вид": "запрещенное обещание", "строки": [vid],
                            "что": "в тексте строки есть «%s»" % фраза,
                            "почему": "это обещание запрещено: %s" % почему})

        # --- кому адресован ролик ---
        сегмент = _norm(r.get("Сегмент"))
        if сегмент and segments:
            d_seg = segments.get(сегмент)
            if d_seg is None:
                out.append({"вид": "сегмент не из справочника", "строки": [vid],
                            "что": "сегмент «%s» не найден в справочнике" % сегмент,
                            "почему": "аудитория придумана, а не взята из разбора "
                                      "отзывов - через партию вывод будет спорным"})
            elif CROSS_CUTTING in _norm(d_seg.get("вес")):
                out.append({"вид": "не сегмент, а мотив", "строки": [vid],
                            "что": "«%s» - %s, он живет внутри других сегментов"
                                   % (сегмент, d_seg.get("вес")),
                            "почему": "адресовать ролик мотиву нельзя: непонятно, "
                                      "чью боль он закрывает"})

        if not ценность:
            # 🔴 02.09: роль «без товара» - ролик чистого узнавания, ценность
            # привязана к товару и тут законно пуста (замер 26.08: репосты
            # дает узнавание). Иначе весь поток «без товара» стоял бы в находках.
            if _norm(r.get("Роль товара")) == "без товара":
                continue
            out.append({"вид": "нет ценности", "строки": [vid],
                        "что": "у строки не заполнена ценность",
                        "почему": "непонятно, что именно проверяет ролик - "
                                  "через партию вывод будет не о чем"})
            continue

        d = values.get(ценность)
        if d is None:
            out.append({"вид": "не из справочника", "строки": [vid],
                        "что": "ценность «%s» не найдена в справочнике" % ценность,
                        "почему": "строка стоит на догадке, а не на языке "
                                  "покупателей: через партию вывод будет спорным"})
            continue

        # --- запрет по возрасту ---
        # Ценность может требовать возраста: «занят сам» с годовалым - это
        # ровно то обещание, над которым мамы смеются в отзывах.
        нужен = d["возраст"]
        дети = profiles.get(кто) or []
        названный = _norm(r.get("Ребенок в кадре"))
        в_кадре, нет_такого = кто_в_кадре(дети, названный)

        if нет_такого:
            out.append({"вид": "нет такого ребенка", "строки": [vid],
                        "что": "в кадре назван «%s», а у «%s» есть только: %s"
                               % (нет_такого, кто,
                                  ", ".join(d0 or "?" for d0, _ in дети) or "никого"),
                        "почему": "снимать некем: ребенка надо назвать так же, "
                                  "как он записан в data/креаторы.tsv"})

        # 🔴 Судим по САМОМУ МЛАДШЕМУ из тех, кто в кадре. Если названы оба
        # ребенка, обещание «занят сам» все равно относится и к младшему -
        # мама смотрит на того, кто в ее семье такого же возраста.
        известные = [d for d in в_кадре if d[1] is not None]
        мерка = min(известные, key=lambda d: d[1]) if известные else None
        подходят = ([] if (мерка and нужен is not None and мерка[1] < нужен)
                    else [1])
        if нужен is not None and в_кадре and not подходят:
            чей = ("«%s», %s мес." % (мерка[0], мерка[1]) if названный
                   else "младшему из детей %s мес." % мерка[1])
            out.append({"вид": "запрет по возрасту", "строки": [vid],
                        "что": "ценность «%s» требует ребенка от %d мес., "
                               "а в кадре у «%s» - %s"
                               % (ценность, нужен, кто, чей),
                        "почему": (d["ограничение"] or "обещание не подтверждается "
                                                       "на таком возрасте") +
                                  ("" if названный else
                                   ". Строка не назвала, кто в кадре, поэтому судим "
                                   "по младшему - заполните «Ребенок в кадре»")})

        # --- 🔴 малыш один в кадре ---
        # Ярлык ценности тут ни при чем: обещание делает КАДР. Найдено вторым
        # слепым проходом 29.08, и создано попыткой развести гипотезы - я убрал
        # взрослого из сцены, не заметив, что вместе с ним ушла и честность.
        сцена = "%s %s %s" % (r.get("Что в кадре") or "", r.get("Хук") or "",
                              r.get("Текст на экране") or "")
        малыши = [в for _, в in в_кадре if в is not None and в < SOLO_AGE]
        if малыши and сцена.strip() and not взрослый_в_кадре(сцена):
            out.append({"вид": "малыш один в кадре", "строки": [vid],
                        "что": "ребенку %d мес., а взрослого в кадре нет" % малыши[0],
                        "почему": "кадр обещает «годовалый играет сам» - над этим "
                                  "обещанием мамы смеются (ОТЗЫВЫ §5). Честная рамка: "
                                  "с 2 лет сам, в 1,5 - вместе со взрослым"})

        # --- 🔴 ценность несет прямой запрет: показать человеку ---
        # Судить машина тут не может. Живой случай: ⛔ «не обещать нагрузку на
        # столешницу» против сцены «встает на планшет всем весом» - по словам
        # ноль совпадений, по смыслу прямое нарушение. Поэтому не вердикт,
        # а обязательная выкладка: строка стоит на ценности с запретом, читай.
        ограничение = d["ограничение"] or ""
        if ограничение.startswith("⛔"):
            out.append({"вид": "ценность с запретом", "строки": [vid],
                        "что": "строка стоит на ценности «%s», у которой есть "
                               "прямой запрет - сверьте сцену глазами" % ценность,
                        "почему": ограничение})

        # --- товар обязан поддерживать заявленную ценность ---
        # Судим, только если ценность вообще привязана к товарам: бывают
        # общие - «подарок», «натуральный материал», они не про предмет.
        товар = _norm(r.get("Товар"))
        дают = goods.get(ценность)
        if товар and дают and товар not in дают:
            out.append({"вид": "товар не дает эту ценность", "строки": [vid],
                        "что": "«%s» заявлена на товаре «%s», а по справочнику "
                               "ее дают: %s" % (ценность, товар, ", ".join(sorted(дают))),
                        "почему": "ролик обещает то, чего предмет не умеет - "
                                  "через партию вывод будет не об этой ценности"})

        # --- ценность верная, но чужая языку мам ---
        if d["статус"] in (DEMAND, NOT_TERM):
            out.append({"вид": "создание спроса", "строки": [vid],
                        "что": "«%s»: %s" % (ценность, d["ограничение"] or d["статус"]),
                        "почему": "это не перехват готового спроса, а обучение "
                                  "аудитории - решать владельцу, но знать заранее"})
        elif d["статус"] == UNVERIFIED:
            out.append({"вид": "не проверено", "строки": [vid],
                        "что": "«%s» прямыми цитатами не подтверждена: %s"
                               % (ценность, d["источник"]),
                        "почему": "ставить можно, выдавать за подтвержденное - нет"})

    out.sort(key=lambda f: (f["строки"], f["вид"]))
    return out


