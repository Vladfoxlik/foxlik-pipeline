# -*- coding: utf-8 -*-
"""Выполнимость плана: может ли назначенный креатор снять эту строку.

🔴 Чем вскрылась нужда. Замер 28.08 на живом плане партии 1: у Спартака сын около
года и один наш товар на руках, а план требовал от него шести разных товаров,
говорящего ребенка и сцену с дочерью. Снимаемой оказалась **одна строка из семи**.

Генератор знает механику, дату и ИМЯ креатора. Про самого креатора он не знает
ничего - план оптимизирован под измеримость и слеп к выполнимости. Гейт однообразия
это тоже не ловит: он ищет повторы, а не невозможность.

🔴 **Почему это условие замера, а не бытовое удобство.** Если строку нельзя снять,
ее снимет другой человек или ее не будет вовсе. И то и другое ломает раскладку
«оба креатора внутри каждой гипотезы», ради которой партия и строится: разницу
механик снова станет не отличить от разницы людей.

Источник профилей - `data/креаторы.tsv`, заполняется человеком со слов креаторов.
Машина профили не угадывает и не дополняет.

    python feasibility.py ../data/план_партии_1.tsv ../data/креаторы.tsv
"""
import io
import sys

# Товары FOXLIK - те же имена, что в variety, но здесь важно другое: есть ли
# предмет НА РУКАХ у конкретного человека.
GOODS = {
    "световой стол": ("световой стол", "световом столе", "светового стола",
                      "световым столом"),
    "световой планшет": ("световой планшет", "световом планшете",
                         "светового планшета", "световым планшетом"),
    "стол-песочница": ("стол-песочниц", "столе-песочниц", "стола-песочниц",
                       "песочниц"),
    "столик": ("столик", "столике", "столика"),
    "стульчик": ("стульчик", "стульч"),
    "полочка": ("полочк", "полк"),
}
ABSORB = {"световой стол": ("столик",), "световой планшет": ("столик",),
          "стол-песочница": ("столик",)}

# Слова, по которым видно пол ребенка в кадре.
GIRL = ("дочь", "дочка", "дочку", "дочери", "девочка", "она рисует", "малышка")
BOY = ("сын", "сына", "сынок", "мальчик", "он рисует")

# Что ребенок должен уметь, чтобы сцена состоялась, и с какого возраста это
# обычно возможно. Числа - ориентир, а не медицинская норма: они нужны, чтобы
# отсеять заведомо невозможное, а не чтобы спорить с родителем о развитии.
SKILLS = {
    "говорит": (("говорит", "рассказыва", "спрашива", "отвечает", "стишок",
                 "предложениями", "повторяет слово"), 24),
    "ходит": (("идет", "ходит", "бежит", "убегает", "приносит", "в сад", "садик"), 15),
    "сидит за столом": (("сидит за", "рисует", "лепит", "собирает", "раскраш"), 18),
}


def _norm(text):
    return (text or "").lower().replace("ё", "е")


def goods_in(text):
    t = _norm(text)
    found = {name for name, keys in GOODS.items() if any(k in t for k in keys)}
    for name in list(found):
        for weaker in ABSORB.get(name, ()):
            found.discard(weaker)
    return found


def read_profiles(stream):
    """Профили из TSV. Пустые и неизвестные поля остаются пустыми - не угадываем."""
    rows = [line.rstrip("\n").split("\t") for line in stream if line.strip()]
    head = [c.strip() for c in rows[0]]
    out = {}
    for raw in rows[1:]:
        item = dict(zip(head, [c.strip() for c in raw]))
        имя = item.get("Креатор", "")
        if not имя:
            continue
        возраст = item.get("Возраст месяцев", "")
        try:
            возраст = int(возраст)
        except ValueError:
            возраст = None
        товары = goods_in(item.get("Товары", ""))
        out[имя] = {
            "кто в кадре": item.get("Кто в кадре", ""),
            "пол": _norm(item.get("Пол ребенка", "")),
            "возраст": возраст,
            "умеет": _norm(item.get("Умеет", "")),
            "товары": товары,
            "товары_текст": item.get("Товары", ""),
            "подтверждено": item.get("Подтверждено", ""),
        }
    return out


def read_tsv(path):
    with io.open(path, encoding="utf-8-sig") as f:
        rows = [line.rstrip("\n").split("\t") for line in f if line.strip()]
    head = [c.strip() for c in rows[0]]
    return [dict(zip(head, [c.strip() for c in r])) for r in rows[1:]]


def check(plan, profiles):
    """Находки: строка плана против профиля назначенного креатора."""
    out = []
    for r in plan:
        vid = r.get("ID", "")
        кто = (r.get("Креатор") or "").strip()
        кадр = r.get("Что в кадре") or ""
        текст = кадр + " " + (r.get("Смысл хука") or "")
        if not кадр.strip():
            continue                    # содержания еще нет - судить нечего
        профиль = profiles.get(кто)
        if профиль is None:
            out.append({"вид": "нет профиля", "строки": [vid],
                        "что": "у креатора «%s» нет профиля - снимаемость строки "
                               "проверить нечем" % (кто or "не назначен"),
                        "почему": "невыполнимая строка выпадет из партии и сломает "
                                  "раскладку креаторов внутри гипотезы"})
            continue

        # --- товар на руках ---
        нужно = goods_in(текст)
        нет = нужно - профиль["товары"]
        if нет:
            out.append({"вид": "нет товара", "строки": [vid],
                        "что": "нужен товар: %s. У креатора «%s» на руках: %s"
                               % (", ".join(sorted(нет)), кто,
                                  профиль["товары_текст"] or "не указано"),
                        "почему": "снять нечем - строку придется отдать другому "
                                  "или выбросить"})

        # --- пол ребенка ---
        t = _norm(текст)
        if профиль["пол"]:
            if any(w in t for w in GIRL) and "мальч" in профиль["пол"]:
                out.append({"вид": "не тот ребенок", "строки": [vid],
                            "что": "в кадре дочь, а по профилю «%s» - сын" % кто,
                            "почему": "сцена написана про другого ребенка - "
                                      "это другой ролик, а не мелкая правка"})
            if any(w in t for w in BOY) and "девоч" in профиль["пол"]:
                out.append({"вид": "не тот ребенок", "строки": [vid],
                            "что": "в кадре сын, а по профилю «%s» - дочь" % кто,
                            "почему": "сцена написана про другого ребенка"})

        # --- умения по возрасту ---
        if профиль["возраст"] is not None:
            for навык, (слова, надо) in SKILLS.items():
                if any(w in t for w in слова) and профиль["возраст"] < надо:
                    out.append({"вид": "рано по возрасту", "строки": [vid],
                                "что": "кадр требует «%s», а ребенку по профилю "
                                       "«%s» - %d мес." % (навык, кто, профиль["возраст"]),
                                "почему": "снять не выйдет, и это станет ясно "
                                          "только на площадке"})
    out.sort(key=lambda f: (f["строки"], f["вид"]))
    return out


LIMITS = ("🔴 Чего эта проверка НЕ видит: обстановку и свет (есть ли дома нужный угол, "
          "окно, второй взрослый за камерой), готовность показывать лицо, время "
          "на съемку. Это спрашивают у человека, а не выводят из таблицы.")


def report(findings, profiles=None):
    if not findings:
        lines = ["✅ Невыполнимых строк не найдено."]
    else:
        lines = ["🔴 Строк, которые назначенный креатор снять не сможет: %d"
                 % len({f["строки"][0] for f in findings}), ""]
        for f in findings:
            lines.append("· [%s] %s" % (f["вид"], ", ".join(f["строки"])))
            lines.append("  %s" % f["что"])
            lines.append("  почему важно: %s" % f["почему"])
    # 🔴 Профиль со слов - не факт. Строить на нем план можно, выдавать за факт нельзя.
    if profiles:
        неподтвержденные = [имя for имя, p in profiles.items()
                            if "да" not in _norm(p.get("подтверждено", ""))]
        if неподтвержденные:
            lines += ["", "⚠️ Профили не подтверждены самими креаторами: %s. "
                          "Проверка идет по тому, что записано со слов."
                      % ", ".join(sorted(неподтвержденные))]
    lines += ["", LIMITS]
    return "\n".join(lines)


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    if "--selftest" in sys.argv or len(args) < 2:
        sys.path.insert(0, "tests")
        import test_feasibility
        test_feasibility.selftest()
        return
    plan = read_tsv(args[0])
    with io.open(args[1], encoding="utf-8-sig") as f:
        profiles = read_profiles(f)
    print(report(check(plan, profiles), profiles))


if __name__ == "__main__":
    main()
