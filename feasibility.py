def _norm(text):
    return (text or "").lower().replace("ё", "е")


# Кто в сегменте выполняет действие. Только явные существительные: местоимения
# «он» и «она» одинаково указывают и на папу, и на дочь - гадать по ним нельзя.
ВЗРОСЛЫЙ_СЛОВА = ("папа", "мама", "отец", "мать", "муж", "жена", "бабушк", "дедушк",
                  "родител", "взрослый")
РЕБЕНОК_СЛОВА = ("дочь", "дочка", "дочку", "сын", "ребенок", "ребенка", "малыш",
                 "девочка", "мальчик", "младш", "старш", "оба")


def _сегменты(текст):
    """Дробим фразу на куски, внутри которых субъект действия один."""
    куски, буфер = [], ""
    i = 0
    разделители = (",", ".", ";", ":", "!", "?", " и ", " а ", " - ", " но ")
    while i < len(текст):
        for р in разделители:
            if текст.startswith(р, i):
                куски.append(буфер)
                буфер = ""
                i += len(р)
                break
        else:
            буфер += текст[i]
            i += 1
    куски.append(буфер)
    return [к for к in куски if к.strip()]


def действие_у_ребенка(текст, слова_триггеры):
    """Выполняет ли действие ребенок, а не взрослый.

    🔴 Живой случай 29.08 на плане партии 1: две находки из трех были ложными.
    «Папа рисует на планшете, дочь стирает ладонью» - рисует ПАПА, а проверка
    требовала от 11-месячной дочери навыка «сидит за столом». Гейт, который
    заваливает нормальные строки, перестают читать, и он пропустит настоящую
    находку вместе с шумом.

    Субъект тянется из предыдущего сегмента: «папа рисует и стирает» - оба
    действия его. Если субъект не назван нигде, считаем действие детским:
    ложная тревога дешевле пропуска.
    """
    последний = None
    for кусок in _сегменты(текст):
        if any(w in кусок for w in ВЗРОСЛЫЙ_СЛОВА):
            последний = "взрослый"
        if any(w in кусок for w in РЕБЕНОК_СЛОВА):
            последний = "ребенок"     # ребенок ближе к глаголу - он и действует
        if any(w in кусок for w in слова_триггеры) and последний != "взрослый":
            # 🔴 Отрицание переворачивает смысл. Найдено 30.08 на живом плане:
            # «он не торопит и не говорит ничего» - это про молчащего взрослого,
            # а проверка прочла как требование речи от 11-месячной. Ложная
            # находка выбивает годную строку, автор ее переписывает - и новый
            # текст рождает новое нарушение. Этот цикл уже стоил нам недели.
            if _отрицание(кусок):
                continue
            return True
    return False


# Частицы отрицания перед глаголом. Список короткий нарочно: чем он длиннее,
# тем больше настоящих требований проверка пропустит молча.
ОТРИЦАНИЯ = (" не ", "не ", " ни ")


def _отрицание(кусок):
    """Есть ли «не» перед действием в этом же куске."""
    к = " " + кусок.strip()
    return any(ч in к for ч in ОТРИЦАНИЯ)


# Предлоги, после которых человек - адресат или место, а не участник кадра.
АДРЕСАТ = ("к ", "у ", "от ", "для ", "про ", "без ")


def _роль_в_кадре(текст, слово):
    """Упомянут ли человек как УЧАСТНИК сцены, а не как адресат.

    🔴 Найдено 30.08 на живом плане: «три вещи уехали к бабушке» читалось как
    «в кадре нужна бабушка», и строка выбывала. Бабушка там - место, куда увезли
    мольберт; в кадре ее нет и не требуется. Признак машинный и узкий: предлог
    направления прямо перед словом.
    """
    i = текст.find(слово)
    while i != -1:
        до = текст[:i].rstrip()
        хвост = (до.rsplit(" ", 1)[-1] + " ") if " " in до else (до + " ")
        if хвост not in АДРЕСАТ:
            return True
        i = текст.find(слово, i + 1)
    return False


def goods_in(text):
    t = _norm(text)
    found = {name for name, keys in GOODS.items() if any(k in t for k in keys)}
    for name in list(found):
        for weaker in ABSORB.get(name, ()):
            found.discard(weaker)
    return found


def read_profiles(stream):
    """Профили из TSV. Пустые и неизвестные поля остаются пустыми - не угадываем.

    🔴 Одна строка = один РЕБЕНОК, а не один креатор. Живой случай 29.08:
    у Ксении сын 1.5 года и дочь 4 лет. Пока ключом был креатор, вторая строка
    молча затирала первую - и сцена с полуторагодовалым проходила проверку
    по возрасту четырехлетки. Дефект тихий: не падает, а одобряет невыполнимое.
    """
    rows = [line.rstrip("\n").split("\t") for line in stream if line.strip()]
    head = [c.strip() for c in rows[0]]
    out = {}
    for raw in rows[1:]:
        item = dict(zip(head, [c.strip() for c in raw]))
        имя = item.get("Креатор", "")
        if not имя:
            continue
        возраст = item.get("Возраст месяцев", "")
        try:
            возраст = int(возраст)
        except ValueError:
            возраст = None
        ребенок = {
            "метка": item.get("Ребенок", "") or item.get("Пол ребенка", ""),
            "пол": _norm(item.get("Пол ребенка", "")),
            "возраст": возраст,
            "умеет": _norm(item.get("Умеет", "")),
        }
        профиль = out.setdefault(имя, {
            "кто в кадре": item.get("Кто в кадре", ""),
            "дети": [],
            "товары": set(),
            "товары_текст": "",
            "второй взрослый": "",
            # 🔴 Как часто второго взрослого можно занимать. Пусто - не спрашивали
            # и не ограничиваем; число - раз в неделю. Он не сотрудник, ставка
            # ему не платится, и согласие на 7-8 съемок за две недели никто
            # не давал (замер 30.08 на плане партии 1: у Ксении вышло 9 строк).
            "второй взрослый в неделю": None,
            "оператор": "",
            "подтверждено": item.get("Подтверждено", ""),
        })
        профиль["дети"].append(ребенок)
        # Товары и взрослые общие для креатора: берем из любой строки, где заполнены.
        профиль["товары"] |= goods_in(item.get("Товары", ""))
        профиль["товары_текст"] = профиль["товары_текст"] or item.get("Товары", "")
        профиль["второй взрослый"] = (профиль["второй взрослый"]
                                      or item.get("Второй взрослый", ""))
        if профиль["второй взрослый в неделю"] is None:
            try:
                профиль["второй взрослый в неделю"] = int(
                    item.get("Второй взрослый в неделю", "").strip())
            except (ValueError, AttributeError):
                pass                    # пусто или мусор - значит не ограничиваем
        профиль["оператор"] = профиль["оператор"] or item.get("Оператор", "")
    return out


def детей(profiles, имя):
    """Сколько детей у креатора. Отдельной функцией - чтобы проверка на это была."""
    return len((profiles.get(имя) or {}).get("дети", []))


def read_tsv(path):
    with io.open(path, encoding="utf-8-sig") as f:
        rows = [line.rstrip("\n").split("\t") for line in f if line.strip()]
    head = [c.strip() for c in rows[0]]
    return [dict(zip(head, [c.strip() for c in r])) for r in rows[1:]]


def check(plan, profiles):
    """Находки: строка плана против профиля назначенного креатора."""
    out = []
    for r in plan:
        vid = r.get("ID", "")
        кто = (r.get("Креатор") or "").strip()
        кадр = r.get("Что в кадре") or ""
        # 🔴 Надпись на экране в состав кадра НЕ входит (30.08). Она пишется
        # поверх видео и может обращаться к кому угодно: «БАБУШКИ, ЭТО ДЛЯ ВАС»
        # адресовано тем, кто дарит, а в кадре папа с дочерью. Пока надпись
        # склеивалась с кадром, проверка требовала бабушку на съемке.
        # Тот же класс, что «уехали к бабушке»: слово есть, роли в кадре нет.
        текст = кадр + " " + (r.get("Хук") or "")
        if not кадр.strip():
            continue                    # содержания еще нет - судить нечего
        профиль = profiles.get(кто)
        if профиль is None:
            out.append({"вид": "нет профиля", "строки": [vid],
                        "что": "у креатора «%s» нет профиля - снимаемость строки "
                               "проверить нечем" % (кто or "не назначен"),
                        "почему": "невыполнимая строка выпадет из партии и сломает "
                                  "раскладку креаторов внутри гипотезы"})
            continue

        # --- товар на руках ---
        нужно = goods_in(текст)
        нет = нужно - профиль["товары"]
        if нет:
            out.append({"вид": "нет товара", "строки": [vid],
                        "что": "нужен товар: %s. У креатора «%s» на руках: %s"
                               % (", ".join(sorted(нет)), кто,
                                  профиль["товары_текст"] or "не указано"),
                        "почему": "снять нечем - строку придется отдать другому "
                                  "или выбросить"})

        # --- какой ребенок играет эту сцену ---
        # Кадр может назвать пол прямо («дочь не отпускает папу»), а может
        # промолчать. Если назван - кандидатов сужаем; если нет - годится любой.
        t = _norm(текст)
        дети = профиль["дети"]
        хочет_девочку = any(w in t for w in GIRL)
        хочет_мальчика = any(w in t for w in BOY)
        кандидаты = дети
        if хочет_девочку and not хочет_мальчика:
            кандидаты = [р for р in дети if "девоч" in р["пол"]]
        elif хочет_мальчика and not хочет_девочку:
            кандидаты = [р for р in дети if "мальч" in р["пол"]]

        if дети and not кандидаты:
            есть = ", ".join("%s %s мес." % (р["метка"] or р["пол"], р["возраст"])
                             for р in дети)
            out.append({"вид": "не тот ребенок", "строки": [vid],
                        "что": "кадр написан про %s, а у «%s» дома: %s"
                               % ("дочь" if хочет_девочку else "сына", кто, есть),
                        "почему": "сцена написана про другого ребенка - "
                                  "это другой ролик, а не мелкая правка"})
            кандидаты = дети            # дальше судим по тому, кто есть

        # --- умения по возрасту ---
        # Находка только если НИ ОДИН подходящий ребенок не дорос: у креатора
        # с двумя детьми старший может сыграть то, что младшему рано.
        for навык, (слова, надо) in SKILLS.items():
            if not any(w in t for w in слова):
                continue
            # Действие взрослого ребенку не приписываем: «папа рисует, дочь
            # стирает» не требует от дочери умения рисовать.
            if not действие_у_ребенка(t, слова):
                continue
            доказ = SKILL_PROOF.get(навык, ())
            годные = [р for р in кандидаты
                      if р["возраст"] is None or р["возраст"] >= надо
                      or any(d in р["умеет"] for d in доказ)]
            if кандидаты and not годные:
                кто_есть = ", ".join("%s %d мес." % (р["метка"] or р["пол"], р["возраст"])
                                     for р in кандидаты if р["возраст"] is not None)
                out.append({"вид": "рано по возрасту", "строки": [vid],
                            "что": "кадр требует «%s», а у «%s» для этой сцены "
                                   "есть только: %s" % (навык, кто, кто_есть),
                            "почему": "снять не выйдет, и это станет ясно "
                                      "только на площадке"})

        # --- второй взрослый в кадре ---
        # Гипотеза «папа» без него не снимается вовсе, а раньше проверка
        # этого не видела совсем - строка уходила в план и ломалась на площадке.
        своя_роль = _norm(профиль["кто в кадре"])
        нужны = {роль for роль, слова in ADULTS.items()
                 if any(_роль_в_кадре(t, w) for w in слова)}
        нужны.discard(своя_роль)
        есть_текст = _norm(профиль["второй взрослый"])
        if (нужны or any(w in t for w in TOGETHER)) and not есть_текст:
            out.append({"вид": "нет второго взрослого", "строки": [vid],
                        "что": "кадр требует второго взрослого (%s), а у «%s» "
                               "в профиле его нет"
                               % (", ".join(sorted(нужны)) or "сцена вдвоем", кто),
                        "почему": "снимать некем: либо роль играет оператор и "
                                  "камеру держать некому, либо сцены не будет"})
        elif нужны and есть_текст:
            # 🔴 Второй взрослый - это КОНКРЕТНЫЙ человек, а не «кто-нибудь».
            # Живой случай 29.08: сцена «подарок глазами бабушки» проходила
            # проверку, потому что у обоих креаторов второй взрослый есть -
            # жена и муж. Бабушки при этом нет ни у кого, и роль сыграть некому.
            есть_роли = {роль for роль, слова in ADULTS.items()
                         if any(w in есть_текст for w in слова)}
            есть_роли.add(своя_роль)
            не_кем = нужны - есть_роли
            if не_кем:
                out.append({"вид": "нет такого взрослого", "строки": [vid],
                            "что": "кадр требует роль «%s», а у «%s» в кадре "
                                   "может быть только: %s (%s)"
                                   % (", ".join(sorted(не_кем)), кто,
                                      ", ".join(sorted(есть_роли)),
                                      профиль["второй взрослый"]),
                            "почему": "роль играть некому - это выяснится "
                                      "на площадке, а не при сборке плана"})
    out.sort(key=lambda f: (f["строки"], f["вид"]))
    return out


