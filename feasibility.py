def report(findings, profiles=None):
    if not findings:
        lines = ["✅ Невыполнимых строк не найдено."]
    else:
        lines = ["🔴 Строк, которые назначенный креатор снять не сможет: %d"
                 % len({f["строки"][0] for f in findings}), ""]
        for f in findings:
            lines.append("· [%s] %s" % (f["вид"], ", ".join(f["строки"])))
            lines.append("  %s" % f["что"])
            lines.append("  почему важно: %s" % f["почему"])
    # 🔴 Профиль со слов - не факт. Строить на нем план можно, выдавать за факт нельзя.
    if profiles:
        неподтвержденные = [имя for имя, p in profiles.items()
                            if "да" not in _norm(p.get("подтверждено", ""))]
        if неподтвержденные:
            lines += ["", "⚠️ Профили не подтверждены самими креаторами: %s. "
                          "Проверка идет по тому, что записано со слов."
                      % ", ".join(sorted(неподтвержденные))]
    lines += ["", LIMITS]
    return "\n".join(lines)


