# -*- coding: utf-8 -*-
"""Словарь механик - память петли.

**Зачем.** Без него петля меряет партию и забывает ее: когда партия кончится,
план следующей снова придется писать руками. Правило из процедуры петли §4.5
прямое: **вывод, не попавший в словарь, считается не сделанным.**

Считается из того, что уже собрано: `ПУБЛИКАЦИИ` дают механику каждого ролика,
`МЕТРИКИ` - репосты на 1000 и подписки. Ничего нового вводить не нужно.

Правила взяты из [ТЗ §4](../управление/ТЗ_ГЕНЕРАТОР_ПЛАНА.md), не выдуманы:

| Что | Значение |
|---|---|
| Минимум для решения | **4 ролика** с этой механикой |
| Подтверждена | медиана группы выше базовой на 20%+ |
| Опровергнута | ниже базовой на 20%+ |
| Иначе | «не решено», копим дальше |
| Выгорание | три применения **подряд** ниже базовой |

**Базовая медиана** - по всем замеренным роликам разом, а не среднее по механикам:
иначе одна многочисленная механика перетягивала бы точку отсчета на себя.

🔴 **Машина не трогает колонки человека.** «Статус решения» и «Дата снятия с плана» -
это решения владельца, и пересчет их не переписывает. Иначе петля начала бы молча
отменять его решения, а заметить это было бы нечем: цифры остались бы правильными.

🔴 **Выгорание не снимает механику с плана само.** Оно записывается в «Статус
по метрикам» и попадает во владельцеву сводку, а снимает - человек. Утверждение,
из-за которого вариант выбывает, требует его решения, даже когда посчитано верно.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

SHEET = "СЛОВАРЬ"
MIN_FOR_DECISION = 4          # ТЗ §4: меньше четырех - копим, а не решаем
SPREAD = 0.20                 # ТЗ §4: ±20% от базовой
BURNOUT_IN_A_ROW = 3          # ТЗ §4: три подряд вниз
# 🔴 Насколько глубоко должен просесть ряд, чтобы это был спад, а не шум.
# Замерено 28.08 на случайных рядах (логнормальное распределение, 2000 прогонов
# на каждый размер) - доля ложных ярлыков «выгорела» на ЧИСТОМ ШУМЕ:
#     старое правило «три подряд ниже общей базовой»: 10% при 20 роликах
#     это правило (вдвое ниже своей же медианы):      5,5% при 6 · 3,4% при 10 ·
#                                                      2,1% при 20 · 1,2% при 40
# При этом настоящий спад втрое ловится, а ряд, качающийся вокруг своей медианы,
# ярлыка не получает. Пересмотреть после второй партии, когда появится история.
BURNOUT_DROP = 0.50

# 🔴 «Ось» - первая колонка листа с 29.08. Без нее срезы по пяти осям
# слиплись бы в один список, и генератор поставил бы тему в план как прием.
COL_AXIS = "Ось"
COL_MECHANIC = "Механика"
# 🔴 Чему верить в осях ролика (А9, 29.08). Оси едут в ПУБЛИКАЦИИ из ПЛАНА,
# то есть описывают ЗАМЫСЕЛ. Креатор мог снять иначе - тогда словарь припишет
# результат ценности и товару, которых в кадре не было, и предложит повторять
# то, чего не делали. Ошибка не подает никаких признаков: цифры остаются
# правильными, неверна привязка.
COL_MATCH = "Соответствие"
MATCH_TRUSTED = ("по сцене", "сверено")   # «сверено» ставит владелец, поправив оси
MATCH_OFF = "отступил"
COL_COUNT = "Применений"
COL_MEDIAN = "Медиана репостов/1000"
COL_SUBS = "Подписки"
COL_METRIC_STATUS = "Статус по метрикам"
COL_VIDEOS = "На каких роликах"
# 🔴 Колонки человека. Список нужен целиком: он и есть граница между тем,
# что считает машина, и тем, что решает владелец.
HUMAN_COLUMNS = ("Статус решения", "Дата снятия с плана")


def median(values):
    """Медиана, а не среднее: одна вирусная выброска не должна красить механику."""
    xs = sorted(v for v in values if v is not None)
    if not xs:
        return None
    mid = len(xs) // 2
    if len(xs) % 2:
        return xs[mid]
    return (xs[mid - 1] + xs[mid]) / 2.0


def _number(value):
    """Число из ячейки таблицы. Google отдает и «1,5», и «1.5», и пустоту."""
    if value is None:
        return None
    text = str(value).strip().replace(",", ".").replace(" ", "").replace(" ", "")
    if not text:
        return None
    try:
        return float(text)
    except ValueError:
        return None


class НетОси(Exception):
    """Ось не найдена в листе ПУБЛИКАЦИИ.

    Молчать нельзя: пустой словарь одинаково выглядит как «по этой оси еще
    нечего считать» и как «колонка называется иначе, и мы посчитали воздух».
    """


# 🔴 Пять осей учета, решение владельца 29.08 (Ш2 в МОДЕЛЬ_КОНТЕНТА).
# До этого словарь считал по одной оси и умел ответить «прием папа дал 1,79»,
# но не «что именно сработало»: о чем ролик, каким товаром, для какой боли,
# какими словами. Расчет один и тот же, меняется только колонка группировки.
# «Роль товара» и «Ситуация» - 02.09: через месяц данных словарь сможет сам
# ответить, что дает товар в развязке против фона (проверка замера 26.08 на своих
# цифрах) и какие ситуации из методики выстреливают.
AXES = ("Механика", "Тема", "Товар", "Ценность", "Тип хука", "Сегмент",
        "Роль товара", "Ситуация")


def build(publications, measurements, axis=COL_MECHANIC):
    """Собирает словарь: {значение оси: {применений, медиана, подписки, ...}}.

    `axis` - по какой колонке ПУБЛИКАЦИЙ группировать. По умолчанию «Механика»:
    на ней стоит выбор приемов в генераторе, и менять это поведение молча нельзя.

    На входе - строки листов как есть. Возвращает готовые значения, не трогая
    таблицу: так расчет проверяется без сети и без листов.
    """
    if publications:
        # Ось ищем в первой строке: если колонки нет, дальше считать нечего.
        # Проверка стоит до цикла, иначе ошибка станет пустым результатом.
        if axis not in publications[0]:
            raise НетОси(u"в листе ПУБЛИКАЦИИ нет колонки «%s» (есть: %s)"
                         % (axis, u", ".join(sorted(k for k in publications[0]
                                                    if not k.startswith("_")))))
    # 🔴 У одного ролика в ПУБЛИКАЦИЯХ строка на каждую площадку. Без сведения
    # по ID каждое применение считалось бы дважды, и порог «4 ролика» брался бы
    # вдвое раньше, чем на самом деле.
    video = {}
    отступили, без_отметки = set(), set()
    for row in publications:
        vid = (row.get("ID") or "").strip()
        if not vid or vid in video:
            continue
        # 🔴 Отступивший ролик выбрасываем ДО счета, а не помечаем после:
        # иначе он войдет и в медиану, и в базу, и в подписки.
        отметка = (row.get(COL_MATCH) or "").strip().lower()
        if отметка == MATCH_OFF:
            отступили.add(vid)
            continue
        if COL_MATCH in row and отметка not in MATCH_TRUSTED:
            без_отметки.add(vid)
        video[vid] = {"механика": (row.get(axis) or "").strip(),
                      "дата": (row.get("Дата") or "").strip()}

    measured = {}
    for row in measurements:
        vid = (row.get("ID") or "").strip()
        rep = _number(row.get("Репосты/1000"))
        if vid and rep is not None:
            measured[vid] = {"репосты": rep, "подписки": _number(row.get("Подписки")) or 0}

    # ролик без замера решать не на чем - он в счет не идет
    pairs = [(vid, video[vid], measured[vid]) for vid in video if vid in measured]

    groups = {}
    for vid, info, m in pairs:
        groups.setdefault(info["механика"], []).append((vid, info["дата"], m))

    # 🔴 База - медиана ПО МЕДИАНАМ МЕХАНИК, а не по всем роликам подряд.
    # Приемка 28.08: на живых данных крупнейшая механика составляла 45% роликов,
    # поэтому «медиана по всем» была ее собственной медианой - механика
    # сравнивалась сама с собой и навсегда застревала в «не решено». Убрать ее
    # из счета: база 0,56 против 0,63, и три вердикта из семи менялись.
    # Считая по медианам механик, мы даем каждому приему один голос независимо
    # от того, сколько раз его сняли. Ровно это и требовалось: точка отсчета
    # не должна зависеть от объема производства.
    per_mech = []
    for mech, items in groups.items():
        if mech:
            per_mech.append(median([m["репосты"] for _, _, m in items]))
    base = median(per_mech)

    # 🔴 Вторая ступень метрики (ТЗ §3). Первая - гейт на репостах, по ней
    # принимаются решения. Вторая - подписки, метрика ПОБЕДЫ: их считают по всей
    # истории, а не по партии, потому что подписок единицы (94 на квартал,
    # из них 26 дал один ролик). Выбирать механики ими нельзя - можно только
    # сказать, что механика вдобавок растит базу.
    #
    # Считаем подписки НА РОЛИК: сумма по группе делится на число роликов.
    # Медиана тут не годится - у большинства роликов ноль, и медиана всегда ноль.
    per_mech_subs = []
    for mech, items in groups.items():
        if mech:
            per_mech_subs.append(sum(m["подписки"] for _, _, m in items) / len(items))
    subs_base = median(per_mech_subs)

    out = Result()
    # 🔴 Считаем, что потеряли по дороге. Мусор в одной ячейке молча выбрасывал
    # ролик: из четырех применений становилось три, и решение по механике
    # отменялось само - при том, что все выглядело исправным.
    out.dropped = {
        "без замера": sum(1 for vid in video if vid not in measured),
        "без механики": sum(1 for _, info, _ in pairs if not info["механика"]),
        # 🔴 Выброшенное обязано быть названо числом. Молча уменьшенное число
        # применений выглядит как «просто мало сняли», и решение по механике
        # отменяется само - тот же класс, что мусор в ячейке (приемка 28.08).
        "снято не по сцене": len([v for v in отступили if v in measured]),
        # Считается, но названо: до появления вопроса в форме такими будут все
        # ролики, и исключение остановило бы петлю целиком.
        "без отметки о съемке": len([v for v in без_отметки if v in measured]),
    }
    for mech, items in groups.items():
        if not mech:
            continue
        # порядок по дате публикации: выгорание - это «подряд во времени»,
        # а не «подряд в таблице». Строки лист отдает в порядке дописывания.
        items.sort(key=lambda x: (_as_date(x[1]), x[0]))
        reps = [m["репосты"] for _, _, m in items]
        subs = sum(m["подписки"] for _, _, m in items)
        out[mech] = {
            "применений": len(items),
            "медиана": median(reps),
            "подписки": int(subs),
            "на каких роликах": ", ".join(vid for vid, _, _ in items),
            "статус по метрикам": _status(len(items), median(reps), reps, base,
                                          subs / len(items), subs_base),
        }
    return out


class Result(dict):
    """Словарь механик плюс счет того, что не доехало.

    Отдельным классом, а не лишним ключом внутри: по этому объекту ходят циклом
    и генератор, и запись в лист, и служебный ключ там оказался бы механикой
    с именем «_потери».
    """
    dropped = {}


def _as_date(text):
    """Дата для сортировки. Строкой сравнивать нельзя.

    🔴 Лист правится руками, и в нем встречается русский формат ДД.ММ.ГГГГ.
    При сравнении строк «01.10.2026» вставало раньше «02.09.2026» - хронология
    ломалась, а выгорание, которое считается «подряд во времени», пропускалось
    молча. Нераспознанное отправляем в конец, а не в начало: неизвестная дата
    не должна притворяться самой ранней.
    """
    import datetime
    text = (text or "").strip()
    for fmt in ("%Y-%m-%d", "%d.%m.%Y", "%d/%m/%Y", "%Y/%m/%d"):
        try:
            return datetime.datetime.strptime(text[:10], fmt).date()
        except ValueError:
            continue
    return datetime.date.max


def _win_status(group_median, base, subs_per_video, subs_base):
    """Четыре статуса метрики победы (ТЗ §3).

    🔴 «При расхождении ступеней выбор не делается. Механика получает статус,
    а не приговор»: `растит раздачу` · `растит базу` · `и то и другое` · `ничего`.
    Ровно потому, что репостов сотни, а подписок единицы - на квартал 94, из них
    26 дал один ролик. Считать по ним нельзя, но и молчать о них нельзя.

    Порог для подписок тот же ±20%, что и для репостов. Он НЕ замерен отдельно:
    замерять не на чем, пока подписок такая горстка. Это назначенное правило,
    и оно ничего не решает - только называет, что видно.
    """
    раздача = bool(base) and group_median >= base * (1 + SPREAD)
    # ноль подписок у всех - тогда «растит базу» не про кого, и это честнее,
    # чем объявить растящими тех, у кого случайно оказалась одна
    база = bool(subs_base) and subs_per_video >= subs_base * (1 + SPREAD)
    if раздача and база:
        return "и то и другое"
    if раздача:
        return "растит раздачу"
    if база:
        return "растит базу"
    return "ничего"


def _status(count, group_median, reps_in_order, base,
            subs_per_video=0.0, subs_base=0.0):
    """Словами, что говорят цифры. Решение - за человеком, это только чтение."""
    if count < MIN_FOR_DECISION:
        return "копим, %d из %d" % (count, MIN_FOR_DECISION)
    if not base:
        # 🔴 Раньше при нулевой базе не было вердикта ни у кого, даже у втрое
        # лучшей механики, и это молчание было неотличимо от «данных мало».
        # Отказ обязан называть себя.
        return "не с чем сравнить: у всех механик нулевой показатель"
    verdict = "не решено"
    if group_median >= base * (1 + SPREAD):
        verdict = "подтверждена"
    elif group_median <= base * (1 - SPREAD):
        verdict = "опровергнута"
    # 🔴 Выгорание помечается только там, где механика НЕ опровергнута. Иначе
    # прием, который никогда не работал, получал бы ярлык «выгорела» - а это
    # про спад, а не про стабильно плохое. Владелец прочел бы «выгорела» как
    # «раньше работало» и стал бы ждать возврата того, чего не было.
    if verdict != "опровергнута" and _burned_out(reps_in_order):
        verdict += " · выгорела: последние %d ниже своей же медианы вдвое" % BURNOUT_IN_A_ROW
    # Вторая ступень идет РЯДОМ с вердиктом гейта, а не вместо него: решение
    # принимает гейт, статус победы только описывает.
    return verdict + " · " + _win_status(group_median, base, subs_per_video, subs_base)


def _burned_out(reps_in_order):
    """Спад внутри механики, а не случайное попадание ниже общей середины.

    🔴 Старое правило «три подряд ниже базовой» на чистом случайном шуме
    срабатывало в 10% прогонов (2000 прогонов, механика из 20 роликов), и на живых
    данных ярлык получила механика из 85 роликов с медианой 0,50 при базе 0,56 -
    просто чуть ниже середины. Ярлык уходил владельцу строкой «снимать с плана
    или нет - решение Ваше», то есть сокращенный выбор подавался из шума.

    Теперь сравниваем механику С САМОЙ СОБОЙ и требуем заметного падения:
    последние три ниже медианы ее прошлого не менее чем вдвое. Случайное
    колебание вокруг своей медианы такой порог не берет, а настоящий спад берет.
    """
    # Нужен хвост из трех и хотя бы двое «до»: на одном значении прошлого
    # медиана прошлого - это само это значение, и любой выброс читался бы спадом.
    if len(reps_in_order) < BURNOUT_IN_A_ROW + 2:
        return False
    tail = reps_in_order[-BURNOUT_IN_A_ROW:]
    before = reps_in_order[:-BURNOUT_IN_A_ROW]
    was = median(before)
    if not was:
        return False
    return all(r <= was * (1 - BURNOUT_DROP) for r in tail)


def write(sheet, data, axis=COL_MECHANIC):
    """Кладет посчитанное в лист, оставляя колонки человека нетронутыми.

    🔴 Строка опознается ПАРОЙ «ось + значение», а не одним значением. Иначе
    «папа» как прием и «папа» как товар слились бы в одну строку, а генератор,
    читающий лист, поставил бы ценность в план как прием - он не может знать,
    что это разные вещи.
    """
    have = {}
    for row in sheet.read():
        name = (row.get(COL_MECHANIC) or "").strip()
        if name:
            have[((row.get(COL_AXIS) or COL_MECHANIC).strip(), name)] = row

    for mech in sorted(data):
        d = data[mech]
        values = [(COL_COUNT, d["применений"]),
                  (COL_MEDIAN, round(d["медиана"], 2) if d["медиана"] is not None else ""),
                  (COL_SUBS, d["подписки"]),
                  (COL_METRIC_STATUS, d["статус по метрикам"]),
                  (COL_VIDEOS, d["на каких роликах"])]
        ключ = (axis, mech)
        if ключ in have:
            for column, value in values:
                sheet.set(have[ключ]["_row"], column, value)
        else:
            row = {COL_AXIS: axis, COL_MECHANIC: mech}
            row.update(dict(values))
            sheet.append(row)


def rebuild(book):
    """Пересчет целиком: три листа на входе, обновленный СЛОВАРЬ на выходе.

    🔴 Возвращает срез по «Механике» и только его: на нем стоит выбор приемов
    в генераторе. Остальные четыре оси пишутся в лист, но генератору не отдаются -
    иначе он поставил бы в план тему или ценность как прием.
    """
    pubs = book.sheet("ПУБЛИКАЦИИ").read()
    mets = book.sheet("МЕТРИКИ").read()
    sheet = book.sheet(SHEET)
    data = build(pubs, mets)
    write(sheet, data, axis=COL_MECHANIC)

    # Остальные оси - те же ролики, разрезанные иначе (Ш2, 29.08).
    # Колонки может не быть у старых публикаций: это переходный период,
    # а не поломка, поэтому пропускаем, но говорим об этом вслух в сводке.
    data.skipped_axes = []
    for axis in AXES:
        if axis == COL_MECHANIC:
            continue
        try:
            write(sheet, build(pubs, mets, axis=axis), axis=axis)
        except НетОси:
            data.skipped_axes.append(axis)
    return data


def summary(data):
    """Короткая сводка владельцу. Молчащий пересчет не отличить от несделанного."""
    if not data:
        return "словарь: считать пока нечего, замеров нет"
    lines = ["Словарь механик обновлен, строк: %d" % len(data)]
    for mech in sorted(data, key=lambda m: -(data[m]["медиана"] or 0)):
        d = data[mech]
        lines.append("· %s: %d прим., медиана %.2f, %s"
                     % (mech, d["применений"], d["медиана"] or 0, d["статус по метрикам"]))
    # 🔴 Что не доехало до счета. Молча потерянный ролик - это молча испорченное
    # решение по механике: из четырех применений становится три, и вердикт
    # отменяется сам, а выглядит это как «данных пока мало».
    lost = getattr(data, "dropped", {}) or {}
    if any(lost.get(k) for k in ("без замера", "без механики",
                                 "снято не по сцене", "без отметки о съемке")):
        lines.append("")
        if lost.get("без замера"):
            lines.append("⚠️ роликов без замера (пустая или нечисловая ячейка "
                         "«Репосты/1000»): %d" % lost["без замера"])
        if lost.get("без механики"):
            lines.append("⚠️ роликов без механики в ПУБЛИКАЦИЯХ, они выброшены "
                         "из счета: %d" % lost["без механики"])
        # 🔴 Два разных сообщения, а не одно: первое требует действия владельца
        # (поправить оси и поставить «сверено»), второе - действия с формой.
        if lost.get("снято не по сцене"):
            lines.append("⚠️ роликов снято НЕ ПО СЦЕНЕ, они выброшены из счета: %d. "
                         "Оси у них описывают замысел, а не кадр. Поправьте оси "
                         "в ПУБЛИКАЦИЯХ и поставьте «сверено» - тогда посчитаются."
                         % lost["снято не по сцене"])
        if lost.get("без отметки о съемке"):
            lines.append("⚠️ роликов БЕЗ ОТМЕТКИ, снято по сцене или нет: %d. "
                         "Они посчитаны, но верить их осям нельзя - креатор "
                         "не ответил на вопрос в форме." % lost["без отметки о съемке"])
    # 🔴 Ось, по которой не посчитали, обязана быть названа. Молчание тут
    # читается как «посчитано по всем пяти», а на деле срез не собран - и это
    # выяснится через партию, когда решение уже принято по одной механике.
    skipped = getattr(data, "skipped_axes", None) or []
    if skipped:
        lines.append("")
        lines.append("⚠️ Срезы не собраны по осям: %s. В ПУБЛИКАЦИЯХ нет таких "
                     "колонок - у роликов, снятых до 29.08, их и не будет."
                     % ", ".join(skipped))
    burnt = [m for m in data if "выгорела" in data[m]["статус по метрикам"]]
    if burnt:
        lines.append("")
        lines.append("Просели заметно и устойчиво: %s. Снимать с плана или нет - "
                     "решение Ваше." % ", ".join(burnt))
    return "\n".join(lines)


