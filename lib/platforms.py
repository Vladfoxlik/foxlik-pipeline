# -*- coding: utf-8 -*-
u"""Упаковка одного ролика под каждую площадку.

🔴 Зачем (31.08, требование владельца). До этого в ВК и Instagram уходил один
и тот же текст. На живом прогоне это стало видно: **в ВК ссылка кликается**,
а мы слали туда голый номер артикула - человек не мог перейти к товару.
**В Instagram ссылка не кликается** - и слать туда ссылку значит занимать
строку подписи мусором, который нельзя нажать.

Один ролик - один смысл, но упаковка у каждой сети своя:

| Площадка | Что получает | Почему |
|---|---|---|
| ВК | текст + **прямая ссылка** на карточку WB | ссылки кликаются |
| Instagram | текст + **артикул номером**, дубль в ленту профиля | ссылки не кликаются |
| YouTube | текст + ссылка + **заголовок** | Shorts без заголовка не публикуется |
| TikTok | текст + артикул | ссылки без верификации не кликаются |

Правила живут в `data/площадки.tsv` с источником у каждой строки: добавить
площадку или поменять лимит можно, не трогая код.
"""

import re

# Шаблон карточки товара на Wildberries. Проверен браузером 31.08: открывается
# «FOXLIK / Детский игровой развивающий световой стол песочница Алфавит».
# ⚠️ Проверять можно только глазами: на запрос из кода WB отвечает 498
# (защита от ботов), и «ссылка не работает» из такого ответа НЕ следует.
WB_URL = "https://www.wildberries.ru/catalog/%s/detail.aspx"

TITLE_LIMIT = 100          # заголовок YouTube Shorts

# Что писать там, где ссылка не кликается (Instagram, TikTok). Витрина в шапке
# профиля живая - замер 02.09: taplink.cc/myplayroom, кнопки «Интернет-магазин»,
# «Купить на WB», «Купить на Ozon».
ПОДСКАЗКА_БЕЗ_ССЫЛКИ = u"👆 Ссылка на магазин - в шапке профиля"


class НетПравил(Exception):
    u"""Аккаунт есть, а правил для его площадки нет. Молчать нельзя: пост уйдет
    с чужой упаковкой - со ссылкой туда, где ссылки не работают."""


class НетСсылки(Exception):
    u"""Площадке нужна ссылка, а в `data/mobzio.tsv` для этого товара ее нет.

    Подставить вместо нее прямую ссылку на WB - худший из вариантов: пост
    выглядит рабочим, но теряет и переход в приложение, и метку источника,
    а видно это станет через месяц по пустой аналитике.
    """


def read_links(stream):
    u"""Ссылки Mobzio из TSV: {(товар, площадка, маркетплейс): url}.

    🔴 Маркетплейс в ключе с 02.09: у одной площадки их два - WB и Ozon,
    и без него словарь молча схлопнул бы вторую ссылку в первую.

    🔴 Хранятся ПОЛНЫЕ адреса, а не шаблон «артикул + суффикс». Замер 02.09:
    у каждого товара свой регистр суффикса - `43287163vk`, но `43287165tG`,
    `79693129vkS`, `150827738Tg`. Шаблон сгенерировал бы мертвые ссылки,
    причем страница по ним открывается (200) - это главная Мобзио, а не товар.
    """
    rows = [line.rstrip("\n").split("\t") for line in stream if line.strip()]
    head = [c.strip() for c in rows[0]]
    out = {}
    for raw in rows[1:]:
        item = dict(zip(head, [c.strip() for c in raw]))
        товар = (item.get(u"Товар") or "").strip().lower()
        площадка = (item.get(u"Площадка") or "").strip().lower()
        магазин = (item.get(u"Маркетплейс") or "WB").strip().lower()
        ссылка = (item.get(u"Ссылка") or "").strip()
        if товар and площадка and ссылка:
            out[(товар, площадка, магазин)] = ссылка
    return out


def read_hashtags(stream):
    u"""Хештеги по товару из TSV: {товар: [#тег, ...]}. Пустой товар - ролик без товара."""
    rows = [line.rstrip("\n").split("\t") for line in stream if line.strip()]
    head = [c.strip() for c in rows[0]]
    out = {}
    for raw in rows[1:]:
        item = dict(zip(head, [c.strip() for c in raw] + [""] * len(head)))
        теги = [t for t in (item.get(u"Хештеги") or "").split() if t.startswith("#")]
        if теги:
            out[(item.get(u"Товар") or "").strip().lower()] = теги
    return out


def read_rules(stream):
    u"""Правила площадок из TSV. Ключ - chanel_id (число, как в API сервиса)."""
    rows = [line.rstrip("\n").split("\t") for line in stream if line.strip()]
    head = [c.strip() for c in rows[0]]
    out = {}
    for raw in rows[1:]:
        item = dict(zip(head, [c.strip() for c in raw]))
        try:
            канал = int(item.get("chanel_id") or 0)
        except ValueError:
            continue
        if not канал:
            continue
        out[канал] = {
            "площадка": item.get("Площадка", ""),
            "ссылка": (item.get("Ссылка кликабельна", "") or "").lower().startswith("да"),
            "лимит": _int(item.get("Лимит текста"), 100000),
            "тегов": _int(item.get("Хештегов максимум"), 30),
            "добавлять": (item.get("Что добавлять к тексту") or "").strip(),
            "поля": _fields(item.get("Поля публикации")),
            "заголовок": (item.get("Заголовок нужен", "") or "").lower().startswith("да"),
            "источник": item.get("Источник", ""),
        }
    return out


def _int(value, default):
    try:
        return int(str(value).strip())
    except (TypeError, ValueError):
        return default


def _fields(text):
    u"""«youtube_privacy_status=1,tiktok_comment=true» -> {поле: значение}."""
    out = {}
    for кусок in (text or "").split(","):
        if "=" not in кусок:
            continue
        имя, значение = кусок.split("=", 1)
        имя, значение = имя.strip(), значение.strip().lower()
        if not имя:
            continue
        if значение in ("true", "да"):
            out[имя] = True
        elif значение in ("false", "нет"):
            out[имя] = False
        else:
            out[имя] = _int(значение, значение)
    return out


def details(accounts, text, артикул, file_ids, rules, publication_type=4,
            ozon=None, links=None, товар=None, strict_links=False, hashtags=None):
    u"""Детали публикации: по одной на аккаунт, каждая упакована по своим правилам.

    `links` и `товар` включают ссылки Mobzio (решение владельца 02.09): короткая
    ссылка открывает товар в приложении маркетплейса, где человек уже авторизован,
    и метит источник перехода. `ozon` - артикул Ozon, ставится вместе с WB.
    `strict_links=True` требует ссылку там, где площадка ее принимает.
    """
    out = []
    if артикул:
        text = _без_ручного_артикула(text)
    for acc in accounts:
        канал = acc.get("chanel_id")
        правило = rules.get(канал)
        if правило is None:
            raise НетПравил(
                u"аккаунт %s (канал %s) не описан в data/площадки.tsv - "
                u"непонятно, как упаковывать пост" % (acc.get("id"), канал))
        ссылка = _link_for(links, товар, правило, strict_links)
        ссылка_ozon = _link_for(links, товар, правило, strict_links, магазин="ozon")
        деталь = {"publication_type": publication_type,
                  "account_id": acc.get("id"),
                  "file_ids": list(file_ids),
                  "content": _text_for(text, артикул, правило,
                                       ozon=ozon, ссылка=ссылка,
                                       ссылка_ozon=ссылка_ozon,
                                       есть_справочник=links is not None,
                                       теги=_tags_for(hashtags, товар, правило))}
        деталь.update(правило["поля"])
        if правило["заголовок"]:
            деталь["title"] = _title(text)
        out.append(деталь)
    return out


def _link_for(links, товар, правило, strict, магазин="wb"):
    u"""Ссылка Mobzio для этой площадки и маркетплейса, если она там нужна."""
    if links is None or правило["добавлять"] != "ссылка":
        return None
    ключ = ((товар or "").strip().lower(),
            (правило["площадка"] or "").strip().lower(), магазин)
    ссылка = links.get(ключ)
    if ссылка is None and strict and магазин == "wb":
        raise НетСсылки(
            u"для товара «%s» нет ссылки Mobzio на площадку «%s» - заведите ее "
            u"в кабинете foxlik.mobz.link и допишите в data/mobzio.tsv"
            % (товар or u"?", правило["площадка"]))
    return ссылка


def _без_ручного_артикула(text):
    u"""Убрать строки «🛒 Артикул ...», вписанные в описание руками: хвост ставит машина.

    🔴 Замер 27.09 на живом W39-10: такая строка из плана плюс машинный хвост дали
    номер дважды, причем с решеткой - Instagram делает из нее ссылку на хештег.
    Гейт заливки плана (setup.do_plan_replace) это ловит, но W39 залит в обход него.
    """
    строки = [s for s in text.split("\n")
              if not (s.strip().startswith(u"🛒") and u"ртикул" in s)]
    return re.sub(r"\n{3,}", "\n\n", "\n".join(строки)).strip()


def _tags_for(hashtags, товар, правило):
    u"""Хештеги строки - только там, где правило площадки их просит (TikTok, 27.09)."""
    if not hashtags or u"хештеги" not in правило["добавлять"]:
        return []
    return hashtags.get((товар or "").strip().lower(), [])[:правило.get("тегов", 30)]


# 🔴 Слова владельца 27.09 для TikTok: «заказать выгодно на сайте FOXLIK.RU либо
# на wb и артикул». Ссылки там не кликаются, поля «Сайт» в профиле нет.
САЙТ = u"🛒 Заказать выгодно на сайте FOXLIK.RU"
# 🔴 Слова владельца 29.09 для Instagram: «артикул WB + сайт, заказывайте со скидкой
# на сайте FOXLIK.RU». Ozon и подсказка про шапку профиля там больше не ставятся.
САЙТ_ПО_ПЛОЩАДКЕ = {u"instagram": u"🛒 Заказывайте со скидкой на сайте FOXLIK.RU"}


def _text_for(text, артикул, правило, ozon=None, ссылка=None, ссылка_ozon=None,
              есть_справочник=False, теги=()):
    u"""Текст под площадку: ссылка там, где она кликается, номер - где нет."""
    if u"сайт" in правило["добавлять"]:
        сайт = САЙТ_ПО_ПЛОЩАДКЕ.get((правило["площадка"] or u"").strip().lower(), САЙТ)
        хвост = сайт + (u"\nили на WB, артикул %s" % артикул if артикул else u"")
        if теги:
            хвост += u"\n\n" + u" ".join(теги)
        return _fit(text, хвост, правило["лимит"])
    хвост = ""
    if артикул:
        if правило["добавлять"] == "ссылка":
            if ссылка:
                хвост = u"🛒 Смотреть на WB: %s" % ссылка
            elif not есть_справочник:
                # переходный режим: справочник ссылок не передан вовсе.
                хвост = WB_URL % артикул
            # 🔴 Справочник есть, а ссылки для этого товара в нем нет - хвоста
            # не будет. Прямая ссылка тут хуже пустоты: пост выглядит рабочим,
            # но теряет переход в приложение и метку источника.
        elif правило["добавлять"] == "артикул":
            # 🔴 БЕЗ решетки. Замер живого поста 02.09: «#43287163» Instagram
            # превращает в ссылку на страницу хештега (/explore/tags/43287163/).
            # Человек жмет на артикул и уходит в поиск Instagram, а не к товару -
            # то есть номер выглядит рабочим и уводит в пустоту. Голый номер
            # остается текстом: его копируют и ищут в приложении маркетплейса.
            хвост = u"🛒 Артикул на WB: %s" % артикул
    # Ozon: там, где ссылка кликается, - ссылкой; где нет - номером. Номер
    # вместо рабочей ссылки перекладывает поиск товара на человека (02.09).
    хвост_ozon = u""
    if ссылка_ozon and правило["ссылка"]:
        хвост_ozon = u"🛒 Смотреть на Ozon: %s" % ссылка_ozon
    elif ozon and (правило["добавлять"] == "артикул" or not ссылка_ozon):
        хвост_ozon = u"🛒 Артикул на Ozon: %s" % ozon
    if хвост_ozon:
        хвост = (хвост + u"\n" if хвост else u"") + хвост_ozon
    # Там, где ссылка не кликается, человеку говорят, где ее взять. Иначе
    # единственный путь к товару - переписать номер руками (замер 02.09:
    # в шапке профиля стоит витрина taplink с кнопками «Купить на WB / Ozon»).
    if хвост and not правило["ссылка"]:
        хвост += u"\n" + ПОДСКАЗКА_БЕЗ_ССЫЛКИ
    return _fit(text, хвост, правило["лимит"])


def _fit(text, хвост, лимит):
    u"""Текст и хвост в предел площадки: режем текст, хвост сохраняем."""
    целиком = (text.strip() + ("\n\n" + хвост if хвост else "")).strip()
    if len(целиком) <= лимит:
        return целиком
    # 🔴 Режем МЫ, а не площадка: она обрежет по своему усмотрению и может
    # оставить пост без хвоста со ссылкой. Хвост сохраняем, режем начало.
    склейка = u"...\n\n" if хвост else u"..."
    место = лимит - len(хвост) - len(склейка)
    итог = (text.strip()[:max(место, 0)].rstrip() + склейка + хвост).strip()
    return итог[:лимит]


def _title(text):
    u"""Заголовок Shorts: первая фраза текста, не длиннее предела площадки."""
    первая = text.strip().split(".")[0].strip() or text.strip()
    return первая[:TITLE_LIMIT].rstrip()


