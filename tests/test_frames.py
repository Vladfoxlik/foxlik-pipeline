def selftest():
    ценности = Gr.read_values(io.StringIO(ЦЕННОСТИ))
    товары = Gr.read_goods(io.StringIO(ТОВАРЫ))
    сегменты = Gr.read_segments(io.StringIO(СЕГМЕНТЫ))
    темы = G.read_themes(io.StringIO(ТЕМЫ))
    профили = F.read_profiles(io.StringIO(ПРОФИЛИ))
    # 🔴 У двух гейтов свои читатели профилей: feasibility держит детей
    # словарями, grounding - парами. Это не дубль, а разные нужды.
    гр_профили = Gr.read_profiles(io.StringIO(ПРОФИЛИ))

    # --- 1. справочник тем читается ---
    assert set(темы) == {"А1", "А3", "А4", "Б11", "В13"}, темы
    assert темы["В13"]["сегмент"] == "даритель", темы["В13"]

    # --- 2. допустимые сочетания для конкретного ребенка ---
    # У Спартака дочь 11 месяцев и только планшет. Значит:
    # «занят сам» (от 24) - нельзя · «читающий ребенок» (от 18) - нельзя ·
    # «анти-гаджет» - у планшета в справочнике товаров НЕТ · остается одно.
    свои = G.allowed(профили["Спартак"], ценности, товары, "световой планшет")
    имена = {c["ценность"] for c in свои}
    assert имена == {"занят вместе со взрослым"}, имена
    assert свои[0]["ребенок"] == "дочь", свои[0]

    # --- 3. 🔴 «создание спроса» и «не проверено» в каркас не идут ---
    # Владелец вправе создавать спрос, но опорой строки такая ценность быть
    # не может - это правило раздела 3, и генератор обязан знать его сам.
    все = G.allowed(профили["Ксения"], ценности, товары, "световой стол")
    assert "осанка" not in {c["ценность"] for c in все}, все

    # --- 4. возраст берется по ТОМУ ребенку, кто в кадре ---
    # У Ксении двое. «Занят сам» доступна только через дочь 48 мес.
    занят = [c for c in все if c["ценность"] == "занят сам"]
    assert занят and all(c["ребенок"] == "дочь" for c in занят), занят

    # --- 5. 🔴 каркас проходит гейты С НУЛЯ находок ---
    # Это и есть смысл файла. Если тут появятся находки, значит генератор
    # снова оставил работу гейтам, а гейты - человеку.
    каркас = G.frames(профили, ценности, товары, сегменты, темы,
                      "Г2 папа", 8, "2026-09-04")
    assert len(каркас) == 8, len(каркас)

    невыполнимые = F.check(каркас, профили)
    assert not невыполнимые, "каркас обязан быть снимаемым: %s" % невыполнимые

    необоснованные = [f for f in Gr.check(каркас, ценности, гр_профили, товары, сегменты)
                      if f["вид"] not in ("ценность с запретом",)]
    assert not необоснованные, "каркас обязан быть обоснованным: %s" % необоснованные

    # --- 6. содержание НЕ выдумывается ---
    for r in каркас:
        assert not r["Что в кадре"], "кадр обязан остаться человеку: %s" % r
        assert not r["Хук"] and not r["Текст на экране"], r
        assert r["Ценность"] and r["Товар"] and r["Тема"] and r["Сегмент"], \
            "а вот оси машина заполняет сама: %s" % r

    # --- 7. креаторы перемешаны, а не идут блоками ---
    подряд = G.longest_run([r["Креатор"] for r in каркас])
    assert подряд <= 2, "один креатор %d дней подряд - это уже про него, а не про прием" % подряд

    # --- 7б. 🔴 каркас обязан ПОКРЫВАТЬ оси, а не повторять одно ---
    # Первый рабочий каркас 29.08 прошел оба гейта и был при этом никуда не
    # годен: все пятнадцать строк с темой А1, полка не задействована ни разу,
    # сегмент один. Гейты этого не ловят - они запрещают неверное, а не требуют
    # разного. Значит требование покрытия живет здесь.
    большой = G.frames(профили, ценности, товары, сегменты, темы,
                       "Г2 папа", 12, "2026-09-04")
    ценности_в = {r["Ценность"] for r in большой}
    assert len(ценности_в) >= 3, "на 12 строк нужно хотя бы три ценности: %s" % ценности_в
    товары_в = {r["Товар"] for r in большой}
    assert len(товары_в) >= 3, "полка есть у креатора - она обязана попасть: %s" % товары_в
    темы_в = {r["Тема"] for r in большой}
    assert len(темы_в) >= 2, "одна тема на всю партию - это не план: %s" % темы_в

    # ...и ни одна ось не занимает больше половины партии
    from collections import Counter
    for ось in ("Ценность", "Товар", "Тема"):
        сколько = Counter(r[ось] for r in большой).most_common(1)[0]
        assert сколько[1] <= len(большой) // 2,             "«%s» занимает %d из %d по оси %s" % (сколько[0], сколько[1], len(большой), ось)

    # --- 7б. 🔴 каркас называет, КТО ИЗ ВЗРОСЛЫХ в кадре (А9, 30.08) ---
    # Найдено на живых данных: карточка креатору собиралась из справочника,
    # где у Ксении «Кто в кадре» = мама (обычно снимает она). Партия целиком
    # проверяет прием «папа», в кадре обязан быть мужчина - у нее это муж.
    # Задание сообщало «в кадре мама», то есть отменяло проверяемую гипотезу.
    # Догадаться по механике можно, и поэтому нельзя: догадка в задании
    # неотличима от требования, а замер молча мерит не то.
    for r in большой:
        assert r.get("Взрослый в кадре"), (
            "каркас не сказал, кто из взрослых в кадре: %s" % r)
    ксения = [r for r in большой if r["Креатор"] == "Ксения"]
    if ксения:
        assert all(r["Взрослый в кадре"] != "мама" for r in ксения), (
            "прием «папа», а в кадре мама: %s" % ксения[0])

    # --- 7в. 🔴 тема сверяется с тем, кто снимает и сколько ребенку (30.08) ---
    # Найдено на сгенерированном каркасе: генератор ставил Спартаку тему
    # «производство» - ЧПУ-фрезеровка и завод, снять это дома невозможно;
    # и тему «осанка» под 11-месячную, которая еще не сидит за столом.
    # Тема выбиралась по сегменту и не сверялась ни с возрастом, ни с тем,
    # кто вообще может это снять. Гейты такого не ловят: строка не запрещена,
    # она бессмысленна.
    темы_все = G.read_themes(io.StringIO(ТЕМЫ))
    каркас2 = G.frames(профили, ценности, товары, сегменты, темы_все,
                       "Г2 папа", 10, "2026-09-22")
    коды = {r["Тема"] for r in каркас2}
    assert "Б11" not in коды, "тему для съемки на заводе отдали креатору: %s" % коды
    for r in каркас2:
        if r["Тема"] == "А4":               # осанка - от 36 месяцев
            дети = dict((к, в) for к, в in гр_профили[r["Креатор"]])
            возраст = дети.get(r["Ребенок в кадре"])
            assert возраст is None or возраст >= 36, (
                "тема «осанка» отдана ребенку %s мес.: %s" % (возраст, r))

    # --- 7г. 🔴 сегмент без своих тем не берется вовсе (30.08) ---
    # Найдено на живом каркасе: единственная тема сегмента «специалист» (А6)
    # отсеклась как несъемная, сегмент остался без тем - и получил чужие.
    # В плане появились строки «специалист + ни минуты себе»: логопеду
    # адресован ролик про мамину усталость. Строка не запрещена, она мимо.
    без_тем = dict(сегменты)
    без_тем["логопед"] = {"кто": "специалист", "вес": "узкий",
                          "боль": "запуск речи", "ценно": "", "осторожно": ""}
    к = G.frames(профили, ценности, товары, без_тем, темы_все, "Г2 папа", 10,
                 "2026-09-22")
    assert "логопед" not in {r["Сегмент"] for r in к}, (
        "сегменту без единой своей темы отдали чужие: %s"
        % [(r["Сегмент"], r["Тема"]) for r in к])

    # --- 7д. 🔴 второй взрослый занят не чаще, чем он согласился (30.08) ---
    # Замер на живом плане: партия целиком на приеме «папа», у Ксении в кадре
    # обязан быть муж - и таких строк вышло девять за две недели. Муж не
    # сотрудник, его согласия никто не спрашивал. Решение владельца 30.08:
    # ставить его в план раз в неделю и смотреть на реакцию.
    # Ограничение стоит на ВХОДЕ: генератор физически не может назначить чаще,
    # вместо того чтобы гейт ловил это на выходе, а человек переписывал план.
    с_лимитом = F.read_profiles(io.StringIO(ПРОФИЛИ_С_ЛИМИТОМ))
    assert с_лимитом["Ксения"]["второй взрослый в неделю"] == 1, с_лимитом["Ксения"]
    assert с_лимитом["Спартак"]["второй взрослый в неделю"] is None, с_лимитом["Спартак"]

    длинный = G.frames(с_лимитом, ценности, товары, сегменты, темы_все,
                       "Г2 папа", 15, "2026-09-04")
    ксенины = sorted(r["Дата в эфир"] for r in длинный if r["Креатор"] == "Ксения")
    assert ксенины, "Ксения обязана остаться в партии, а не выпасть целиком"
    import datetime as _dt
    for пред, след in zip(ксенины, ксенины[1:]):
        разрыв = (_dt.date(*map(int, след.split("-")))
                  - _dt.date(*map(int, пред.split("-")))).days
        assert разрыв >= 7, (
            "муж занят дважды за неделю: %s и %s (%d дней)" % (пред, след, разрыв))
    assert len(ксенины) <= 3, (
        "на 15 дней при «раз в неделю» больше трех съемок не выходит: %s" % ксенины)

    # ...а сам лимит доказуемо работает: без него строк Ксении заметно больше.
    # 🔴 Тишина не подтверждение: без этой пары прогонов «3 строки» одинаково
    # значило бы «лимит сработал» и «столько и было бы без него».
    без_лимита = G.frames(профили, ценности, товары, сегменты, темы_все,
                          "Г2 папа", 15, "2026-09-04")
    сколько_без = len([r for r in без_лимита if r["Креатор"] == "Ксения"])
    assert сколько_без > len(ксенины), (
        "проверка ничего не доказывает: без лимита тоже %d строк" % сколько_без)

    # --- 7е. 🔴 роликов у креаторов поровну (решение владельца 30.08) ---
    # Замер, из-за которого правило появилось: с лимитом второго взрослого
    # освободившиеся дни уходили тому, у кого лимита нет, и партия вышла
    # 13 строк Спартаку против 2 Ксении. Это не только несправедливо по
    # деньгам (ставка платится за ролик) - это меряет уже не прием, а одного
    # человека: 13 роликов одной семьи с одним товаром.
    # Значит размер партии задает САМЫЙ ОГРАНИЧЕННЫЙ креатор, а size - потолок.
    from collections import Counter as _C
    доли = _C(r["Креатор"] for r in длинный)
    assert len(set(доли.values())) == 1, (
        "роликов у креаторов поровну не вышло: %s" % dict(доли))
    assert set(доли) == {"Ксения", "Спартак"}, (
        "равенство не должно достигаться выбрасыванием креатора: %s" % dict(доли))
    assert len(длинный) == len(ксенины) * 2, (
        "партию задает самый ограниченный: %d строк при %d съемках Ксении"
        % (len(длинный), len(ксенины)))

    # ...и при равных долях чередование возвращается - это его же требование
    assert G.longest_run([r["Креатор"] for r in длинный]) <= 2, длинный

    # ...а потолок size продолжает работать: просят меньше - дают меньше
    короткий = G.frames(с_лимитом, ценности, товары, сегменты, темы_все,
                        "Г2 папа", 4, "2026-09-04")
    assert len(короткий) <= 4, len(короткий)
    доли_к = _C(r["Креатор"] for r in короткий)
    assert len(set(доли_к.values())) == 1, dict(доли_к)

    # --- 8. 🔴 доказательство, что сборка вообще способна отказать ---
