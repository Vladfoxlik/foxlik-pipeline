# -*- coding: utf-8 -*-
"""Проверка разведки чужих залетов.

🔴 Главное, что здесь проверяется, - **предохранитель на расход**. Квота чужая
(правило от 25.08: чужие токены и сервисы не тратим без сметы), и прогон,
который молча вылезет за остаток, - это ровно тот класс отказов, который
выглядит как успех.

Сеть в проверках не нужна: считаем на подставных числах.
"""
import io
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import scout as S  # noqa: E402


def selftest():
    # --- 1. расход считается ДО запуска ---
    # 🔴 Ставка уточнена сверкой 29.08: мгновенный замер после прогона давал
    # $0.0019-0.0026 за запись, а квота за сессию упала на $0.32 при 74 записях -
    # втрое больше. Apify начисляет с задержкой, и «дешево» было измерено неверно.
    ок, нужно = S.affordable(остаток=4.55, items=240)
    assert ок, "240 записей по $0.0045 - это $1.08, должно влезать в $4.55"
    assert abs(нужно - 1.08) < 0.01, нужно

    # --- 2. 🔴 прогон, который не влезает, не запускается ---
    ок, нужно = S.affordable(остаток=0.60, items=1000)
    assert not ок, "$4.50 при остатке $0.60 - запускать нельзя"

    # --- 3. 🔴 запас не тратится ---
    # Ровно впритык - тоже отказ: последние центы квоты оставляем нетронутыми,
    # иначе следующий срочный прогон упрется в ноль.
    ок, _ = S.affordable(остаток=1.30, items=200)     # нужно $0.90, запас $0.50
    assert not ок, "впритык к остатку запускать нельзя, есть запас"
    ок, _ = S.affordable(остаток=1.60, items=200)
    assert ок, "$0.90 при остатке $1.60 - влезает с запасом"

    # --- 4. список источников: выключенные строки не берутся ---
    src = io.StringIO(
        "Аккаунт\tЗачем\tБерем\n"
        "@detsky_stul\tпрямой конкурент\tда\n"
        "@sandart_obelmaz\tпесок без хука\tнет\n"
        "@clevrika\tэталон ниши\tда\n")
    import tempfile
    import os
    with tempfile.NamedTemporaryFile("w", suffix=".tsv", delete=False,
                                     encoding="utf-8") as f:
        f.write(src.getvalue())
        path = f.name
    try:
        got = S.read_sources(path)
        assert [s["Аккаунт"] for s in got] == ["@detsky_stul", "@clevrika"], got
    finally:
        os.unlink(path)

    # --- 5. разбор выдачи: берем videoPlayCount, а не videoViewCount ---
    # Записано в CLAUDE.md по итогам прошлых прогонов: viewCount врет.
    rows = S.digest([{"ownerUsername": "detsky_stul", "url": "u1",
                      "timestamp": "2026-08-01T10:00:00.000Z",
                      "videoPlayCount": 142595, "videoViewCount": 7,
                      "likesCount": 900, "commentsCount": 12,
                      "caption": "текст\tс табом\nи переносом"}])
    assert rows[0]["просмотры"] == 142595, rows[0]
    assert "\t" not in rows[0]["текст"] and "\n" not in rows[0]["текст"], \
        "таб или перенос в тексте развалили бы TSV"

    # --- 5б. 🔴 фото и карусели не идут в счет ---
    # Живой случай 29.08: у @detsky_stul 18 записей из 20 имели ноль просмотров -
    # это были фото, у которых videoPlayCount не заполняется в принципе.
    # Медиана по такой выдаче дала бы ноль и вывод «у конкурента не смотрят».
    смесь = [{"type": "Video", "productType": "clips", "videoPlayCount": 43561,
              "ownerUsername": "clevrika"},
             {"type": "Sidecar", "videoPlayCount": 0, "ownerUsername": "clevrika"},
             {"type": "Image", "videoPlayCount": 0, "ownerUsername": "clevrika"}]
    assert len(S.digest(смесь)) == 3, "без фильтра берем все"
    только = S.digest(смесь, only_video=True)
    assert len(только) == 1, только
    assert только[0]["тип"] == "клип", только

    # --- 6. мусор в выдаче не роняет разбор ---
    мусор = S.digest([None, "строка", {}])
    assert len(мусор) == 1 and мусор[0]["просмотры"] == 0, мусор

    # --- 7. 🔴 рамка записана в самом модуле ---
    # Репостов Apify по чужим не отдает, и это не мелочь: наша метрика победы -
    # репосты. Если рамка «гипотезы, а не выводы» потеряется, кто-нибудь начнет
    # принимать решения по чужим просмотрам.
    assert "репост" in S.__doc__.lower(), "ограничение обязано быть в шапке модуля"
    assert "гипотез" in S.__doc__.lower()

    print("scout selftest OK: расход считается до запуска, невлезающий прогон "
          "отклонен, запас не тратится, выключенные источники не берутся, "
          "videoPlayCount вместо viewCount, мусор не роняет, рамка записана")


if __name__ == "__main__":
    selftest()
