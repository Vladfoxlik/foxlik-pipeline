# -*- coding: utf-8 -*-
"""Проверка словаря механик - памяти петли.

Правила взяты из ТЗ §4, а не выдуманы: минимум **4 ролика** для решения ·
подтверждена при медиане выше базовой на 20%+ · опровергнута при ниже на 20%+ ·
иначе «не решено» · выгорание - три применения подряд ниже базовой.

🔴 Главное, что здесь проверяется: **машина не трогает колонки человека.**
«Статус решения» и «Дата снятия с плана» - это решения владельца. Если пересчет
будет их затирать, петля начнет молча отменять его решения, и заметить это будет
нечем: цифры-то останутся правильными.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import dictionary as D  # noqa: E402


class FakeSheet:
    """Лист таблицы на словарях. Помнит, что именно в него писали."""

    def __init__(self, header, rows=()):
        self.header = list(header)
        self.rows = [dict(r) for r in rows]
        for i, r in enumerate(self.rows):
            r.setdefault("_row", i + 2)
        self.appended = []
        self.writes = []

    def read(self):
        return [dict(r) for r in self.rows]

    def append(self, values):
        self.appended.append(dict(values))
        row = dict(values)
        row["_row"] = len(self.rows) + 2
        self.rows.append(row)

    def set(self, row, column, value):
        self.writes.append((row, column, value))
        for r in self.rows:
            if r["_row"] == row:
                r[column] = value

    def set_many(self, row, pairs):
        for column, value in pairs:
            self.set(row, column, value)


def pubs_sheet(items, match="по сцене"):
    """ПУБЛИКАЦИИ: у одного ролика СТРОКА НА КАЖДУЮ ПЛОЩАДКУ.

    `match` - что стоит в колонке «Соответствие» у всех строк. По умолчанию
    «по сцене»: старые проверки написаны про счет, а не про доверие к разметке,
    и подкладывать им неподтвержденное значило бы менять их предмет.
    """
    rows = []
    for item in items:
        vid, mech, date = item[0], item[1], item[2]
        own = item[3] if len(item) > 3 else match
        for platform in ("instagram", "vk"):
            rows.append({"ID": vid, "Механика": mech, "Дата": date,
                         "Площадка": platform, "Креатор": "Ксения",
                         "Соответствие": own})
    return FakeSheet(["ID", "Дата", "Площадка", "Ссылка", "Медиа ID",
                      "Креатор", "Механика", "Соответствие", "Длина", "Разрешение"],
                     rows)


def metrics_sheet(items):
    rows = [{"ID": vid, "Репосты/1000": rep, "Подписки": subs, "Дата замера": "2026-09-11"}
            for vid, rep, subs in items]
    return FakeSheet(["ID", "Дата замера", "Просмотры", "Охват", "Репосты",
                      "Репосты/1000", "Сохранения", "Комментарии", "Подписки",
                      "Вердикт", "Пропуск первых 3 сек", "Среднее время"], rows)


def dict_sheet(rows=()):
    return FakeSheet(["Механика", "Применений", "Медиана репостов/1000", "Подписки",
                      "Статус решения", "Статус по метрикам", "На каких роликах",
                      "Дата снятия с плана"], rows)


def selftest():
    # --- 1. медиана считается честно, на четном и нечетном числе ---
    assert D.median([1.0]) == 1.0
    assert D.median([1.0, 3.0]) == 2.0
    assert D.median([1.0, 2.0, 9.0]) == 2.0
    assert D.median([]) is None

    # --- 2. одна публикация на двух площадках - это ОДИН ролик ---
    # Иначе каждое применение считалось бы дважды, и порог «4 ролика»
    # брался бы вдвое раньше, чем на самом деле.
    pubs = pubs_sheet([("P1-01", "папа", "2026-09-04")])
    mets = metrics_sheet([("P1-01", 2.0, 5)])
    out = D.build(pubs.read(), mets.read())
    assert out["папа"]["применений"] == 1, out["папа"]

    # --- 3. ролик без замера в счет не идет ---
    pubs = pubs_sheet([("P1-01", "папа", "2026-09-04"), ("P1-02", "папа", "2026-09-05")])
    mets = metrics_sheet([("P1-01", 2.0, 5)])
    out = D.build(pubs.read(), mets.read())
    assert out["папа"]["применений"] == 1, "замера нет - решать не на чем"

    # --- 4. меньше четырех применений - копим, а не решаем ---
    assert "копим" in out["папа"]["статус по метрикам"]
    assert "1 из 4" in out["папа"]["статус по метрикам"], out["папа"]

    # --- 5. подтверждение и опровержение относительно БАЗОВОЙ медианы ---
    # базовая - медиана всех замеренных роликов, а не среднее по механикам
    items, mrows = [], []
    for i, rep in enumerate([3.0, 3.0, 3.0, 3.0], 1):        # «папа» - сильно выше
        items.append(("A%d" % i, "папа", "2026-09-0%d" % i)); mrows.append(("A%d" % i, rep, 2))
    for i, rep in enumerate([0.2, 0.2, 0.2, 0.2], 1):        # «название» - сильно ниже
        items.append(("B%d" % i, "название", "2026-09-0%d" % i)); mrows.append(("B%d" % i, rep, 0))
    for i, rep in enumerate([1.0, 1.0, 1.0, 1.0], 1):        # «вопрос» - ровно базовая
        items.append(("C%d" % i, "вопрос", "2026-09-0%d" % i)); mrows.append(("C%d" % i, rep, 1))
    out = D.build(pubs_sheet(items).read(), metrics_sheet(mrows).read())
    # 🔴 к вердикту гейта теперь приписана вторая ступень (ТЗ §3) -
    # сравниваем началом строки, а не целиком
    assert out["папа"]["статус по метрикам"].startswith("подтверждена"), out["папа"]
    # 🔴 «опровергнута» и без пометки выгорания: прием, который никогда
    # не работал, не выгорал. Иначе владелец прочтет «выгорела» как
    # «раньше работало» и станет ждать возврата того, чего не было.
    assert out["название"]["статус по метрикам"].startswith("опровергнута"), out["название"]
    assert out["вопрос"]["статус по метрикам"].startswith("не решено"), out["вопрос"]

    # --- 6. подписки суммируются, ролики перечисляются ---
    assert out["папа"]["подписки"] == 8
    assert out["папа"]["на каких роликах"] == "A1, A2, A3, A4", out["папа"]

    # --- 7. выгорание: три применения ПОДРЯД ниже базовой ---
    # порядок берется по дате публикации, а не по порядку строк в листе
    # Случай подобран так, чтобы механика НЕ была опровергнута: медиана 0,9
    # при базовой 1,0 - это «не решено». Именно на таком приеме выгорание и есть
    # полезный сигнал: он еще не признан плохим, но последние три раза просел.
    items = [("D%d" % i, "уставшая", "2026-09-0%d" % i) for i in range(1, 6)]
    base = [("E%d" % i, "прочее", "2026-09-0%d" % i) for i in range(1, 5)]
    bm = [("E%d" % i, 1.0, 0) for i in range(1, 5)]
    # строки нарочно вперемешку: порядок берется по дате, а не по листу
    mrows = [("D4", 0.9, 0), ("D1", 5.0, 0), ("D5", 0.9, 0), ("D2", 5.0, 0), ("D3", 0.9, 0)]
    out = D.build(pubs_sheet(items + base).read(), metrics_sheet(mrows + bm).read())
    assert out["уставшая"]["статус по метрикам"].startswith("не решено"), out["уставшая"]
    assert "выгорела" in out["уставшая"]["статус по метрикам"], out["уставшая"]
    # а если последний раз хороший - выгорания нет, даже если провалов было три
    mrows2 = [("D1", 0.9, 0), ("D2", 0.9, 0), ("D3", 0.9, 0), ("D4", 0.9, 0), ("D5", 5.0, 0)]
    out2 = D.build(pubs_sheet(items + base).read(), metrics_sheet(mrows2 + bm).read())
    assert "выгорела" not in out2["уставшая"]["статус по метрикам"], out2["уставшая"]

    # --- 8. 🔴 колонки человека не затираются ---
    sheet = dict_sheet([{"Механика": "папа", "Применений": "1",
                         "Статус решения": "в плане партии 2",
                         "Дата снятия с плана": "2026-09-30",
                         "Статус по метрикам": "старое"}])
    D.write(sheet, {"папа": {"применений": 9, "медиана": 2.0, "подписки": 3,
                             "статус по метрикам": "подтверждена",
                             "на каких роликах": "A1"}})
    written = {(c, v) for _, c, v in sheet.writes}
    assert not any(c == "Статус решения" for _, c, _ in sheet.writes), sheet.writes
    assert not any(c == "Дата снятия с плана" for _, c, _ in sheet.writes), sheet.writes
    assert ("Статус по метрикам", "подтверждена") in written
    assert ("Применений", 9) in written
    row = sheet.read()[0]
    assert row["Статус решения"] == "в плане партии 2", "решение владельца стерли"
    assert row["Дата снятия с плана"] == "2026-09-30"

    # --- 9. новая механика дописывается, повторный пересчет не плодит дублей ---
    sheet = dict_sheet()
    data = {"папа": {"применений": 4, "медиана": 2.0, "подписки": 3,
                     "статус по метрикам": "подтверждена", "на каких роликах": "A1"}}
    D.write(sheet, data)
    D.write(sheet, data)
    assert len(sheet.appended) == 1, "второй пересчет завел дубль строки"
    assert len(sheet.read()) == 1

    # --- 10. пустые данные не роняют и не портят лист ---
    empty = dict_sheet()
    D.write(empty, D.build([], []))
    assert empty.read() == [] and not empty.appended

    # --- 11. 🔴 базу не задает самая массовая механика ---
    # Приемка 28.08: на живых данных крупнейшая механика составляла 45% роликов,
    # то есть медиану «по всем» задавала она сама и сравнивалась сама с собой.
    # Убрать ее - база 0,56 против 0,63, и три вердикта из семи менялись.
    # Считаем базу по МЕДИАНАМ МЕХАНИК: тогда вес механики не зависит от того,
    # сколько раз ее сняли.
    big = [("B%d" % i, "галочки", "2026-09-%02d" % (i + 1)) for i in range(12)]
    small = [("S%d" % i, "папа", "2026-09-%02d" % (i + 20)) for i in range(4)]
    pubs = pubs_sheet(big + small)
    mets = metrics_sheet([(v, 0.5, 0) for v, _, _ in big]
                         + [(v, 0.9, 1) for v, _, _ in small])
    got = D.build(pubs.read(), mets.read())
    # медианы механик 0,5 и 0,9, база между ними - массовая «галочки» обязана
    # получить вердикт, а не сравниться сама с собой и остаться «не решено»
    assert got["галочки"]["статус по метрикам"].startswith("опровергнута"), got
    assert got["папа"]["статус по метрикам"].startswith("подтверждена"), got

    # --- 12. 🔴 «выгорела» не ставится на шуме ---
    # Правило «три подряд ниже базовой» на чистом случайном шуме срабатывало
    # в 10% прогонов. Спад - это когда последние ролики ниже СВОЕЙ ЖЕ медианы
    # заметно, а не когда три числа подряд оказались чуть ниже общей середины.
    ровный = [("R%d" % i, "ровная", "2026-09-%02d" % (i + 1)) for i in range(8)]
    pubs = pubs_sheet(ровный + small)
    # ряд качается вокруг своей медианы, последние три - чуть ниже: это шум
    шум = [0.9, 0.4, 1.1, 0.5, 0.8, 0.45, 0.5, 0.48]
    mets = metrics_sheet([(v, шум[i], 0) for i, (v, _, _) in enumerate(ровный)]
                         + [(v, 0.9, 0) for v, _, _ in small])
    got = D.build(pubs.read(), mets.read())
    assert "выгорела" not in got["ровная"]["статус по метрикам"], (
        "ярлык выгорания поставлен на шуме: %s" % got["ровная"])

    # настоящий спад - последние втрое ниже начала - помечается
    падение = [3.0, 3.2, 2.8, 3.1, 0.4, 0.3, 0.35, 0.3]
    mets = metrics_sheet([(v, падение[i], 0) for i, (v, _, _) in enumerate(ровный)]
                         + [(v, 0.9, 0) for v, _, _ in small])
    got = D.build(pubs.read(), mets.read())
    assert "выгорела" in got["ровная"]["статус по метрикам"], got["ровная"]

    # --- 13. 🔴 база = 0 не глушит логику молча ---
    # Раньше при нулевой базе НИ ОДНА механика не получала вердикта, даже втрое
    # лучшая, и отказ был неотличим от «данных мало».
    нули = [("Z%d" % i, "нулевая", "2026-09-%02d" % (i + 1)) for i in range(4)]
    pubs = pubs_sheet(нули)
    mets = metrics_sheet([(v, 0.0, 0) for v, _, _ in нули])
    got = D.build(pubs.read(), mets.read())
    assert "не с чем сравнить" in got["нулевая"]["статус по метрикам"], got

    # --- 14. 🔴 даты сравниваются как даты, а не как строки ---
    # Лист правится руками, и русский формат ДД.ММ.ГГГГ сортировался строкой:
    # «01.10» вставало раньше «02.09», хронология ломалась, и настоящее
    # выгорание пропускалось молча.
    ru = [("D1", "рус", "28.09.2026"), ("D2", "рус", "05.10.2026"),
          ("D3", "рус", "06.10.2026"), ("D4", "рус", "07.10.2026")]
    pubs = pubs_sheet(ru + small)
    mets = metrics_sheet([("D1", 3.0, 0), ("D2", 0.3, 0), ("D3", 0.3, 0),
                          ("D4", 0.3, 0)] + [(v, 0.9, 0) for v, _, _ in small])
    got = D.build(pubs.read(), mets.read())
    assert got["рус"]["на каких роликах"].startswith("D1"), (
        "хронология сломана: %s" % got["рус"]["на каких роликах"])

    # --- 15. 🔴 выброшенные строки сосчитаны и названы ---
    # Мусор в одной ячейке молча выбрасывал ролик: из 4 применений становилось 3,
    # и решение по механике отменялось само.
    pubs = pubs_sheet([("G1", "гад", "2026-09-01"), ("G2", "гад", "2026-09-02"),
                       ("G3", "гад", "2026-09-03"), ("G4", "гад", "2026-09-04")])
    mets = metrics_sheet([("G1", 1.0, 0), ("G2", "н/д", 0), ("G3", 1.2, 0),
                          ("G4", 1.1, 0)])
    got = D.build(pubs.read(), mets.read())
    text = D.summary(got)
    assert "1" in text and ("без замера" in text or "выброш" in text), text

    # --- 16. 🔴 четыре статуса метрики победы (ТЗ §3) ---
    # Их не было в коде вовсе: двухступенчатость сводилась к одной ступени,
    # а критерий приемки «у механики выставлены ОБА статуса» был невыполним.
    # Правило ТЗ: при расхождении ступеней выбор не делается - механика получает
    # статус, а не приговор.
    def набор(имя, реп, подп, n=4, день=1):
        pb = [("%s%d" % (имя, i), имя, "2026-09-%02d" % (день + i)) for i in range(n)]
        mt = [(v, реп, подп) for v, _, _ in pb]
        return pb, mt

    p1, m1 = набор("оба", 3.0, 5)             # и репосты, и подписки высокие
    p2, m2 = набор("раздача", 3.0, 0, день=10)   # репосты есть, подписок нет
    p3, m3 = набор("база", 0.2, 5, день=20)      # подписки есть, репостов нет
    p4, m4 = набор("ничего", 0.2, 0, день=1)     # ни того, ни другого
    got = D.build(pubs_sheet(p1 + p2 + p3 + p4).read(),
                  metrics_sheet(m1 + m2 + m3 + m4).read())
    assert "и то и другое" in got["оба"]["статус по метрикам"], got["оба"]
    assert "растит раздачу" in got["раздача"]["статус по метрикам"], got["раздача"]
    assert "растит базу" in got["база"]["статус по метрикам"], got["база"]
    assert "ничего" in got["ничего"]["статус по метрикам"], got["ничего"]

    # статус победы не подменяет вердикт гейта - они стоят рядом
    assert "опровергнута" in got["ничего"]["статус по метрикам"], got["ничего"]

    # --- 🔴 пять осей учета, а не одна (Ш2, решение владельца 29.08) ---
    # До этого дня словарь считал только по «Механике» и умел ответить
    # «прием папа дал 1,79», но не «что именно сработало»: о чем ролик,
    # каким товаром, для какой боли, какими словами. Тот же расчет должен
    # уметь группировать по любой оси - иначе четыре новые колонки плана
    # останутся текстом в таблице, которого петля не видит.
    строки = []
    for vid, mech, тема, товар, ценность, тип in (
            ("P9-01", "папа", "А1 гаджет-вина", "планшет", "анти-гаджет", "вопрос"),
            ("P9-02", "папа", "А1 гаджет-вина", "стол", "анти-гаджет", "вопрос"),
            ("P9-03", "вопрос маме", "А3 ни минуты себе", "стол", "занят сам", "утверждение"),
            ("P9-04", "вопрос маме", "А3 ни минуты себе", "полка", "порядок", "утверждение")):
        for platform in ("instagram", "vk"):
            строки.append({"ID": vid, "Механика": mech, "Тема": тема, "Товар": товар,
                           "Ценность": ценность, "Тип хука": тип,
                           "Дата": "2026-09-04", "Площадка": platform,
                           "Креатор": "Ксения"})
    pubs = FakeSheet(["ID", "Дата", "Площадка", "Ссылка", "Медиа ID", "Креатор",
                      "Механика", "Тема", "Товар", "Ценность", "Тип хука",
                      "Длина", "Разрешение"], строки)
    mets = metrics_sheet([("P9-01", 3.0, 5), ("P9-02", 3.2, 4),
                          ("P9-03", 0.3, 0), ("P9-04", 0.4, 1)])

    по_механике = D.build(pubs.read(), mets.read())
    assert set(по_механике) == {"папа", "вопрос маме"}, по_механике

    по_теме = D.build(pubs.read(), mets.read(), axis="Тема")
    assert set(по_теме) == {"А1 гаджет-вина", "А3 ни минуты себе"}, по_теме
    assert по_теме["А1 гаджет-вина"]["применений"] == 2
    assert по_теме["А1 гаджет-вина"]["медиана"] > по_теме["А3 ни минуты себе"]["медиана"]

    # ось «Товар» режет те же ролики иначе: стол попал и в удачную, и в слабую тему
    по_товару = D.build(pubs.read(), mets.read(), axis="Товар")
    assert по_товару["стол"]["применений"] == 2, по_товару["стол"]
    assert по_товару["планшет"]["применений"] == 1

    # ось, которой нет в листе, - это не «ноль применений», это ошибка настройки
    try:
        D.build(pubs.read(), mets.read(), axis="Погода")
        raise AssertionError("несуществующая ось обязана быть слышной")
    except D.НетОси:
        pass

    # --- 🔴 срезы по осям не смешиваются в листе ---
    # Без колонки «Ось» строка «анти-гаджет» стояла бы в СЛОВАРЕ рядом с «папа»,
    # и генератор поставил бы ценность в план как прием: он читает лист и не может
    # знать, что это разные вещи.
    лист = FakeSheet(["Ось", "Механика", "Применений", "Медиана репостов/1000",
                      "Подписки", "Статус решения", "Статус по метрикам",
                      "На каких роликах", "Дата снятия с плана"])
    D.write(лист, по_механике, axis="Механика")
    D.write(лист, по_теме, axis="Тема")
    оси = set((r.get("Ось") or "") for r in лист.read())
    assert оси == {"Механика", "Тема"}, оси
    имена = [(r.get("Ось"), r.get("Механика")) for r in лист.read()]
    assert ("Механика", "папа") in имена, имена
    assert ("Тема", "А1 гаджет-вина") in имена, имена
    # одноименные значения в разных осях - это РАЗНЫЕ строки, а не одна
    D.write(лист, {"папа": по_теме["А1 гаджет-вина"]}, axis="Товар")
    строк_папа = [r for r in лист.read() if r.get("Механика") == "папа"]
    assert len(строк_папа) == 2, "«папа» как прием и как товар - две строки: %s" % строк_папа

    # --- 16. 🔴 ролик, снятый не по сцене, словарь НЕ учит (А9, 29.08) ---
    # Оси в ПУБЛИКАЦИЯХ переносятся из ПЛАНА, то есть описывают замысел. Если
    # креатор отступил, эти оси врут - и словарь припишет результат ценности,
    # которой в кадре не было. Считать такое нельзя, но и молчать нельзя:
    # выброшенное обязано быть названо числом, иначе применений станет меньше
    # само собой, ровно как с мусором в ячейке (приемка 28.08).
    pubs = pubs_sheet([("P1-01", "папа", "2026-09-04"),
                       ("P1-02", "папа", "2026-09-05"),
                       ("P1-03", "папа", "2026-09-06", "отступил")])
    mets = metrics_sheet([("P1-01", 2.0, 5), ("P1-02", 2.2, 4), ("P1-03", 9.0, 30)])
    out = D.build(pubs.read(), mets.read())
    assert out["папа"]["применений"] == 2, (
        "отступление посчитали как замысел: %s" % out["папа"])
    assert out.dropped.get("снято не по сцене") == 1, out.dropped
    assert "P1-03" not in out["папа"]["на каких роликах"], out["папа"]

    # --- 16б. владелец сверил оси руками - ролик возвращается в счет ---
    # Без этого отступивший ролик выпадал бы навсегда, и единственным способом
    # его учесть было бы переписать разметку задним числом, скрыв отступление.
    pubs = pubs_sheet([("P1-01", "папа", "2026-09-04"),
                       ("P1-03", "папа", "2026-09-06", "сверено")])
    mets = metrics_sheet([("P1-01", 2.0, 5), ("P1-03", 3.0, 7)])
    out = D.build(pubs.read(), mets.read())
    assert out["папа"]["применений"] == 2, (
        "«сверено» - это подтверждение владельца, оно считается: %s" % out["папа"])
    assert not out.dropped.get("снято не по сцене"), out.dropped

    # --- 16в. отметки нет вовсе - считаем, но говорим вслух сколько ---
    # 🔴 Исключать неподтвержденные нельзя: до появления вопроса в форме такими
    # будут ВСЕ ролики, и петля встанет целиком, доложив «считать нечего».
    # Поэтому дыра не закрывается, а делается видимой.
    pubs = pubs_sheet([("P1-01", "папа", "2026-09-04"),
                       ("P1-02", "папа", "2026-09-05")], match="")
    mets = metrics_sheet([("P1-01", 2.0, 5), ("P1-02", 2.2, 4)])
    out = D.build(pubs.read(), mets.read())
    assert out["папа"]["применений"] == 2, out["папа"]
    assert out.dropped.get("без отметки о съемке") == 2, out.dropped

    # --- 16в-2. и то и другое обязано попасть в сводку владельцу ---
    # Счет внутри объекта, которого никто не видит, - это тишина. Ровно на этом
    # 28.08 разошлись «данных мало» и «данные выброшены».
    pubs = pubs_sheet([("P1-01", "папа", "2026-09-04"),
                       ("P1-02", "папа", "2026-09-05", ""),
                       ("P1-03", "папа", "2026-09-06", "отступил")])
    mets = metrics_sheet([("P1-01", 2.0, 5), ("P1-02", 2.2, 4), ("P1-03", 9.0, 30)])
    текст = D.summary(D.build(pubs.read(), mets.read())).lower()
    assert "не по сцене" in текст, текст
    assert "без отметки" in текст, текст

    # --- 16г. колонки «Соответствие» нет вовсе - старая таблица не падает ---
    # Лист заведен до 29.08, колонку допишет setup.py. До этого счет обязан
    # идти по-старому, а не отказывать: отказ остановил бы петлю на ровном месте.
    старые = FakeSheet(["ID", "Дата", "Площадка", "Механика"],
                       [{"ID": "P1-01", "Механика": "папа", "Дата": "2026-09-04",
                         "Площадка": "vk"}])
    out = D.build(старые.read(), metrics_sheet([("P1-01", 2.0, 5)]).read())
    assert out["папа"]["применений"] == 1, out

    print("dictionary selftest OK: медиана, один ролик на двух площадках, порог 4, "
          "±20% от базовой, выгорание по порядку дат и не на шуме, база не от "
          "массовой механики, нулевая база названа, русские даты, потери сосчитаны, "
          "колонки человека целы, без дублей, счет по любой из пяти осей, "
          "снятое не по сцене не учится и названо числом")


if __name__ == "__main__":
    selftest()
