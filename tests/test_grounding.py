# -*- coding: utf-8 -*-
"""Гейт обоснованности: на чем стоит каждая строка плана.

🔴 Чем вскрылась нужда. Аудит 29.08: содержание ролика - «что в кадре» и «смысл
хука» - агент писал из головы. При этом в проекте с 22.07 лежал разбор 4 277
отзывов с языком мам и тринадцатью готовыми сюжетами, и он не открывался.
План партии 1 совпал с этими сюжетами в 4-5 строках из 15, и то случайно.

Гейт не выдумывает содержание. Он спрашивает у каждой строки: **на чем ты
стоишь** - на ценности, подтвержденной языком покупателей, или на догадке.
И ловит обещания, которые отзывы прямо запрещают давать.
"""
import io
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import grounding as G  # noqa: E402

СПРАВОЧНИК = (
    "Ценность\tСвойство товара\tЧто меняет в дне мамы\tСтатус\tВозраст от\tОграничение\tИсточник\n"
    "анти-гаджет\tсвет и песок\tне просит мультики\tживет\t\t\tОТЗЫВЫ §2\n"
    "занят сам\tсенсорика\tсвободное время мамы\tживет\t24\t"
    "не обещать «займет годовалого»\tОТЗЫВЫ §2, §5\n"
    "осанка\tрастущий стол\tсидит правильно\tсоздание спроса\t\t"
    "мамы так не думают\tОТЗЫВЫ §3\n")

ПРОФИЛИ = (
    "Креатор\tКто в кадре\tРебенок\tПол ребенка\tВозраст месяцев\tУмеет\tТовары\tВторой взрослый\tОператор\tПодтверждено\n"
    "Спартак\tпапа\tдочь\tдевочка\t11\tходит\tсветовой планшет\tжена\tжена\tда\n"
    "Ксения\tмама\tдочь\tдевочка\t48\tможет все\tсветовой стол\tмуж\tштатив\tда\n")


СТОПЫ = (
    "Действие\tСлова-признаки\tКласс\tПочему нельзя требовать\tЧто вместо\tИсточник\n"
    "сверлить стену и вешать полку\tсверлит, вешает полку, дюбел\t"
    "необратимое в чужом жилье\tПолка у креатора уже висит, дыры остаются навсегда\t"
    "снимать уже висящую полку\tзамер владельца 30.08\n"
    "переставлять высоту стола\tщелкает фиксатором, отметки на ножке\t"
    "требует инструмента\tВысота перекручивается отверткой, это не жест\t"
    "показывать две высоты склейкой\tзамер владельца 30.08\n")


def row(vid, creator, value, frame="кадр", hook="хук"):
    return {"ID": vid, "Креатор": creator, "Ценность": value,
            "Что в кадре": frame, "Хук": hook,
            "Механика": "м", "Тема": "т", "Товар": "световой планшет"}


def selftest():
    справочник = G.read_values(io.StringIO(СПРАВОЧНИК))
    assert set(справочник) == {"анти-гаджет", "занят сам", "осанка"}, справочник
    профили = G.read_profiles(io.StringIO(ПРОФИЛИ))

    # --- 1. ценность, которой нет в справочнике ---
    # Это и есть «я придумал»: строка ни на что не опирается, и через партию
    # будет непонятно, что именно мы проверяли.
    f = G.check([row("P1-01", "Ксения", "ребенку весело")], справочник, профили)
    assert f and "справочник" in f[0]["что"].lower(), f

    # подтвержденная ценность находкой не считается
    assert not G.check([row("P1-02", "Ксения", "анти-гаджет")], справочник, профили)

    # --- 2. 🔴 обещание, которое отзывы запрещают давать ---
    # «Занят сам» с ребенком младше двух лет - это ровно «займет годовалого»,
    # прямой запрет из ОТЗЫВЫ §5. У Спартака дочери 11 месяцев.
    f = G.check([row("P1-03", "Спартак", "занят сам")], справочник, профили)
    assert f, "обещание «займет годовалого» обязано быть поймано"
    assert "11" in f[0]["что"] or "возраст" in f[0]["что"].lower(), f

    # та же ценность у Ксении, где дочери 4 года, проходит
    assert not G.check([row("P1-04", "Ксения", "занят сам")], справочник, профили)

    # --- 2б. 🔴 старший ребенок не прикрывает младшего ---
    # Живой случай: слепая приемка 29.08 нашла в партии 1 строку P1-06, где
    # в кадре ТОЛЬКО младший сын Ксении, 18 месяцев, а ценность - «занят сам»
    # (от 24). Гейт молчал: он спрашивал «есть ли у креатора ХОТЬ ОДИН
    # подходящий ребенок», и старшая дочь 48 мес. проходила за всех.
    # Правило перевернуто: при неизвестности судим по САМОМУ МЛАДШЕМУ.
    двое = G.read_profiles(io.StringIO(
        "Креатор\tКто в кадре\tРебенок\tПол ребенка\tВозраст месяцев\tУмеет\tТовары\t"
        "Второй взрослый\tОператор\tПодтверждено\n"
        "Ксения\tмама\tсын\tмальчик\t18\tделает не всегда\tсветовой стол\tмуж\tштатив\tда\n"
        "Ксения\tмама\tдочь\tдевочка\t48\tможет все\tсветовой стол\tмуж\tштатив\tда\n"))
    f = [x for x in G.check([row("P1-06", "Ксения", "занят сам")], справочник, двое)
         if x["вид"] == "запрет по возрасту"]
    assert f, "младший 18 мес. в семье со старшей 48 обязан ловиться"
    assert "18" in f[0]["что"], f

    # ...а если сказано, что в кадре старшая - строка проходит
    старшая = row("P1-07", "Ксения", "занят сам")
    старшая["Ребенок в кадре"] = "дочь"
    assert not [x for x in G.check([старшая], справочник, двое)
                if x["вид"] == "запрет по возрасту"], \
        "названному ребенку 48 мес., запрета нет"

    # ...а если названный ребенок младший - ловится, несмотря на наличие старшей
    младший = row("P1-08", "Ксения", "занят сам")
    младший["Ребенок в кадре"] = "сын"
    f = [x for x in G.check([младший], справочник, двое)
         if x["вид"] == "запрет по возрасту"]
    assert f and "18" in f[0]["что"], f

    # 🔴 в кадре могут быть оба ребенка: судим по МЛАДШЕМУ из названных
    # Найдено вторым слепым проходом: у четырех строк Ксении сцена требует двоих,
    # а колонка принимала одного - и проверка возраста ложилась не на того.
    оба = row("P1-10", "Ксения", "занят сам")
    оба["Ребенок в кадре"] = "сын, дочь"
    f = [x for x in G.check([оба], справочник, двое) if x["вид"] == "запрет по возрасту"]
    assert f and "18" in f[0]["что"], \
        "если в кадре двое, обещание меряется по младшему: %s" % f

    # 🔴 ребенок, которого у креатора нет, - отдельная находка, а не тишина
    чужой_ребенок = row("P1-09", "Ксения", "анти-гаджет")
    чужой_ребенок["Ребенок в кадре"] = "племянник"
    f = [x for x in G.check([чужой_ребенок], справочник, двое)
         if x["вид"] == "нет такого ребенка"]
    assert f, "в кадре назван ребенок, которого нет в профиле - это брак съемки"

    # --- 2в. 🔴 малыш один в кадре - это обещание «годовалый играет сам» ---
    # Найдено вторым слепым проходом 29.08 и создано мной же: разводя гипотезы,
    # я убрал папу из строк Спартака, и в кадре осталась одна 11-месячная. Ярлык
    # ценности при этом стоял безобидный («экономия места»), поэтому проверка
    # по ценности молчала. Признак машинный: ребенок младше двух лет и НИ ОДНОГО
    # взрослого в описании кадра.
    один = row("P1-40", "Спартак", "экономия места",
               frame="Кадр сверху, взрослых нет. Дочь ползет через комнату "
                     "и садится к планшету, кладет обе ладони в песок")
    справочник_плюс = dict(справочник)
    справочник_плюс["экономия места"] = {"статус": "живет", "возраст": None,
                                         "ограничение": "", "источник": "",
                                         "свойство": "", "меняет": ""}
    f = [x for x in G.check([один], справочник_плюс, профили)
         if x["вид"] == "малыш один в кадре"]
    assert f, "11-месячная одна с песком - запрещенное обещание, ярлык тут ни при чем"

    # взрослый в кадре снимает вопрос
    вместе = row("P1-41", "Спартак", "экономия места",
                 frame="Папа сидит рядом и ведет ее ладонью по песку")
    assert not [x for x in G.check([вместе], справочник_плюс, профили)
                if x["вид"] == "малыш один в кадре"]

    # ребенок старше двух лет один в кадре - это норма, не находка
    большой = row("P1-42", "Ксения", "экономия места",
                  frame="Дочь одна за столом, взрослых нет, рисует песком")
    assert not [x for x in G.check([большой], справочник_плюс, профили)
                if x["вид"] == "малыш один в кадре"], \
        "четырехлетке быть одной в кадре не запрещено"

    # --- 2г. 🔴 ⛔ ценности выносится человеку, а не судится машиной ---
    # Живой случай 29.08: ценность «устойчивость» несет ⛔ «не обещать нагрузку
    # на столешницу-мольберт: ломается», а сцена показывала ребенка, встающего
    # на планшет всем весом. Гейт молчал дважды: ценность не привязана ни к
    # одному товару, и по СЛОВАМ «нагрузка» со «встает всем весом» не совпадает.
    # 🔴 Судить об этом машина не может - и не должна делать вид. Ее работа:
    # обязательно показать запрет рядом со строкой, чтобы человек посмотрел.
    сп = dict(справочник)
    сп["устойчивость"] = {"статус": "живет", "возраст": None, "свойство": "", "меняет": "",
                          "ограничение": "⛔ не обещать нагрузку на столешницу-мольберт: "
                                         "ломается, главный негатив", "источник": "ОТЗЫВЫ §4"}
    вес = row("P1-43", "Ксения", "устойчивость",
              frame="Дочь встает на планшет и переносит на него весь вес")
    f = [x for x in G.check([вес], сп, профили) if x["вид"] == "ценность с запретом"]
    assert f, "строка на ценности с ⛔ обязана попасть человеку на глаза"
    assert "столешниц" in f[0]["почему"], f

    # ценность без ⛔ такой пометки не дает - иначе отчет превратится в шум
    assert not [x for x in G.check([row("P1-44", "Ксения", "анти-гаджет")], сп, профили)
                if x["вид"] == "ценность с запретом"]

    # --- 3. ценность, которой мамы не пользуются, - предупреждение, не запрет ---
    # Владелец вправе создавать спрос. Но знать, что это создание спроса,
    # а не перехват готового, он обязан заранее.
    f = G.check([row("P1-05", "Ксения", "осанка")], справочник, профили)
    assert f and f[0]["вид"] == "создание спроса", f

    # --- 4. 🔴 стоп-фраза в тексте кадра или хука ---
    f = G.check([row("P1-06", "Ксения", "анти-гаджет",
                     hook="Займет годовалого на час")], справочник, профили)
    assert f and "запрещ" in f[0]["почему"].lower(), f

    # --- 5. перекос покрытия виден в отчете ---
    # Сильнейшая ценность может оказаться в плане один раз, а слабая - шесть.
    # Само по себе это не ошибка, но увидеть это надо до съемки, а не после.
    план = ([row("P%02d" % i, "Ксения", "анти-гаджет") for i in range(3)] +
            [row("P1%02d" % i, "Ксения", "осанка") for i in range(6)])
    отчет = G.report(G.check(план, справочник, профили), план, справочник)
    assert "покрытие" in отчет.lower(), отчет

    # --- 5б. 🔴 товар обязан поддерживать заявленную ценность ---
    # Полка не дает анти-гаджет: у нее нет ни подсветки, ни песка. Строка
    # с таким сочетанием обещает то, чего предмет не умеет, и через партию
    # вывод «анти-гаджет не работает» будет о чем угодно, кроме анти-гаджета.
    товары = G.read_goods(io.StringIO(
        "Товар\tФункция\tЧто заменяет\tВозраст\tЦенность\tСтатус\tИсточник\n"
        "световой стол\tрисование песком\tпесочницу\t1-10\tанти-гаджет\tподтверждено\tДНК\n"
        "световой стол\tхранение\tкоробки\t1-10\tпорядок на уровне ребенка\tподтверждено\tДНК\n"
        "полка\tкниги обложкой вперед\tстопку\t1-10\tчитающий ребенок\tподтверждено\tОТЗЫВЫ\n"))
    строка = row("P1-20", "Ксения", "анти-гаджет")
    строка["Товар"] = "полка"
    f = G.check([строка], справочник, профили, товары)
    assert f and f[0]["вид"] == "товар не дает эту ценность", f

    # тот же товар со своей ценностью проходит
    ок = row("P1-21", "Ксения", "читающий ребенок")
    ок["Товар"] = "полка"
    assert not G.check([ок], {"читающий ребенок": {"статус": "живет", "возраст": None,
                                                   "ограничение": "", "источник": "",
                                                   "свойство": "", "меняет": ""}},
                       профили, товары)

    # ценность, не привязанная НИ К ОДНОМУ товару, находкой не считается:
    # бывают общие - «подарок», «натуральный материал»
    общая = row("P1-22", "Ксения", "анти-гаджет")
    общая["Товар"] = "полка"
    пустые = G.read_goods(io.StringIO(
        "Товар\tФункция\tЧто заменяет\tВозраст\tЦенность\tСтатус\tИсточник\n"
        "световой стол\tподсветка\tночник\t0-10\tвечерний ритуал\tподтверждено\tДНК\n"))
    assert not [x for x in G.check([общая], справочник, профили, пустые)
                if x["вид"] == "товар не дает эту ценность"], \
        "ценность не привязана ни к одному товару - судить не по чему"

    # --- 5в. 🔴 сегмент: кому адресован ролик ---
    # Живой случай 29.08: в партии 1 все пятнадцать строк написаны для мамы,
    # которая покупает себе, а 40% столов покупают В ПОДАРОК. Целый сегмент
    # с другой болью не звали вовсе, и увидеть это было нечем.
    сегменты = G.read_segments(io.StringIO(
        "Сегмент\tКто это\tЕго боль\tЧто для него ценно\tВес\tОсторожно\tИсточник\n"
        "мама ядра\tмама 1-3 лет\tни минуты себе\tзанят сам\tядро\t\tОТЗЫВЫ §1\n"
        "даритель\tбабушка\tчто подарить\tподарок\t~40% столов\t\tОТЗЫВЫ §1\n"
        "мама-сборщик\tсквозной мотив, а НЕ сегмент\tстрах сборки\tрастет\t"
        "сквозной мотив\t\tОТЗЫВЫ §1\n"))
    assert set(сегменты) == {"мама ядра", "даритель", "мама-сборщик"}, сегменты

    # сегмент не из справочника - находка
    чужой = row("P1-30", "Ксения", "анти-гаджет")
    чужой["Сегмент"] = "молодые папы-геймеры"
    f = [x for x in G.check([чужой], справочник, профили, segments=сегменты)
         if x["вид"] == "сегмент не из справочника"]
    assert f, "выдуманный сегмент обязан быть пойман"

    # свой сегмент проходит
    свой = row("P1-31", "Ксения", "анти-гаджет")
    свой["Сегмент"] = "мама ядра"
    assert not [x for x in G.check([свой], справочник, профили, segments=сегменты)
                if "сегмент" in x["вид"]]

    # 🔴 сквозной мотив сегментом не считается: он живет внутри других
    мотив = row("P1-32", "Ксения", "анти-гаджет")
    мотив["Сегмент"] = "мама-сборщик"
    f = [x for x in G.check([мотив], справочник, профили, segments=сегменты)
         if x["вид"] == "не сегмент, а мотив"]
    assert f, "мама-сборщик - мотив, а не аудитория: адресовать ролик ей нельзя"

    # --- 5г. перекос по сегментам виден в отчете ---
    однобокий = []
    for i in range(6):
        r = row("S%02d" % i, "Ксения", "анти-гаджет")
        r["Сегмент"] = "мама ядра"
        однобокий.append(r)
    отчет = G.report(G.check(однобокий, справочник, профили, segments=сегменты),
                     однобокий, справочник, сегменты)
    assert "даритель" in отчет, "непокрытый сегмент обязан быть назван: %s" % отчет

    # --- 6. 🔴 доказательство, что гейт вообще способен ловить ---
    # Ноль находок одинаково выглядит как «все обосновано» и как «гейт молчит».
    заведомо = [row("X1", "Спартак", "выдуманная ценность",
                    hook="Займет годовалого, песок не рассыпается")]
    f = G.check(заведомо, справочник, профили)
    assert len(f) >= 2, "заведомо плохая строка дала меньше двух находок: %s" % f

    # --- 6б. 🔴 цена съемки: чего нельзя требовать от человека дома ---
    # Замер владельца 30.08 по двум строкам плана: «папа сверлит стену и вешает
    # полку» и «папа щелкает фиксатором, меняя высоту стола». Первое - дыры
    # в его собственной квартире, полка там уже висит. Второе физически неверно:
    # высота перекручивается ОТВЕРТКОЙ, это разборка на минуты, а не жест.
    # Гейт до 30.08 не знал о съемке ничего: он проверял правдивость обещания
    # и молчал о том, выполнима ли сцена вообще.
    стопы = G.read_stops(io.StringIO(СТОПЫ))
    сцена = ("Папа сверлит стену и вешает полку низко, дети растаскивают дюбели")
    f = G.check([row("P1-10", "Ксения", "анти-гаджет", frame=сцена)],
                справочник, профили, stops=стопы)
    assert any("сверл" in x["что"].lower() or "необратим" in x["что"].lower()
               or "цена" in x["вид"].lower() for x in f), f
    # в находке обязана быть замена, иначе она запрещает и не помогает
    сверление = [x for x in f if "цена" in x["вид"].lower()]
    assert сверление and "уже висящ" in сверление[0]["почему"], сверление
    # 🔴 и основание: замер владельца или моя догадка - это разные веса
    assert "основание" in сверление[0]["почему"], сверление[0]
    assert "замер владельца" in сверление[0]["почему"], сверление[0]

    сцена2 = "Папа щелкает фиксатором на первой отметке, младший дотягивается стоя"
    f = G.check([row("P1-04", "Ксения", "анти-гаджет", frame=сцена2)],
                справочник, профили, stops=стопы)
    assert any("цена" in x["вид"].lower() for x in f), f

    # обычная сцена находкой не считается - иначе гейт запретит все
    ок = "Папа садится рядом с дочерью к планшету и водит ее руку по песку"
    f = G.check([row("P1-01", "Спартак", "анти-гаджет", frame=ок)],
                справочник, профили, stops=стопы)
    assert not any("цена" in x["вид"].lower() for x in f), f

    # 🔴 признак не должен ловиться внутри другого слова. Замер 30.08 на живом
    # плане: признак «на пол» сработал на сцене «папа переставляет книги
    # НА ПОЛку». Одна такая находка выбивает годную строку, а следующая правка
    # рождает новое нарушение - цикл, который мы уже проходили.
    словарь_с_фразой = (
        "Действие\tСлова-признаки\tКласс\tПочему нельзя требовать\tЧто вместо\tИсточник\n"
        "уборка\tна пол, сверл\tвремя\tубирать долго\tне сорить\tпроба\n")
    двусмысленно = G.read_stops(io.StringIO(словарь_с_фразой))
    f = G.check([row("P1-12", "Ксения", "анти-гаджет",
                     frame="Папа переставляет книги на полку обложками вперед")],
                справочник, профили, stops=двусмысленно)
    assert not any("цена" in x["вид"].lower() for x in f), (
        "признак «на пол» пойман внутри слова «полку»: %s" % f)
    # ...но настоящее вхождение ловится
    f = G.check([row("P1-12", "Ксения", "анти-гаджет",
                     frame="Песок высыпается на пол, дети топчутся рядом")],
                справочник, профили, stops=двусмысленно)
    assert any("цена" in x["вид"].lower() for x in f), f
    # ...и однословный признак остается основой: «сверл» обязан ловить «сверлит»
    f = G.check([row("P1-10", "Ксения", "анти-гаджет",
                     frame="Папа сверлит стену")],
                справочник, профили, stops=двусмысленно)
    assert any("цена" in x["вид"].lower() for x in f), f

    # без справочника стопов проверка молчит, а не падает: старые планы живые
    assert not any("цена" in x["вид"].lower() for x in
                   G.check([row("P1-10", "Ксения", "анти-гаджет", frame=сцена)],
                           справочник, профили))

    # --- 7. отчет всегда говорит, чего он НЕ проверяет ---
    assert G.LIMITS in G.report([], [], справочник)
    assert "смысл" in G.LIMITS.lower() or "сцен" in G.LIMITS.lower()


    # --- 🔴 стоп-действие привязывается к ТОВАРУ (31.08) ---
    # Замер владельца на карточке P1-03: «полочка для книг, он туда не может
    # поставить корзину, туда только книжки ставятся». Сцена с корзиной
    # на книжной полке прошла все четыре гейта.
    # Первая починка провалилась молча: признаки были записаны как
    # «корзину на полку», а в сцене стоял обратный порядок - «ставит на
    # нижнюю полку корзину». Строка в справочнике была, защиты не было.
    # Короткое слово «корзин» ловит любой порядок, но само по себе законно
    # (корзина для игрушек на полу). Поэтому у стоп-действия есть товар.
    ТАБ = chr(9)
    с_товаром = ('Действие\tСлова-признаки\tТовар\tКласс\tПочему нельзя требовать\tЧто вместо\tИсточник' + chr(10) + 'класть на книжную полку не книги\tкорзин, коробк, ящик\tполка\tневерно по факту\tПолка - для книг обложкой вперед\tпоказывать книги\tзамер владельца 31.08' + chr(10))
    стопы_т = G.read_stops(io.StringIO(с_товаром))
    assert стопы_т[0].get(u"товар") == u"полка", стопы_т

    полка = row(u"S1", u"Ксения", u"анти-гаджет",
                frame=u"папа ставит на нижнюю полку корзину и кладет туда машинку")
    полка[u"Товар"] = u"полка"
    н = [f for f in G.check([полка], справочник, профили, stops=стопы_т)
         if f["вид"] == u"цена съемки"]
    assert н, u"корзина на книжной полке прошла молча"

    # ...и контроль: та же корзина при ДРУГОМ товаре - не находка
    стол = row(u"S2", u"Ксения", u"анти-гаджет",
               frame=u"мама ставит корзину с игрушками рядом со столом")
    стол[u"Товар"] = u"световой стол"
    н2 = [f for f in G.check([стол], справочник, профили, stops=стопы_т)
          if f["вид"] == u"цена съемки"]
    assert not н2, u"стоп-действие полки сработало на другом товаре: %s" % н2

    print("grounding selftest OK: ценность из справочника, запрет по возрасту, "
          "создание спроса помечено, стоп-фразы, товар против ценности, перекос покрытия, "
          "гейт доказан заведомым случаем, граница названа")


