# -*- coding: utf-8 -*-
u"""Упаковка поста под каждую площадку. Сеть не нужна.

🔴 Зачем (31.08, по требованию владельца). До этого в обе сети уходил ОДИН
и тот же текст, и это было видно на живом прогоне: в ВК ссылка кликается,
а мы слали туда голый номер артикула; в Instagram ссылка не кликается,
и слать туда ссылку - значит занимать строку мусором.

Правила лежат в `data/площадки.tsv`, а не в коде: у каждой строки источник,
и добавление площадки не требует правки программы.
"""
import io
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from lib import platforms as P  # noqa: E402

ПРАВИЛА = (
    "Площадка\tchanel_id\tСсылка кликабельна\tЛимит текста\tХештегов максимум\t"
    "Что добавлять к тексту\tПоля публикации\tЗаголовок нужен\tИсточник\n"
    "vk\t2\tда\t16000\tнет предела\tссылка\tvkontakte_carousel=false\tнет\tдока ВК\n"
    "instagram\t1\tнет\t2200\t30\tартикул\tinstagram_share_to_feed=true\tнет\tдока Meta\n"
    "youtube\t16\tда\t5000\t15\tссылка\tyoutube_privacy_status=1\tда\tдока YouTube\n"
)

АККАУНТЫ = [{"id": 2248535, "chanel_id": 2, "name": "FOXLIK"},
            {"id": 2248551, "chanel_id": 1, "name": "myplayroom_shop"},
            {"id": 999, "chanel_id": 16, "name": "FOXLIK YouTube"}]

ТЕКСТ = u"Принес пульт - ушел рисовать песком. Световой стол не запрещает мультики."


def selftest():
    правила = P.read_rules(io.StringIO(ПРАВИЛА))
    assert set(правила) == {2, 1, 16}, правила

    детали = P.details(АККАУНТЫ, ТЕКСТ, артикул="43287163", file_ids=[7], rules=правила)
    по_аккаунту = {d["account_id"]: d for d in детали}
    assert set(по_аккаунту) == {2248535, 2248551, 999}, по_аккаунту

    # --- ВК: ссылка кликается, значит идет ссылка, а не номер ---------------
    вк = по_аккаунту[2248535]
    assert "wildberries.ru/catalog/43287163/detail.aspx" in вк["content"], вк
    assert "Артикул" not in вк["content"], u"в ВК номер не нужен - там ссылка"
    assert вк["publication_type"] == 4 and вк["file_ids"] == [7]

    # --- Instagram: ссылка не кликается, значит номер ------------------------
    иг = по_аккаунту[2248551]
    assert "43287163" in иг["content"], иг
    # 🔴 БЕЗ решетки. Замер живого поста 02.09: «#43287163» Instagram превращает
    # в ссылку на страницу хештега (/explore/tags/43287163/) - человек жмет
    # на артикул и уходит в поиск Instagram, а не к товару. Номер без решетки
    # остается текстом, который копируют и ищут в приложении маркетплейса.
    assert "#43287163" not in иг["content"],         u"решетка делает из артикула хештег и уводит человека в поиск Instagram"
    assert "wildberries.ru" not in иг["content"], \
        u"некликабельная ссылка в Instagram - мусор в подписи"
    assert иг.get("instagram_share_to_feed") is True, иг

    # --- YouTube: нужен заголовок ------------------------------------------
    ют = по_аккаунту[999]
    assert ют.get("title"), u"Shorts без заголовка не публикуется"
    assert len(ют["title"]) <= 100, u"заголовок YouTube не длиннее 100 знаков"
    assert ют.get("youtube_privacy_status") == 1, ют

    # --- 🔴 лимит текста режется по площадке, а не по самой длинной ---------
    длинный = u"а" * 3000
    детали2 = P.details(АККАУНТЫ, длинный, артикул="43287163", file_ids=[7],
                        rules=правила)
    по2 = {d["account_id"]: d for d in детали2}
    assert len(по2[2248551]["content"]) <= 2200, u"Instagram обрежет сам и криво"
    assert len(по2[2248535]["content"]) > 2200, u"в ВК резать незачем"

    # --- площадка, которой нет в правилах, не пропадает молча ---------------
    чужой = АККАУНТЫ + [{"id": 555, "chanel_id": 77, "name": "Неизвестная"}]
    try:
        P.details(чужой, ТЕКСТ, артикул="43287163", file_ids=[7], rules=правила)
        raise AssertionError(u"аккаунт без правил обязан быть слышен")
    except P.НетПравил as e:
        assert "555" in str(e) or "77" in str(e), e

    # --- 🔴 без артикула ссылку не выдумываем -------------------------------
    без = P.details(АККАУНТЫ[:1], ТЕКСТ, артикул="", file_ids=[7], rules=правила)
    assert "wildberries" not in без[0]["content"], \
        u"ссылка на пустой артикул ведет в никуда"
    assert без[0]["content"].strip() == ТЕКСТ.strip()

    # === ссылки Mobzio и артикул Ozon (решение владельца 02.09) ============
    # 🔴 Ссылка ведет НЕ на wildberries.ru, а на короткую mobz.link: она
    # открывает товар в приложении маркетплейса, где человек уже авторизован
    # (слова владельца 02.09), и метит источник перехода. Прямая ссылка
    # не делает ни того, ни другого.
    # 🔴 У площадки ДВЕ ссылки - на WB и на Ozon (02.09). Ключ без маркетплейса
    # оставил бы вторую невидимой: словарь молча схлопнул бы их в одну.
    ССЫЛКИ = (u"Товар\tПлощадка\tМаркетплейс\tСсылка\tСтатус\tИсточник\n"
              u"световой стол\tvk\tWB\thttps://foxlik.mobz.link/43287163vk\tживая\tзамер\n"
              u"световой стол\tvk\tOzon\thttps://foxlik.mobz.link/646406042vk\tживая\tзамер\n"
              u"световой стол\tinstagram\tWB\thttps://foxlik.mobz.link/43287163ig\tживая\tзамер\n")
    ссылки = P.read_links(io.StringIO(ССЫЛКИ))
    assert ссылки[(u"световой стол", u"vk", u"wb")].endswith("43287163vk"), ссылки
    assert ссылки[(u"световой стол", u"vk", u"ozon")].endswith("646406042vk"), ссылки

    детали3 = P.details(АККАУНТЫ, ТЕКСТ, артикул="43287163", file_ids=[7],
                        rules=правила, ozon="646406042",
                        links=ссылки, товар=u"световой стол")
    по3 = {d["account_id"]: d for d in детали3}

    вк3 = по3[2248535]["content"]
    assert "foxlik.mobz.link/43287163vk" in вк3, вк3
    # 🔴 Ссылка подписана так же, как артикул Ozon строкой ниже: голый адрес
    # рядом с «🛒 Артикул на Ozon» читается как обрывок, а не как «купить тут».
    assert u"🛒 Смотреть на WB:" in вк3, вк3
    assert "wildberries.ru/catalog" not in вк3, u"прямая ссылка теряет диплинк и метку"
    # 🔴 Ozon тоже ссылкой, а не номером: там, где ссылка кликается, номер -
    # это работа, переложенная на человека (вопрос владельца 02.09).
    assert u"🛒 Смотреть на Ozon: https://foxlik.mobz.link/646406042vk" in вк3, вк3
    assert u"Артикул на Ozon" not in вк3, u"номер вместо рабочей ссылки"

    иг3 = по3[2248551]["content"]
    assert "43287163" in иг3 and "646406042" in иг3, иг3
    assert "#" not in иг3, u"ни один номер не должен стать хештегом: %s" % иг3
    # там, где ссылка не кликается, человеку говорят, где ее взять
    assert u"в шапке профиля" in иг3.lower(), иг3
    assert "mobz.link" not in иг3, u"в Instagram ссылка не кликается - это мусор"

    # --- 🔴 нет ссылки Mobzio там, где она нужна, - молчать нельзя ----------
    # Тихая подстановка прямой ссылки на WB выглядит как рабочий пост, но
    # теряет и диплинк, и метку источника: пропажу видно только через месяц
    # по пустой аналитике. У YouTube ссылки Mobzio нет ни для одного товара
    # (замер 02.09), и это должно быть слышно при сборке, а не потом.
    try:
        P.details(АККАУНТЫ, ТЕКСТ, артикул="43287163", file_ids=[7], rules=правила,
                  ozon="646406042", links=ссылки, товар=u"световой стол",
                  strict_links=True)
        raise AssertionError(u"отсутствие ссылки Mobzio обязано быть слышно")
    except P.НетСсылки as e:
        assert u"youtube" in str(e).lower(), e
        assert u"световой стол" in str(e), u"находка без товара - нечего заводить: %s" % e

    # без strict_links сборка идет, но ссылки не выдумываются
    мягко = P.details(АККАУНТЫ, ТЕКСТ, артикул="43287163", file_ids=[7], rules=правила,
                      ozon="646406042", links=ссылки, товар=u"световой стол")
    ют3 = {d["account_id"]: d for d in мягко}[999]["content"]
    assert "mobz.link" not in ют3 and "wildberries.ru" not in ют3, \
        u"чужую ссылку подставлять нельзя: перехода не будет там, где его ждут"

    # --- старое поведение сохраняется, когда справочника нет ---------------
    # (переходный режим: пока ссылки заведены не на все товары)
    без_справочника = P.details(АККАУНТЫ[:1], ТЕКСТ, артикул="43287163",
                                file_ids=[7], rules=правила)
    assert "wildberries.ru/catalog/43287163" in без_справочника[0]["content"]

    print("platforms selftest OK: ВК получает ссылку Mobzio, Instagram артикулы "
          "обоих маркетплейсов, YouTube заголовок, лимиты по площадке, "
          "чужой канал слышен, пропажа ссылки Mobzio слышна")


if __name__ == "__main__":
    selftest()
