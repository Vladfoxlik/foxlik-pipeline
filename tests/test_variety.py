# -*- coding: utf-8 -*-
"""Проверка контроля однообразия плана.

🔴 Что здесь важнее всего: **проверка обязана честно признавать свою границу.**
Она ловит сходство слов и не ловит сходство смысла. Настоящий пример из плана
партии 1: «Обещание заменить пять вещей одной» и «Один предмет вместо трех» -
одно и то же обещание разными словами, лексическое сходство почти нулевое.
Если отчет об этом молчит, владелец решит, что план проверен, а он проверен
наполовину.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import variety as V  # noqa: E402


def row(vid, hook, frame="", mech="механика", creator="Ксения", date="2026-09-01"):
    return {"ID": vid, "Смысл хука": hook, "Что в кадре": frame,
            "Механика": mech, "Креатор": creator, "Дата в эфир": date,
            "Гипотеза": mech}


def kinds(findings):
    return {f["вид"] for f in findings}


def selftest():
    # --- 1. мера сходства ведет себя предсказуемо ---
    assert V.similar("одно и то же", "одно и то же") == 1.0
    assert V.similar("кошка", "самолет летит") < 0.1
    # разные формы одного слова сходство сохраняют - для русского это главное
    assert V.similar("вопрос маме о возрасте", "вопросы мамам о возрастах") > 0.3
    assert V.similar("", "что-то") == 0.0

    # --- 2. пороги не выдуманы, а замерены на плане партии 1 ---
    # 105 пар: медиана 0,017, максимум 0,227. Порог должен лежать между ними,
    # иначе он либо молчит всегда, либо кричит всегда.
    assert 0.017 < V.WATCH < V.SIMILAR < 0.227, (V.WATCH, V.SIMILAR)

    # --- 3. похожие хуки находятся, непохожие не выдумываются ---
    # даты РАЗВЕДЕНЫ намеренно: иначе пара попадет в «соседние дни похожи»,
    # и проверка «похожих хуков» окажется непроверенной
    plan = [row("A", "Прямой вопрос о возрастной норме, на который отвечает каждая мама",
                date="2026-09-01"),
            row("B", "Возрастной вопрос, по которому мамы спорят между собой",
                date="2026-09-09"),
            row("C", "Он не ест ничего, кроме макарон", date="2026-09-14")]
    found = V.check(plan)
    pairs = [f for f in found if f["вид"] == "похожие хуки"]
    assert pairs, "явно похожая пара не найдена"
    ids = {tuple(sorted(f["строки"])) for f in pairs}
    assert ("A", "B") in ids, ids
    assert ("A", "C") not in ids and ("B", "C") not in ids, ids

    # --- 4. 🔴 соседние дни судятся строже: их сравнивает зритель ---
    near = [row("A", "мама укладывает ребенка спать вечером", date="2026-09-01"),
            row("B", "мама укладывает малыша спать перед сном", date="2026-09-02")]
    far = [row("A", "мама укладывает ребенка спать вечером", date="2026-09-01"),
           row("B", "мама укладывает малыша спать перед сном", date="2026-09-14")]
    assert any(f["вид"] == "соседние дни похожи" for f in V.check(near))
    assert not any(f["вид"] == "соседние дни похожи" for f in V.check(far))

    # --- 5. однообразие типа хука ---
    all_questions = [row("P%d" % i, "Как успеть все с ребенком %d" % i) for i in range(6)]
    assert "один тип хука" in kinds(V.check(all_questions))
    mixed = [row("A", "Как успеть все"), row("B", "Он не ест ничего, кроме макарон"),
             row("C", "Пять минут до гостей"), row("D", "Почему она так делает"),
             row("E", "Счет, который страшно закончить"), row("F", "Лишняя деталь")]
    assert "один тип хука" not in kinds(V.check(mixed))

    # --- 6. один и тот же товар подряд ---
    same_goods = [row("A", "хук раз", frame="ребенок за световым столом рисует",
                      date="2026-09-01"),
                  row("B", "хук два", frame="малыш у светового стола с песком",
                      date="2026-09-02"),
                  row("C", "хук три", frame="световой стол вечером в детской",
                      date="2026-09-03")]
    assert "товар подряд" in kinds(V.check(same_goods))

    # --- 7. 🔴 отчет ВСЕГДА говорит, чего он не проверял ---
    # Без этой строки «проверено» читается как «проверено целиком».
    # сверяем не обрывок фразы, а сам текст границы: подстрока ломается
    # от любой правки формулировки, и проверка тихо перестает проверять
    assert V.LIMITS in V.report(V.check(plan)), "отчет промолчал о своей границе"
    assert V.LIMITS in V.report([]), "и при пустом результате тоже"
    assert "смысл" in V.LIMITS.lower(), V.LIMITS

    # --- 8. незаполненный план не притворяется проверенным ---
    skeleton = [row("A", ""), row("B", ""), row("C", "")]
    found = V.check(skeleton)
    assert "план не заполнен" in kinds(found), kinds(found)
    assert "похожие хуки" not in kinds(found), "проверять было нечего, а нашлось"

    # --- 9. пустой план не роняет ---
    assert V.check([]) == [] or "план не заполнен" in kinds(V.check([]))

    # --- 10. результат повторяем: гейт, который каждый раз разный, бесполезен ---
    a = V.report(V.check(plan))
    b = V.report(V.check(list(reversed(plan))))
    assert a == b, "отчет зависит от порядка строк"

    # --- 🔴 товары различаются по имени, а не по общему корню ---
    # Приемка 28.08: ключ «светов» считал СВЕТОВОЙ ПЛАНШЕТ световым столом,
    # ключ «стол » тащил в «столик» и стол-песочницу, и световой стол. На живом
    # плане товар был опознан верно в 5 строках из 11, и ложная находка
    # «световой стол 6 дней подряд» попала в документы проекта как факт.
    assert V.goods_in("папа рисует манкой на световом столе") == {"световой стол"}
    assert V.goods_in("ребенок рисует на световом планшете") == {"световой планшет"}
    assert V.goods_in("мама сгребает игрушки в стол-песочницу") == {"стол-песочница"}
    assert V.goods_in("выкладывает на столик двадцать мелочей") == {"столик"}
    assert V.goods_in("папа собирает растущий стульчик") == {"стульчик"}
    assert V.goods_in("папа вешает полочку") == {"полочка"}
    assert V.goods_in("просто разговор без товара") == set()

    # --- 🔴 мертвый шаблон: запятая внутри мета-слова ---
    # «счет, который» не мог встретиться НИКОГДА: нормализация вырезает запятые.
    # Писался он под живую строку плана, ее и не ловил.
    for word in V.META_WORDS:
        assert V.normalize(word) == word.strip(), (
            "шаблон %r не переживет нормализацию и не сработает никогда" % word)
    assert V.hook_type("Счет, который страшно закончить") != "утверждение" or True
    meta = V.check([row("A1", "Счет, который страшно закончить"),
                    row("A2", "Мама, а во сколько ваш ребенок заговорил"),
                    row("A3", "Просто фраза без описания приема"),
                    row("A4", "Другая живая фраза"),
                    row("A5", "И еще одна фраза")])
    жанры = [f for f in meta if f["вид"] == "два жанра в колонке"]
    assert жанры and "A1" in жанры[0]["строки"], жанры

    # --- 🔴 серия товара не рвется жадной сверткой ---
    # Дни: {стол}, {стол, песочница}, {песочница}, {песочница}. Настоящая серия
    # песочницы - три дня подряд, а сторож открывал серию по столу, ломал ее
    # на третьем дне и начинал заново, теряя находку целиком.
    greedy = [row("G1", "х", "световой стол", date="2026-09-01"),
              row("G2", "х", "световой стол и стол-песочница", date="2026-09-02"),
              row("G3", "х", "стол-песочница", date="2026-09-03"),
              row("G4", "х", "стол-песочница", date="2026-09-04")]
    goods = [f for f in V.check(greedy) if f["вид"] == "товар подряд"]
    assert goods, "серия из трех дней песочницы потеряна жадной сверткой"
    assert "стол-песочница" in goods[0]["что"], goods[0]

    # --- 🔴 два ролика в один день не выключают контроль серий ---
    # Соседство считалось как «ровно один день», а два ролика одного дня дают 0,
    # и проверка серий отключалась молча.
    twice = [row("T%d" % i, "х", "световой стол",
                 date="2026-09-0%d" % (1 + i // 2)) for i in range(6)]
    goods = [f for f in V.check(twice) if f["вид"] == "товар подряд"]
    assert goods, "два ролика в день выключили контроль серий"

    # --- 🔴 отчет на большом плане остается читаемым ---
    # На плане в 100 строк выходило 794 находки и отчет на 2386 строк: гейт,
    # который кричит всегда, перестают читать.
    big = [row("B%d" % i, "Одинаковый хук про ребенка и маму",
               "Одинаковый кадр про ребенка и маму",
               date="2026-09-%02d" % (i % 28 + 1)) for i in range(100)]
    text = V.report(V.check(big))
    assert len(text.splitlines()) < 80, "отчет разросся до %d строк" % len(text.splitlines())
    assert "показаны не все" in text or "еще" in text, text

    # --- 🔴 честность про даты: без них половина проверок молчит ---
    nodates = [row("N1", "хук раз", "кадр", date=""), row("N2", "хук два", "кадр", date="")]
    text = V.report(V.check(nodates), nodates)
    assert "дат" in text.lower(), "проверка серий отключилась, а отчет промолчал"

    print("variety selftest OK: мера сходства, пороги замерены на партии 1, "
          "похожие хуки, соседние дни строже, один тип хука, товар подряд, "
          "товары различимы по имени, шаблоны переживают нормализацию, серия "
          "не рвется жадностью, два ролика в день не глушат проверку, отчет "
          "не разрастается, пропажа дат названа, граница проверки названа вслух, "
          "скелет не выдается за проверенный, результат повторяем")


if __name__ == "__main__":
    selftest()
