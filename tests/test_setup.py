# -*- coding: utf-8 -*-
u"""Проверка заливки плана в живую таблицу. Сеть не нужна.

🔴 Зачем набор появился (31.08). В листе ПЛАН лежала отмененная партия из 15 строк,
а рабочий файл после пересборки 30.08 - это 6 строк с теми же ID и другим содержанием.
`--plan` пропускает строку, если ID уже есть, и напечатал бы «добавлено новых: 0» -
это читается как «все уже залито». Партия ушла бы в работу по отмененному плану,
и ни одна сторона при этом не падает.

Тот же класс, что docx, разошедшийся с `.md`: правится один конец, второй молчит.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import setup as S  # noqa: E402


class FakeSheet:
    def __init__(self, rows, header=None):
        self.rows = list(rows)
        self.cleared = 0
        # 🔴 Настоящий лист берет ТОЛЬКО колонки своего заголовка
        # (lib/sheets.Sheet.append). Без этого заглушка принимала любые поля,
        # и проверки проходили на данных, которых в живой таблице не появится.
        self.header = header

    def read(self):
        return [dict(r) for r in self.rows]

    def clear(self, keep_header=True):
        self.cleared += 1
        self.rows = []

    def append(self, values):
        self.rows.append(dict(values))


АРТИКУЛЫ = {"световой стол": ["43287166"], "световой планшет": ["79693129"]}

# 🔴 В плане - только человеческий текст. Хвост со ссылкой или номером
# подставляет машина под каждую сеть (lib/platforms.py), правило от 31.08.
ФАЙЛ = [{"ID": "P1-01", "Креатор": "Ксения", "Товар": "световой стол",
         "Описание к посту": "новое описание"},
        {"ID": "P1-02", "Креатор": "Спартак", "Товар": "световой планшет",
         "Описание к посту": "другое описание"}]

ТАБЛИЦА_СТАРАЯ = [{"ID": "P1-01", "Креатор": "Спартак", "Товар": "световой стол",
                   "Описание к посту": ""},
                  {"ID": "P1-07", "Креатор": "Ксения", "Товар": "полка",
                   "Описание к посту": ""}]


def selftest():
    # --- 1. расхождение файла и таблицы называется вслух -------------------
    отчет = S.plan_diff(ФАЙЛ, ТАБЛИЦА_СТАРАЯ)
    assert отчет["новые"] == ["P1-02"], отчет
    assert отчет["лишние"] == ["P1-07"], u"строка есть в таблице, но не в файле"
    assert отчет["разошлись"] == ["P1-01"], u"один ID, разное содержание - молчать нельзя"

    # --- 2. совпадающий план не считается расхождением ---------------------
    ровно = S.plan_diff(ФАЙЛ, [dict(r) for r in ФАЙЛ])
    assert ровно["новые"] == [] and ровно["лишние"] == [] and ровно["разошлись"] == [], ровно

    # --- 3. 🔴 перезалив ставит в таблицу ровно то, что в файле -------------
    лист = FakeSheet(ТАБЛИЦА_СТАРАЯ)
    S.do_plan_replace(ФАЙЛ, лист, АРТИКУЛЫ)
    assert лист.cleared == 1, u"старые строки обязаны уйти, иначе останется отмененное"
    assert [r["ID"] for r in лист.rows] == ["P1-01", "P1-02"], лист.rows
    assert лист.rows[0]["Креатор"] == "Ксения", u"взято содержание файла, не таблицы"

    # --- 4. пустой файл не стирает таблицу ---------------------------------
    лист2 = FakeSheet(ТАБЛИЦА_СТАРАЯ)
    try:
        S.do_plan_replace([], лист2, АРТИКУЛЫ)
        raise AssertionError(u"пустым файлом таблицу стирать нельзя")
    except SystemExit:
        assert лист2.cleared == 0 and лист2.rows, u"таблица уже пострадала"

    # --- 5. 🔴 строка без описания к посту не доедет до эфира ---------------
    # такт с 31.08 такую строку откладывает: пустой пост хуже отказа. Значит
    # ловить это надо при заливке, а не в день публикации.
    без_описания = [{"ID": "P1-01", "Креатор": "Ксения", "Товар": "световой стол",
                     "Описание к посту": ""}]
    try:
        S.do_plan_replace(без_описания, FakeSheet([]), АРТИКУЛЫ)
        raise AssertionError(u"строка без описания обязана остановить заливку")
    except SystemExit as e:
        assert "P1-01" in str(e), e

    # --- 6б. 🔴 артикул в тексте плана - теперь ошибка (31.08) --------------
    # С появлением упаковки по площадкам хвост подставляется автоматически:
    # в ВК ссылкой, в Instagram номером. Артикул, вписанный в план руками,
    # уедет ВТОРЫМ - пост выйдет с номером дважды. Прогон это и показал.
    вручную = [{"ID": "P1-01", "Товар": "световой стол",
                "Описание к посту": u"Текст. 🛒 Артикул на WB: #43287166"}]
    дубли = S.plan_with_manual_article(вручную)
    assert дубли == ["P1-01"], дубли
    чисто = [{"ID": "P1-02", "Товар": "световой стол",
              "Описание к посту": u"Просто человеческий текст без номера"}]
    assert S.plan_with_manual_article(чисто) == []

    # --- 6. 🔴 подпись без артикула WB не уезжает -------------------------
    # Решение владельца 31.08: подпись ведет на артикул WB, как раньше. Забытый
    # артикул виден только после публикации, а переснять пост нельзя - место занято.
    # Замер 195 постов: артикул стоял у 65%, то есть забывали регулярно и вручную.
    артикулы = {"световой планшет": ["79693129"], "световой стол": ["43287163", "43287166"]}
    без_артикула = [{"ID": "P1-01", "Товар": "световой планшет",
                     "Описание к посту": "Хороший текст без номера"}]
    беда = S.plan_without_article(без_артикула, артикулы)
    assert беда == ["P1-01"], беда

    с_артикулом = [{"ID": "P1-01", "Товар": "световой планшет",
                    "Описание к посту": "Текст. Артикул на WB: #79693129"},
                   {"ID": "P1-02", "Товар": "световой стол",
                    "Описание к посту": "Текст. Артикул на WB: #43287166"}]
    assert S.plan_without_article(с_артикулом, артикулы) == []
    # ⚠️ Эта функция осталась от правила, отмененного вечером 31.08: артикул
    # больше не требуется в тексте, его ставит машина. Проверка сохранена -
    # решение владельца о канале может вернуться, и тогда правило понадобится.

    # 🔴 чужой артикул в подписи - тоже беда: покупатель уйдет не на тот товар
    чужой = [{"ID": "P1-03", "Товар": "световой планшет",
              "Описание к посту": "Текст. Артикул на WB: #43287166"}]
    assert S.plan_without_article(чужой, артикулы) == ["P1-03"], \
        u"артикул другого товара обязан считаться ошибкой"

    # товара нет в справочнике - молчать нельзя, но и падать незачем
    неизвестный = [{"ID": "P1-04", "Товар": "мольберт", "Описание к посту": "Текст"}]
    assert S.plan_without_article(неизвестный, артикулы) == ["P1-04"]

    # --- 7. 🔴 гейт артикула стоит ВНУТРИ заливки ---------------------------
    # Проверка, которая живет отдельной функцией и не вызывается из рабочего пути, -
    # это документ, а не гейт. Класс ошибки, на котором проект уже стоял (28.08).
    сномером = [{"ID": "P1-01", "Креатор": "Ксения", "Товар": "световой стол",
                 "Описание к посту": "текст 🛒 Артикул на WB: #43287166"}]
    лист5 = FakeSheet([])
    try:
        S.do_plan_replace(сномером, лист5, АРТИКУЛЫ)
        raise AssertionError("заливка пропустила вписанный руками артикул")
    except SystemExit as e:
        assert "P1-01" in str(e) and лист5.cleared == 0, e

    # --- 8. 🔴 колонки файла обязаны существовать в листе (31.08) -----------
    # Живой случай того же дня, найденный холостым прогоном. Лист ПЛАН заведен
    # по старой схеме: колонок «Описание к посту», «Хук», «Текст на экране» в нем
    # нет. Sheets.append берет только колонки заголовка - значит описания молча
    # пропали, а заливка отчиталась «переписано 6». Через день такт отложил бы
    # всю партию со словами «в ПЛАНЕ нет описания», и виноватым выглядел бы план.
    старый_лист = FakeSheet([], header=["ID", "Креатор", "Товар", "Статус"])
    try:
        S.do_plan_replace(ФАЙЛ, старый_лист, АРТИКУЛЫ)
        raise AssertionError("заливка в лист без нужных колонок обязана остановиться")
    except SystemExit as e:
        assert "Описание к посту" in str(e), e
        assert "--sheets" in str(e), u"находка без «что делать» - тупик: %s" % e
        assert старый_лист.cleared == 0, u"таблица уже очищена, а данные некуда класть"

    # лист со всеми колонками принимает заливку молча
    полный = FakeSheet([], header=["ID", "Креатор", "Товар", "Описание к посту"])
    S.do_plan_replace(ФАЙЛ, полный, АРТИКУЛЫ)
    assert len(полный.rows) == 2, полный.rows

    # --- 9. новые оси 02.09 присутствуют в обеих схемах --------------------
    # 🔴 «Роль товара» - ручка баланса репосты/подписки (замер 26.08),
    # «Ситуация» - код из методики, точный анти-дубль вместо лексического.
    for лист_имя in ("ПЛАН", "ПУБЛИКАЦИИ"):
        for кол in (u"Роль товара", u"Ситуация"):
            assert кол in S.LAYOUT[лист_имя], (
                u"%s: нет колонки «%s» - ось не доедет до учета" % (лист_имя, кол))

    # --- 10а. дефект 02.09: свежий lib/sheets.Sheet рождается с header=[]
    # (не None), и проверка «в листе нет колонок» в do_plan_replace молча
    # пропускалась целиком: «Смысл ролика» выпал из живой таблицы при отчете
    # об успехе. Ленивый лист повторяет настоящий: заголовок пуст до read().
    class ЛенивыйЛист(FakeSheet):
        def __init__(self, rows, header):
            FakeSheet.__init__(self, rows, header=[])
            self._настоящий = list(header)

        def read(self):
            self.header = list(self._настоящий)
            return FakeSheet.read(self)

    ленивый = ЛенивыйЛист([], header=["ID", "Креатор", "Товар"])
    try:
        S.do_plan_replace(ФАЙЛ, ленивый, АРТИКУЛЫ)
        assert False, u"заливка в лист без колонки файла обязана падать"
    except SystemExit as e:
        assert u"нет колонок" in str(e), e

    # у ленивого листа СО всеми колонками заливка проходит
    ленивый_полный = ЛенивыйЛист(
        [], header=["ID", "Креатор", "Товар", "Описание к посту"])
    S.do_plan_replace(ФАЙЛ, ленивый_полный, АРТИКУЛЫ)
    assert len(ленивый_полный.rows) == 2, ленивый_полный.rows

    # --- 10. «Смысл ролика» (обратная связь владельца 02.09) ---------------
    # 🔴 Сюжет начинается со смысла: что зритель должен понять о товаре.
    # Без записанной колонки смысл живет в голове автора, и проверка
    # «хук и сцена доносят смысл» становится невозможной. Кейс, оплативший
    # правило: хук про кофе, из которого польза товара не читалась вовсе.
    план_колонки = S.LAYOUT["ПЛАН"]
    assert u"Смысл ролика" in план_колонки, u"ПЛАН: нет колонки «Смысл ролика»"
    assert (план_колонки.index(u"Смысл ролика")
            == план_колонки.index(u"Ситуация") + 1), (
        u"«Смысл ролика» стоит сразу после «Ситуации»: смысл порождает сцену")
    assert u"Смысл ролика" not in S.LAYOUT["ПУБЛИКАЦИИ"], (
        u"смысл - инструмент генерации, в учет публикаций не едет")

    # 🔴 Аудит 02.09: «Статус=ЧЕРНОВИК» обещан комментарием схемы как гейт,
    # но не фильтровался нигде - генераторские черновики уехали бы в форму.
    смешанный = [{"ID": "P9-01", "Креатор": "Ксения", "Хук": "хук раз",
                  "Статус": "ЧЕРНОВИК"},
                 {"ID": "P9-02", "Креатор": "Спартак", "Хук": "хук два",
                  "Статус": "УТВЕРЖДЕН"}]
    опции = S.form_options(смешанный)
    assert len(опции) == 1 and "P9-02" in опции[0],         "черновик не должен попадать в форму: %r" % опции

    # 🔴 Аудит 02.09: plan_diff кричал «разошлись: 14 из 14» из-за формата
    # даты («2026-09-04» в файле против серийного «46269» в листе) - настоящая
    # тревога утонула бы в привычном шуме.
    отчет9 = S.plan_diff(
        [{"ID": "P9-03", "Дата в эфир": "2026-09-04", "Хук": "х"}],
        [{"ID": "P9-03", "Дата в эфир": "46269", "Хук": "х"}])
    assert отчет9["разошлись"] == [],         "одинаковая дата в разных представлениях - не расхождение: %r" % отчет9

    print("setup selftest OK: расхождение видно, перезалив заменяет целиком, "
          "пустой файл не стирает, строка без описания не проходит, "
          "подпись без своего артикула WB не уезжает")


if __name__ == "__main__":
    selftest()
