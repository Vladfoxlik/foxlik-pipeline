# -*- coding: utf-8 -*-
u"""Проверка заливки плана в живую таблицу. Сеть не нужна.

🔴 Зачем набор появился (31.08). В листе ПЛАН лежала отмененная партия из 15 строк,
а рабочий файл после пересборки 30.08 - это 6 строк с теми же ID и другим содержанием.
`--plan` пропускает строку, если ID уже есть, и напечатал бы «добавлено новых: 0» -
это читается как «все уже залито». Партия ушла бы в работу по отмененному плану,
и ни одна сторона при этом не падает.

Тот же класс, что docx, разошедшийся с `.md`: правится один конец, второй молчит.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import setup as S  # noqa: E402


class FakeSheet:
    def __init__(self, rows):
        self.rows = list(rows)
        self.cleared = 0

    def read(self):
        return [dict(r) for r in self.rows]

    def clear(self, keep_header=True):
        self.cleared += 1
        self.rows = []

    def append(self, values):
        self.rows.append(dict(values))


ФАЙЛ = [{"ID": "P1-01", "Креатор": "Ксения", "Описание к посту": "новое"},
        {"ID": "P1-02", "Креатор": "Спартак", "Описание к посту": "новое"}]

ТАБЛИЦА_СТАРАЯ = [{"ID": "P1-01", "Креатор": "Спартак", "Описание к посту": ""},
                  {"ID": "P1-07", "Креатор": "Ксения", "Описание к посту": ""}]


def selftest():
    # --- 1. расхождение файла и таблицы называется вслух -------------------
    отчет = S.plan_diff(ФАЙЛ, ТАБЛИЦА_СТАРАЯ)
    assert отчет["новые"] == ["P1-02"], отчет
    assert отчет["лишние"] == ["P1-07"], u"строка есть в таблице, но не в файле"
    assert отчет["разошлись"] == ["P1-01"], u"один ID, разное содержание - молчать нельзя"

    # --- 2. совпадающий план не считается расхождением ---------------------
    ровно = S.plan_diff(ФАЙЛ, [dict(r) for r in ФАЙЛ])
    assert ровно["новые"] == [] and ровно["лишние"] == [] and ровно["разошлись"] == [], ровно

    # --- 3. 🔴 перезалив ставит в таблицу ровно то, что в файле -------------
    лист = FakeSheet(ТАБЛИЦА_СТАРАЯ)
    S.do_plan_replace(ФАЙЛ, лист)
    assert лист.cleared == 1, u"старые строки обязаны уйти, иначе останется отмененное"
    assert [r["ID"] for r in лист.rows] == ["P1-01", "P1-02"], лист.rows
    assert лист.rows[0]["Креатор"] == "Ксения", u"взято содержание файла, не таблицы"

    # --- 4. пустой файл не стирает таблицу ---------------------------------
    лист2 = FakeSheet(ТАБЛИЦА_СТАРАЯ)
    try:
        S.do_plan_replace([], лист2)
        raise AssertionError(u"пустым файлом таблицу стирать нельзя")
    except SystemExit:
        assert лист2.cleared == 0 and лист2.rows, u"таблица уже пострадала"

    # --- 5. 🔴 строка без описания к посту не доедет до эфира ---------------
    # такт с 31.08 такую строку откладывает: пустой пост хуже отказа. Значит
    # ловить это надо при заливке, а не в день публикации.
    без_описания = [{"ID": "P1-01", "Креатор": "Ксения", "Описание к посту": ""}]
    try:
        S.do_plan_replace(без_описания, FakeSheet([]))
        raise AssertionError(u"строка без описания обязана остановить заливку")
    except SystemExit as e:
        assert "P1-01" in str(e), e

    print("setup selftest OK: расхождение видно, перезалив заменяет целиком, "
          "пустой файл не стирает, строка без описания не проходит")


if __name__ == "__main__":
    selftest()
