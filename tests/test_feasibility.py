# -*- coding: utf-8 -*-
"""Проверка выполнимости плана: может ли назначенный креатор это снять.

🔴 Чем вскрылась нужда. Замер 28.08 на живом плане партии 1: у Спартака сын
около года и один товар из наших, а план требовал от него шести разных товаров,
говорящего ребенка и сцену с дочерью. Снимаемой оказалась **одна строка из семи**.

Генератор знает механику, дату и ИМЯ креатора. Про самого креатора он не знает
ничего: план оптимизирован под измеримость и слеп к выполнимости. Гейт однообразия
это тоже не ловит - он ищет повторы, а не невозможность.

Почему это условие ЗАМЕРА, а не удобство: если строку нельзя снять, ее переснимет
другой человек или ее не будет вовсе. И то и другое ломает раскладку «оба креатора
внутри каждой гипотезы», ради которой партия и строится, - разницу механик снова
станет не отличить от разницы людей.
"""
import io
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import feasibility as F  # noqa: E402

ПРОФИЛИ = ("Креатор\tКто в кадре\tПол ребенка\tВозраст месяцев\tУмеет\tТовары\tПодтверждено\n"
           "Спартак\tпапа\tмальчик\t12\tдержит предмет\tсветовой планшет\tнет\n"
           "Ксения\tмама\tдевочка\t24\tходит, говорит\tсветовой стол, столик\tда\n")


def row(vid, creator, frame, hook=""):
    return {"ID": vid, "Креатор": creator, "Что в кадре": frame,
            "Смысл хука": hook, "Механика": "м", "Дата в эфир": "2026-09-01"}


def selftest():
    профили = F.read_profiles(io.StringIO(ПРОФИЛИ))
    assert set(профили) == {"Спартак", "Ксения"}, профили
    assert профили["Спартак"]["возраст"] == 12
    assert "световой планшет" in профили["Спартак"]["товары"]

    # --- 1. 🔴 товара нет на руках ---
    # Живой случай: план требовал от Спартака шести разных товаров.
    f = F.check([row("P1-05", "Спартак", "папа собирает растущий стульчик")], профили)
    assert f and "стульчик" in f[0]["что"], f
    assert f[0]["строки"] == ["P1-05"], f

    # тот же товар у того, у кого он есть, находкой не считается
    assert not F.check([row("P1-13", "Ксения", "ребенок за световым столом")], профили)

    # --- 2. 🔴 пол ребенка не тот ---
    # P1-01 была написана про дочь, а у Спартака сын. Это не придирка: сцена
    # «дочь не отпускает папу» с сыном - другой ролик, и снимать его нечем.
    f = F.check([row("P1-01", "Спартак", "дочь не отпускает папу в дверях")], профили)
    assert f and ("дочь" in f[0]["что"] or "пол" in f[0]["что"].lower()), f

    # --- 3. 🔴 ребенок не умеет того, что требует кадр ---
    f = F.check([row("P1-09", "Спартак", "ребенок рассказывает, как прошел день")],
                профили)
    assert f, "говорящий ребенок у годовалого - это невыполнимо"
    f = F.check([row("P1-12", "Спартак", "ребенок идет в детский сад сам")], профили)
    assert f, "годовалый не ходит в сад"

    # у Ксении двухлетка - те же строки выполнимы
    assert not F.check([row("P1-09", "Ксения", "ребенок рассказывает, как прошел день")],
                       профили)

    # --- 4. неизвестный креатор: молчать нельзя, но и обвинять не в чем ---
    f = F.check([row("P1-20", "Новенький", "что угодно в кадре")], профили)
    assert f and "профил" in f[0]["что"].lower(), f

    # --- 5. 🔴 непроверенный профиль помечается отдельно ---
    # Все, что мы знаем о Спартаке, - со слов владельца. Строить на этом план
    # можно, но выдавать это за факт нельзя.
    text = F.report(F.check([row("P1-05", "Спартак", "нужен стульчик")], профили),
                    профили)
    assert "не подтверж" in text.lower(), text
    assert "Спартак" in text

    # --- 6. пустой кадр не порождает находок: проверять еще нечего ---
    assert not F.check([row("P1-01", "Спартак", "")], профили)

    # --- 7. отчет всегда говорит, чего проверка НЕ видит ---
    assert F.LIMITS in F.report([], профили)
    assert "обстанов" in F.LIMITS.lower() or "свет" in F.LIMITS.lower()

    # --- 8. 🔴 доказательство, что проверка вообще способна ловить ---
    # Ноль находок одинаково выглядит как «все снимаемо» и как «проверка молчит».
    заведомо = [row("X1", "Спартак", "папа и дочь собирают стол-песочницу, "
                                     "дочь рассказывает стишок")]
    f = F.check(заведомо, профили)
    assert len(f) >= 2, "проверка не поймала заведомо невозможную строку: %s" % f

    print("feasibility selftest OK: товар на руках, пол ребенка, умения по возрасту, "
          "неизвестный креатор, непроверенный профиль помечен, пустой кадр "
          "не судится, граница названа, проверка доказана заведомым случаем")


if __name__ == "__main__":
    selftest()
