# -*- coding: utf-8 -*-
"""Проверка выполнимости плана: может ли назначенный креатор это снять.

🔴 Чем вскрылась нужда. Замер 28.08 на живом плане партии 1: у Спартака сын
около года и один товар из наших, а план требовал от него шести разных товаров,
говорящего ребенка и сцену с дочерью. Снимаемой оказалась **одна строка из семи**.

Генератор знает механику, дату и ИМЯ креатора. Про самого креатора он не знает
ничего: план оптимизирован под измеримость и слеп к выполнимости. Гейт однообразия
это тоже не ловит - он ищет повторы, а не невозможность.

Почему это условие ЗАМЕРА, а не удобство: если строку нельзя снять, ее переснимет
другой человек или ее не будет вовсе. И то и другое ломает раскладку «оба креатора
внутри каждой гипотезы», ради которой партия и строится, - разницу механик снова
станет не отличить от разницы людей.
"""
import io
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import feasibility as F  # noqa: E402

ПРОФИЛИ = ("Креатор\tКто в кадре\tПол ребенка\tВозраст месяцев\tУмеет\tТовары\tПодтверждено\n"
           "Спартак\tпапа\tмальчик\t12\tдержит предмет\tсветовой планшет\tнет\n"
           "Ксения\tмама\tдевочка\t24\tходит, говорит\tсветовой стол, столик\tда\n")


def row(vid, creator, frame, hook="", screen=""):
    return {"ID": vid, "Креатор": creator, "Что в кадре": frame,
            "Хук": hook, "Текст на экране": screen,
            "Механика": "м", "Дата в эфир": "2026-09-01"}


def selftest():
    профили = F.read_profiles(io.StringIO(ПРОФИЛИ))
    assert set(профили) == {"Спартак", "Ксения"}, профили
    assert профили["Спартак"]["дети"][0]["возраст"] == 12
    assert "световой планшет" in профили["Спартак"]["товары"]

    # --- 1. 🔴 товара нет на руках ---
    # Живой случай: план требовал от Спартака шести разных товаров.
    f = F.check([row("P1-05", "Спартак", "папа собирает растущий стульчик")], профили)
    assert f and "стульчик" in f[0]["что"], f
    assert f[0]["строки"] == ["P1-05"], f

    # тот же товар у того, у кого он есть, находкой не считается
    assert not F.check([row("P1-13", "Ксения", "ребенок за световым столом")], профили)

    # --- 2. 🔴 пол ребенка не тот ---
    # P1-01 была написана про дочь, а у Спартака сын. Это не придирка: сцена
    # «дочь не отпускает папу» с сыном - другой ролик, и снимать его нечем.
    f = F.check([row("P1-01", "Спартак", "дочь не отпускает папу в дверях")], профили)
    assert f and ("дочь" in f[0]["что"] or "пол" in f[0]["что"].lower()), f

    # --- 3. 🔴 ребенок не умеет того, что требует кадр ---
    f = F.check([row("P1-09", "Спартак", "ребенок рассказывает, как прошел день")],
                профили)
    assert f, "говорящий ребенок у годовалого - это невыполнимо"
    f = F.check([row("P1-12", "Спартак", "ребенок идет в детский сад сам")], профили)
    assert f, "годовалый не ходит в сад"

    # у Ксении двухлетка - те же строки выполнимы
    assert not F.check([row("P1-09", "Ксения", "ребенок рассказывает, как прошел день")],
                       профили)

    # --- 4. неизвестный креатор: молчать нельзя, но и обвинять не в чем ---
    f = F.check([row("P1-20", "Новенький", "что угодно в кадре")], профили)
    assert f and "профил" in f[0]["что"].lower(), f

    # --- 5. 🔴 непроверенный профиль помечается отдельно ---
    # Все, что мы знаем о Спартаке, - со слов владельца. Строить на этом план
    # можно, но выдавать это за факт нельзя.
    text = F.report(F.check([row("P1-05", "Спартак", "нужен стульчик")], профили),
                    профили)
    assert "не подтверж" in text.lower(), text
    assert "Спартак" in text

    # --- 6. пустой кадр не порождает находок: проверять еще нечего ---
    assert not F.check([row("P1-01", "Спартак", "")], профили)

    # --- 7. отчет всегда говорит, чего проверка НЕ видит ---
    assert F.LIMITS in F.report([], профили)
    assert "обстанов" in F.LIMITS.lower() or "свет" in F.LIMITS.lower()

    # --- 8. 🔴 доказательство, что проверка вообще способна ловить ---
    # Ноль находок одинаково выглядит как «все снимаемо» и как «проверка молчит».
    заведомо = [row("X1", "Спартак", "папа и дочь собирают стол-песочницу, "
                                     "дочь рассказывает стишок")]
    f = F.check(заведомо, профили)
    assert len(f) >= 2, "проверка не поймала заведомо невозможную строку: %s" % f

    # --- 9. 🔴 у одного креатора может быть НЕСКОЛЬКО детей ---
    # Живой случай 29.08: у Ксении сын 1.5 года и дочь 4 лет. Пока профиль
    # хранил одного ребенка на креатора, вторая строка молча затирала первую -
    # и сцена с полуторагодовалым проходила проверку по возрасту четырехлетки.
    # Это тихий дефект: он не падает, он одобряет невыполнимое.
    двое = ("Креатор\tКто в кадре\tРебенок\tПол ребенка\tВозраст месяцев\tУмеет\tТовары\tВторой взрослый\tОператор\tПодтверждено\n"
            "Ксения\tмама\tсын\tмальчик\t18\tделает сам не всегда\tполка\tмуж\tштатив\tда\n"
            "Ксения\tмама\tдочь\tдевочка\t48\tможет все\tполка\tмуж\tштатив\tда\n"
            "Спартак\tпапа\tдочь\tдевочка\t11\tходит, говорит слова\tсветовой планшет, полка\tжена\tжена\tда\n")
    пр2 = F.read_profiles(io.StringIO(двое))
    assert F.детей(пр2, "Ксения") == 2, "оба ребенка должны сохраниться: %s" % пр2

    # сцена под старшую дочь выполнима - есть кому сыграть
    assert not F.check([row("D1", "Ксения", "дочь рассказывает, как прошел день")], пр2)
    # сцена под сына требует речи предложениями, а ему 18 месяцев
    f = F.check([row("D2", "Ксения", "сын рассказывает, как прошел день")], пр2)
    assert f, "у полуторагодовалого сына связной речи нет - это находка"
    assert "сын" in f[0]["что"] or "18" in f[0]["что"], f
    # у Спартака дочери 11 месяцев: та же сцена невыполнима, хотя пол совпал
    f = F.check([row("D3", "Спартак", "дочь рассказывает, как прошел день")], пр2)
    assert f, "11 месяцев - говорить предложениями рано, совпадения пола мало"

    # --- 9б. 🔴 слово родителя сильнее возрастной таблицы ---
    # Живой случай 29.08: Спартак написал, что дочь в 11 месяцев ходит,
    # а проверка забраковала сцену по норме «ходит с 15 месяцев». Пороги нужны,
    # чтобы отсеять заведомо невозможное, а не чтобы спорить с родителем
    # о развитии его ребенка. Что названо в «Умеет» - то ребенок умеет.
    ранний = ("Креатор\tКто в кадре\tРебенок\tПол ребенка\tВозраст месяцев\tУмеет\tТовары\tВторой взрослый\tОператор\tПодтверждено\n"
              "Спартак\tпапа\tдочь\tдевочка\t11\tсидит, ползает, стоит, ходит, говорит слова\tполка\tжена\tжена\tда\n")
    пр4 = F.read_profiles(io.StringIO(ранний))
    assert not F.check([row("R1", "Спартак", "дочь идет к полке")], пр4), \
        "родитель сказал, что ходит - таблица возрастов это не отменяет"
    # но «говорит слова» - это не связная речь: сцена с рассказом все равно находка
    f = F.check([row("R2", "Спартак", "дочь рассказывает, как прошел день")], пр4)
    assert f, "«говорит слова» не равно «говорит предложениями»"

    # --- 9в. 🔴 действие взрослого не приписывать ребенку ---
    # Живой случай 29.08 на плане партии 1: две находки из трех оказались
    # ложными. «Папа рисует на планшете, дочь стирает ладонью» - рисует ПАПА,
    # а проверка требовала от 11-месячной дочери навыка «сидит за столом».
    # Гейт, который заваливает нормальные строки, перестают читать - и он
    # пропустит настоящую находку вместе с шумом.
    мл = ("Креатор\tКто в кадре\tРебенок\tПол ребенка\tВозраст месяцев\tУмеет\tТовары\tВторой взрослый\tОператор\tПодтверждено\n"
          "Спартак\tпапа\tдочь\tдевочка\t11\tсидит, ползает, стоит, ходит\tсветовой планшет, полка\tжена\tжена\tда\n")
    пр5 = F.read_profiles(io.StringIO(мл))
    assert not F.check([row("S1", "Спартак",
        "папа рисует на световом планшете машинку, дочь стирает ладонью")], пр5), \
        "рисует папа, а не дочь - это не находка"
    assert not F.check([row("S2", "Спартак",
        "папа собирает полку, дочь рядом вытаскивает книги")], пр5), \
        "собирает папа"
    # но если рисует сам ребенок - находка остается
    f = F.check([row("S3", "Спартак", "дочь сидит за столом и рисует")], пр5)
    assert f, "вот тут действие у ребенка, и ему 11 месяцев"

    # --- 10. 🔴 второй взрослый в кадре: этого требует гипотеза «папа» ---
    # Вторая гипотеза партии 1 построена на приеме «папа» и без второго
    # взрослого не снимается вовсе. Раньше проверка этого не видела совсем.
    одиночка = ("Креатор\tКто в кадре\tРебенок\tПол ребенка\tВозраст месяцев\tУмеет\tТовары\tВторой взрослый\tОператор\tПодтверждено\n"
                "Одна\tмама\tдочь\tдевочка\t36\tвсе\tполка\t\tштатив\tда\n")
    пр3 = F.read_profiles(io.StringIO(одиночка))
    f = F.check([row("V1", "Одна", "мама и папа вдвоем собирают полку")], пр3)
    assert f and "взросл" in f[0]["что"].lower(), \
        "второго взрослого в профиле нет - сцену вдвоем снять некем: %s" % f
    # а у Ксении муж есть - та же сцена проходит
    assert not F.check([row("V2", "Ксения", "мама и папа вдвоем собирают полку")], пр2)

    # --- 11. 🔴 второй взрослый - это КОНКРЕТНЫЙ человек, а не «кто-нибудь» ---
    # Живой случай 29.08: владелец спросил, кто снимет сцену «подарок глазами
    # бабушки». Проверка молчала: у обоих креаторов второй взрослый есть
    # (жена и муж), и она считала, что сцена снимаема. Но бабушки нет ни
    # у кого, и роль сыграть некому - это выяснилось бы на площадке.
    f = F.check([row("G1", "Ксения", "бабушка приносит коробку, внук распаковывает")],
                пр2)
    assert f, "бабушки нет в профиле - сцену снять некем"
    assert "бабушк" in f[0]["что"].lower(), f
    # а сцену с мужем Ксения снимет: он и есть ее второй взрослый
    assert not F.check([row("G2", "Ксения", "папа и мама вдвоем у стола")], пр2)

    # --- 🔴 два ложных срабатывания, найденных на живом плане 30.08 ---
    # Оба одного класса: слово нашлось, а смысла за ним нет. Ложная находка
    # выбивает годную строку, автор ее переписывает - и новый текст рождает
    # новое нарушение. Этот цикл мы уже проходили с ограничениями на выходе.

    # 1. отрицание: «он не торопит и НЕ ГОВОРИТ ничего» - это про взрослого,
    #    и вдобавок отрицание. Читалось как требование речи от 11-месячной.
    молчит = row("F1", "Спартак",
                 "Папа ведет пальцем по песку, дочь повторяет движение "
                 "ладонью. Он не торопит и не говорит ничего")
    assert not [x for x in F.check([молчит], профили) if "возраст" in x["вид"]], \
        "«не говорит» прочитано как требование говорить"

    # 2. упоминание вне кадра: «три вещи уехали К БАБУШКЕ» - бабушки в кадре нет,
    #    она вообще не участвует. Читалось как «нужна бабушка на съемке».
    бабушке = row("F2", "Спартак",
                  "Папа выносит из комнаты мольберт и доску, три вещи уехали "
                  "к бабушке, на их место встает один стол")
    assert not [x for x in F.check([бабушке], профили) if "взросл" in x["вид"]], \
        "«уехали к бабушке» прочитано как роль в кадре"

    # ...а настоящее требование по-прежнему ловится
    правда = row("F3", "Спартак", "Дочь говорит слово и показывает пальцем")
    assert [x for x in F.check([правда], профили) if "возраст" in x["вид"]], \
        "проверка речи не должна была замолчать совсем"

    # --- 🔴 надпись на экране не задает состав кадра (30.08) ---
    # Живой случай: текст на экране «БАБУШКИ, ЭТО ДЛЯ ВАС» - обращение к тем,
    # кто дарит, а в кадре папа с дочерью. Проверка склеивала кадр, хук
    # и надпись в одну строку и требовала бабушку на съемке.
    # Класс тот же, что «уехали к бабушке»: слово есть, роли в кадре нет.
    надпись = row("S1", "Спартак", "папа с дочерью сидят на полу у планшета",
                  screen=u"БАБУШКИ, ЭТО ДЛЯ ВАС")
    f = F.check([надпись], профили)
    assert not [x for x in f if u"бабушк" in x["что"].lower()], (
        u"надпись принята за состав кадра: %s" % f)

    # ...и контроль: та же бабушка В КАДРЕ по-прежнему ловится
    в_кадре = row("S2", "Спартак", u"бабушка достает планшет из коробки")
    f2 = F.check([в_кадре], профили)
    assert [x for x in f2 if u"бабушк" in x["что"].lower()], (
        u"проверка перестала ловить настоящую бабушку в кадре: %s" % f2)


    print("feasibility selftest OK: товар на руках, пол ребенка, умения по возрасту, "
          "неизвестный креатор, непроверенный профиль помечен, пустой кадр "
          "не судится, граница названа, проверка доказана заведомым случаем, "
          "несколько детей у одного креатора, второй взрослый в кадре")


if __name__ == "__main__":
    selftest()
