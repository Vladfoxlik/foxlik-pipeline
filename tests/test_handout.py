def проверить_памятку():
    u"""🔴 Ролевой прогон 02.09: в таблице негде узнать, КУДА сдавать ролик.

    Прочел таблицу как креатор, которому снимать завтра, и споткнулся на том,
    чего в ней нет вовсе: ссылки на форму сдачи, требований к файлу, что делать
    при вопросе по строке. Задание без этого не работает: человек снимет и не
    поймет, куда деть готовое.
    """
    блоки = H.памятка()
    # 🔴 Памятка - не простыня строк, а блоки со стилем: заголовок, текст,
    # предупреждение. Замечание владельца 02.09 на первую версию: «нет никакого
    # форматирования, все просто вставлено в ячейки».
    assert all(isinstance(b, tuple) and len(b) == 2 for b in блоки), блоки
    стили = {с for с, _ in блоки}
    assert {u"h1", u"h2", u"text"} <= стили, u"нет иерархии - все одним стилем: %s" % стили
    assert u"warn" in стили, u"важное ничем не выделено"
    # текст пункта идет одной ячейкой, а не разрезан переносами на обрывки
    assert [т for с, т in блоки if с == u"text" and len(т) > 60], \
        u"текст разбит на куски - в таблице это выглядит обрывками строк"
    целиком = u"\n".join(т for _, т in блоки)
    assert u"forms.gle" in целиком or u"docs.google.com/forms" in целиком, \
        u"нет ссылки на форму сдачи - человек снимет и не поймет, куда деть ролик"
    assert u"вертикал" in целиком.lower(), u"не сказано, что видео вертикальное"
    # 🔴 Про галочку почты в форме: без нее форма не отправляется вовсе,
    # и это самая частая точка, где человек застревает молча (замер 31.08).
    assert u"почт" in целиком.lower(), u"про обязательную почту в форме не сказано"
    assert u"№" in целиком, u"не сказано, что при сдаче нужен номер строки"
    # памятка - это ровно то, что уходит человеку: служебного в ней быть не должно
    for слово in (u"гипотез", u"репост", u"сигнал", u"механик"):
        assert слово not in целиком.lower(), u"служебное слово «%s» в памятке" % слово


