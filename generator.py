def _rebalance(counts):
    """Не дает одной гипотезе занять больше половины партии.

    🔴 Замер на своем же коде 27.08: при наивном чередовании единственная
    полезная механика получила 10 слотов из 15 и легла **пятью подряд** в конце.
    Для замера это терпимо, для ленты - нет: зритель видит пять почти одинаковых
    роликов, а креатор снимает их под копирку.

    Математика простая: чтобы ни одна пара соседей не совпала, самая большая
    группа не может быть больше половины (с округлением вверх). Лишнее уходит
    в слоты креаторов - их гипотезы разные по определению, это самое безопасное
    место для остатка.

    🔴 Правка 28.08 по итогам приемки. Раньше остаток уходил в слоты креатора
    без всякого потолка, и при одной пригодной механике квота раздувалась
    с пяти строк до семи из пятнадцати. У этих строк механика пустая, а словарь
    пустые механики пропускает: партия из 15 роликов отдавала памяти петли восемь.
    Дыра в памяти хуже однообразной ленты - она невидима и убивает следующий цикл,
    тогда как однообразие видно глазом и о нем сказано в сводке.

    Поэтому квота держится в своем потолке (один слот из трех), а излишек
    остается у механики. Если из-за этого гипотеза идет подряд - об этом
    предупреждает сводка, а не прячет раздуванием квоты.
    """
    counts = {k: v for k, v in counts.items() if v > 0}
    dropped = 0
    quota_cap = counts.get(None, 0)         # квота не растет сверх своего потолка
    while counts:
        total = sum(counts.values())
        limit = (total + 1) // 2
        big = max(counts, key=lambda k: counts[k])
        if counts[big] <= limit:
            break
        excess = counts[big] - limit
        room = quota_cap - counts.get(None, 0)
        if None in counts and big is not None and room > 0:
            move = min(excess, room)
            counts[big] -= move
            counts[None] += move
            if move < excess:
                break                       # дальше двигать некуда - оставляем как есть
        else:
            break
    return counts, dropped


def _arrange(counts):
    """Порядок, в котором одинаковые гипотезы стоят как можно дальше друг от друга.

    Наивный круг разваливается, как только группы не равны.

    🔴 Правка 28.08: жадный выбор «у кого осталось больше» давал ПЯТЬ роликов
    подряд, когда пригодная механика одна (10 слотов против 5 квоты). Раньше это
    прикрывалось раздуванием квоты креатора, а квоту трогать нельзя - у ее строк
    механика пустая, и они выпадают из памяти петли.

    Теперь раскладка идет от обратного: самая большая группа заранее делится
    на равные куски по числу промежутков между остальными роликами. При 10 и 5
    это дает серии по два (математический минимум ceil(10/6) = 2) вместо пяти,
    а при равных группах - обычное чередование без серий вовсе.
    """
    counts = {k: v for k, v in counts.items() if v > 0}
    if not counts:
        return []
    # самая большая группа - ее и разносим; остальные идут разделителями
    big = max(counts, key=lambda k: (counts[k], str(k)))
    others = []
    left = {k: v for k, v in counts.items() if k != big}
    while sum(left.values()) > 0:                    # разделители чередуем сами
        for k in sorted(left, key=lambda k: (-left[k], str(k))):
            if left[k] > 0:
                others.append(k)
                left[k] -= 1
                break
    gaps = len(others) + 1                           # промежутков на один больше
    total = counts[big]
    sizes = [total // gaps + (1 if i < total % gaps else 0) for i in range(gaps)]
    order = []
    for i, size in enumerate(sizes):
        order += [big] * size
        if i < len(others):
            order.append(others[i])
    return order


def longest_run(labels):
    """Самая длинная серия одинаковых подряд. Нужна и коду, и проверкам."""
    best = run = 0
    prev = object()
    for x in labels:
        run = run + 1 if x == prev else 1
        prev = x
        best = max(best, run)
    return best


def propose(dictionary, plan, creators, start, size=BATCH_SIZE):
    """Черновик плана: каркас строк без содержания.

    Пустой словарь дает пустой план - сочинять партию не на чем, и молча
    выдумать ее было бы хуже, чем не выдать ничего.
    """
    picks = usable(dictionary)
    if not picks:
        return []
    creators = list(creators) or ["не назначен"]

    # 🔴 Один слот из трех - под гипотезу креатора. Она не соревнуется с гипотезой
    # из данных: у той всегда есть цифра в обосновании, и креатор проигрывает
    # всегда. Через два цикла креаторы перестанут предлагать.
    creator_slots = size // CREATOR_QUOTA
    data_slots = size - creator_slots

    # сколько гипотез уместится, чтобы на каждую было не меньше четырех
    room = max(1, data_slots // MIN_PER_HYPOTHESIS)
    chosen = picks[:min(len(picks), MAX_HYPOTHESES - 1, room)]
    if not chosen:
        chosen = picks[:1]

    # раздаем слоты поровну, остаток - первым по полезности
    per = {mech: data_slots // len(chosen) for mech, _ in chosen}
    for i in range(data_slots - sum(per.values())):
        per[chosen[i % len(chosen)][0]] += 1

    counts = {mech: per[mech] for mech, _ in chosen}
    facts = {mech: fact for mech, fact in chosen}
    counts[None] = creator_slots
    facts[None] = "квота креаторов: их гипотеза проверяется только в плане"

    counts, dropped = _rebalance(counts)
    order = [(mech, facts[mech]) for mech in _arrange(counts)]

    number = next_batch_number(plan)
    dates = _dates(start, len(order))
    # 🔴 Счетчик СВОЙ у каждой гипотезы, а не общий по дням.
    #
    # Замер на своем же коде 27.08: при общем счетчике и чередовании гипотез
    # четность склеивается - «папа» целиком достался Ксении, слоты креатора
    # целиком Спартаку. Это ровно тот confound, ради которого все затевалось:
    # разницу механик стало бы не отличить от разницы людей (из аккаунта
    # креатора пересылают вчетверо чаще, 2,11 против 0,50).
    # 🔴 Правка 28.08. Счетчик, стартующий с первого креатора в КАЖДОЙ гипотезе,
    # давал перекос: при трех гипотезах первый по алфавиту брал 9 роликов из 15
    # и не видел пяти дней недели из семи - человек оказывался привязан к дням,
    # то есть вместо убранного confound появлялся новый.
    #
    # Теперь выбор двойной: внутри гипотезы креатор обязан смениться, а из тех,
    # кто может, берется наименее загруженный по всей партии. Это держит и
    # перемешивание внутри гипотезы, и ровную нагрузку целиком.
    last = {}                    # кто снимал предыдущий ролик этой гипотезы
    load = {c: 0 for c in creators}
    rows = []
    for i, ((mech, fact), date) in enumerate(zip(order, dates)):
        key = mech or CREATOR_SLOT
        можно = [c for c in creators if c != last.get(key)] or list(creators)
        кто = min(можно, key=lambda c: (load[c], c))
        load[кто] += 1
        last[key] = кто
        row = {c: "" for c in COLUMNS}
        row.update({
            "ID": "P%d-%02d" % (number, i + 1),
            "Креатор": кто,
            "Механика": mech or "",
            "Гипотеза": mech or CREATOR_SLOT,
            "Факт-источник": fact,
            "Ожидаемый сигнал": "репосты на 1000 выше базовой медианы",
            "Дата в эфир": date,
            "Статус": DRAFT,
        })
        rows.append(row)
    return rows


def write(sheet, rows):
    """Дописывает черновик в лист ПЛАН. Повтор безопасен: ID не дублируются."""
    have = {str(r.get("ID") or "").strip() for r in sheet.read()}
    added = 0
    for row in rows:
        if row["ID"] in have:
            continue
        sheet.append(row)
        have.add(row["ID"])
        added += 1
    return added


def summary(rows, dictionary=None):
    """Что предложено - словами. Молчащий генератор не отличить от несделанного.

    Второй довод необязательный: если словарь передан, сводка расскажет и о том,
    что в партию НЕ попало. Приемка 28.08: выгоревшие механики машина снимала
    молча, а недобранные гипотезы копились вечно и были невидимы - очередь
    существовала, и владелец о ней не знал.
    """
    if not rows:
        return ("План следующей партии собрать не из чего: в словаре нет механик, "
                "по которым можно принимать решение. Нужны замеры.")
    from collections import Counter
    per = Counter(r["Гипотеза"] for r in rows)
    lines = ["📋 Черновик плана партии: %d роликов, %s - %s"
             % (len(rows), rows[0]["Дата в эфир"], rows[-1]["Дата в эфир"]), ""]
    for hyp, n in per.most_common():
        who = ", ".join(sorted({r["Креатор"] for r in rows if r["Гипотеза"] == hyp}))
        lines.append("· %s - %d роликов (%s)" % (hyp, n, who))
    lines += ["",
              "🔴 Механика внутри гипотезы повторяется НАМЕРЕННО: без четырех "
              "роликов решение принять не на чем. Но кадр и хук у них обязаны "
              "быть разными - замер 26.08: один и тот же текст поста дает разброс "
              "×50, план задается кадром, а не текстом. Одинаковые кадры внутри "
              "гипотезы сделают замер бессмысленным и ленту однообразной.",
              "",
              "Колонки «что в кадре» и «смысл хука» пустые намеренно: содержание "
              "машина не выдумывает."]

    # 🔴 Однообразие партии - это не сбой раскладки, а состояние словаря.
    # Молчать о нем нельзя: владелец увидит скучную ленту и не поймет, почему.
    top, top_n = per.most_common(1)[0]
    if top_n * 3 > len(rows):
        lines += ["",
                  "⚠️ На «%s» приходится %d роликов из %d - партия выйдет "
                  "однообразной. Причина не в расписании, а в словаре: пригодных "
                  "механик мало. Нужна новая гипотеза - Ваша или от креаторов."
                  % (top, top_n, len(rows))]
    runs = longest_run([r["Гипотеза"] for r in rows])
    if runs > 1:
        lines += ["",
                  "⚠️ Одна гипотеза стоит %d дня подряд - развести не удалось, "
                  "слотов не хватило." % runs]
    # 🔴 Предупреждение обязательное, а не вежливое. У слотов креатора механика
    # пустая, а словарь пустые механики пропускает - результат этих роликов
    # не попал бы в память петли вообще, и заметить это было бы нечем:
    # строки в плане есть, цифры по остальным считаются.
    if any(r["Гипотеза"] == CREATOR_SLOT for r in rows):
        lines.append("🔴 У слотов креатора механика пустая. Проставьте ее при "
                     "утверждении: без нее ролик не попадет в словарь механик, "
                     "и его результат петля не запомнит.")

    # 🔴 Партия целиком на одном человеке. Это тот самый confound, ради которого
    # генератор и написан: прием становится неотличим от человека, а из аккаунта
    # креатора пересылают вчетверо чаще (2,11 против 0,50, замер 26.08).
    # Раньше проходило бесшумно - генератор просто брал, кого нашел в плане.
    who = sorted({r["Креатор"] for r in rows if r.get("Креатор")})
    if len(who) < 2:
        имя = who[0] if who else "не назначен"
        lines += ["",
                  "🔴 Вся партия достается одному исполнителю (%s). Разницу "
                  "механик будет не отличить от разницы людей - это ломает саму "
                  "цель партии. Назначьте второго креатора до утверждения." % имя]

    # 🔴 На гипотезу должно приходиться не меньше четырех роликов, иначе
    # решение принять не на чем и слоты потрачены впустую. При укороченной партии
    # это неизбежно - но сказать об этом обязаны.
    мало = [h for h, n in per.items() if h != CREATOR_SLOT and n < MIN_PER_HYPOTHESIS]
    if мало:
        lines += ["",
                  "⚠️ Роликов меньше четырех на гипотезу: %s. Решение по ним "
                  "принять будет не на чем - партия короче, чем нужно для замера."
                  % ", ".join("%s (%d)" % (h, per[h]) for h in мало)]

    # 🔴 Что НЕ попало в партию. Вариант, выбывший молча, - закрытая дверь:
    # владелец не узнает, что механику сняла машина, а не он.
    if dictionary:
        взяты = {r["Механика"] for r in rows if r["Механика"]}
        выгоревшие, очередь = [], []
        for mech, d in dictionary.items():
            if not mech or mech in взяты:
                continue
            статус = d.get("статус по метрикам", "")
            if "выгорела" in статус:
                выгоревшие.append(mech)
            elif "опровергнута" not in статус:
                очередь.append((mech, d.get("применений") or 0))
        if выгоревшие:
            lines += ["",
                      "🔴 Не взяты как выгоревшие: %s. Машина сняла их сама - "
                      "если считаете иначе, верните их в план руками."
                      % ", ".join(sorted(выгоревшие))]
        if очередь:
            очередь.sort(key=lambda x: -x[1])
            lines += ["",
                      "⏳ Очередь недобранных гипотез (в эту партию не влезли): %s. "
                      "Пока их не поставить, они не доберут четырех роликов никогда."
                      % ", ".join("%s (%d из %d)" % (m, n, MIN_PER_HYPOTHESIS)
                                  for m, n in очередь)]
    # 🔴 Гейт однообразия вызывается ЗДЕСЬ, а не «руками перед утверждением».
    # Приемка 28.08: он не был подключен ни к чему - не импортировался никем,
    # в расписании его не было. То есть проверка, объявленная обязательной перед
    # утверждением партии, пропускалась молча, а выглядело это как «гейт есть».
    #
    # На свежем черновике он почти всегда молчит: колонки хука и кадра пустые
    # по замыслу. Смысл в другом - когда владелец заполнит их и пересоберет
    # сводку, проверка отработает сама, без отдельной команды.
    try:
        import variety
        находки = variety.check(rows)
        реальные = [f for f in находки if f["вид"] != "план не заполнен"]
        if реальные:
            lines += ["", variety.report(реальные, rows)]
    except Exception as e:                       # гейт не должен ронять сводку
        lines += ["", "⚠️ Проверка однообразия не отработала: %s" % str(e)[:200]]

    # 🔴 Выполнимость - вторая обязательная проверка перед утверждением.
    # Замер 28.08: план требовал от Спартака шести товаров и говорящего ребенка,
    # а у него сын около года и один товар. Снимаемой была одна строка из семи,
    # и ни одно правило партии этого не ловило.
    try:
        import io as _io
        import os as _os
        import feasibility
        путь = _os.path.join(_os.path.dirname(_os.path.abspath(__file__)),
                             "..", "data", "креаторы.tsv")
        if _os.path.exists(путь):
            with _io.open(путь, encoding="utf-8-sig") as f:
                профили = feasibility.read_profiles(f)
            находки = feasibility.check(rows, профили)
            if находки:
                lines += ["", feasibility.report(находки, профили)]
        else:
            lines += ["", "⚠️ Профилей креаторов нет (data/креаторы.tsv) - "
                          "снимаемость строк проверить нечем."]
    except Exception as e:
        lines += ["", "⚠️ Проверка выполнимости не отработала: %s" % str(e)[:200]]

    lines.append("План черновой и ничего не публикует, пока Вы его не утвердите.")
    return "\n".join(lines)


def maybe_propose(book, dictionary_data, today):
    """Предлагает следующую партию, если предыдущая полностью замерена.

    🔴 Условие «полностью замерена» строгое намеренно. Собрать план по половине
    партии - значит принять решение на половине данных, а потом уже не отличить,
    чем оно было вызвано. Лучше не предложить ничего, чем предложить рано.

    Возвращает (строки, причина). Строки пустые - причина словами, зачем-то же
    генератор промолчал.
    """
    plan = book.sheet("ПЛАН").read()
    if not plan:
        return [], "плана нет - предлагать следующую партию не от чего"

    # 🔴 Замерен - значит В ЯЧЕЙКЕ ЕСТЬ ЧИСЛО, а не строка в листе.
    # Приемка 28.08: гейт считал строки, поэтому владелец, заведший строки
    # в МЕТРИКАХ заранее (обычная привычка при работе в таблице), снимал гейт
    # сам - и партия 2 предлагалась по пяти замеренным роликам из пятнадцати.
    measured = set()
    for r in book.sheet("МЕТРИКИ").read():
        key = str(r.get("ID") or "").strip()
        if key and _has_number(r.get("Репосты/1000")):
            measured.add(key)

    ids = [str(r.get("ID") or "").strip() for r in plan if str(r.get("ID") or "").strip()]
    # 🔴 ID не по шаблону обходили гейт целиком: при пустых ID или кириллической
    # «Р» вместо латинской «P» номер партии сбрасывался на 1, и в лист ложился
    # второй комплект строк, визуально неотличимый от первого. Учет после этого
    # не сходится никаким разбором, поэтому это отказ, а не предупреждение.
    чужие = [i for i in ids if not re.match(r"^P\d+-\d+$", i)]
    без_id = len([r for r in plan if not str(r.get("ID") or "").strip()])
    if чужие or без_id:
        примеры = ", ".join(чужие[:3]) or "пустые"
        return [], ("в плане %d строк с ID не по шаблону P<партия>-<номер> (%s) - "
                    "проверить, чем замерена партия, невозможно. Исправьте ID: "
                    "иначе следующая партия ляжет поверх незамеренной"
                    % (len(чужие) + без_id, примеры))

    current = "P%d-" % max_batch(ids)
    batch = [i for i in ids if i.startswith(current)]
    left = [i for i in batch if i not in measured]
    if left:
        return [], "партия %s замерена не вся: осталось %d из %d" % (
            current.rstrip("-"), len(left), len(batch))

    # Последний день партии ищем СРАВНЕНИЕМ ДАТ, а не строк: «05.10.2026»
    # строкой меньше «28.09.2026», и хвост партии находился неверно.
    даты = [_as_date(r.get("Дата в эфир")) for r in plan
            if str(r.get("ID") or "").startswith(current)]
    даты = [d for d in даты if d]
    непонятных = sum(1 for r in plan
                     if str(r.get("ID") or "").startswith(current)
                     and _as_date(r.get("Дата в эфир")) is None
                     and str(r.get("Дата в эфир") or "").strip())
    if непонятных:
        return [], ("в партии %s у %d строк дата не читается - неясно, когда "
                    "закончится партия. Приведите даты к виду ГГГГ-ММ-ДД"
                    % (current.rstrip("-"), непонятных))
    try:
        start = _next_day(max(даты) if даты else today)
    except ValueError as e:
        return [], str(e)
    creators = sorted({str(r.get("Креатор") or "").strip() for r in plan
                       if str(r.get("Креатор") or "").strip()})
    rows = propose(dictionary_data, plan, creators or ["не назначен"], start)
    if not rows:
        return [], "в словаре нет механик, по которым можно принимать решение"
    return rows, ""


def _has_number(value):
    """В ячейке настоящее число, а не пустота и не текст.

    Лист отдает все строками, и «» с «н/д» выглядят так же, как «1,5».
    Запятая - обычный русский десятичный разделитель, ее принимаем.
    """
    text = str(value if value is not None else "").strip().replace(",", ".")
    if not text:
        return False
    try:
        float(text)
        return True
    except ValueError:
        return False


def max_batch(ids):
    best = 0
    for i in ids:
        m = re.match(r"^P(\d+)-", i)
        if m:
            best = max(best, int(m.group(1)))
    return best


def _as_date(value):
    """Дата из того, что лежит в листе. None, если не разобрать.

    🔴 Раньше нераспознанное молча заменялось сегодняшним днем. Достаточно было
    русского формата «18.09.2026» в плане - и партия 2 стартовала завтра, поверх
    идущей партии 1: три недели наложения по одной публикации в день на общий
    аккаунт, гипотезы обеих партий перемешаны в одном окне раздачи. Отказ был
    невидим: даты в новом плане выглядели совершенно нормально.
    """
    if isinstance(value, datetime.date):
        return value
    text = str(value or "").strip()[:10]
    for fmt in ("%Y-%m-%d", "%d.%m.%Y", "%d/%m/%Y", "%Y/%m/%d"):
        try:
            return datetime.datetime.strptime(text, fmt).date()
        except ValueError:
            continue
    return None


def _next_day(value):
    d = _as_date(value)
    if d is None:
        # Молча взять сегодня нельзя: партия наедет на идущую. Пусть решает тот,
        # кто вызвал, - он знает, чем заменить.
        raise ValueError("не разобрать дату %r: ожидается ГГГГ-ММ-ДД или ДД.ММ.ГГГГ"
                         % (value,))
    return (d + datetime.timedelta(days=1)).isoformat()


