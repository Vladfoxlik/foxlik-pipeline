# нарушение. Цикл не сходится.
#
# Здесь порядок обратный: перебираются только **допустимые** сочетания.
# Возраст ребенка в кадре, ценность, разрешенная этим возрастом, товар,
# у которого эта ценность подтверждена, тема под сегмент. Нарушить это
# генератор не может физически - не «старается не».
#
# Человеку остаются четыре колонки: «Что в кадре», «Хук» и «Текст на экране».
