def _num(value):
    """Число из ячейки. Лист отдает все строками, включая «3,0» с запятой."""
    if isinstance(value, (int, float)):
        return float(value)
    try:
        return float(str(value or "").strip().replace(",", "."))
    except ValueError:
        return 0.0


def usable(dictionary):
    """Механики, которые можно ставить в план, и почему.

    Возвращает список пар (механика, основание) в порядке убывания пользы:
    сперва то, что подтверждено, потом то, что не досчитано.
    """
    confirmed, collecting = [], []
    for mech, d in dictionary.items():
        if not str(mech or "").strip():
            # 🔴 Пустое имя механики сливалось со слотом креатора: в сводке
            # выходила одна строка «гипотеза креатора - 10 роликов», внутри
            # которой были перемешаны настоящая гипотеза и квота.
            continue
        status = d.get("статус по метрикам", "")
        if "опровергнута" in status or "выгорела" in status:
            continue
        # 🔴 Лист отдает числа строками, и «3,0» роняло генератор целиком.
        fact = "медиана %.2f реп/1000 на %d роликах" % (_num(d.get("медиана")),
                                                        int(_num(d.get("применений"))))
        if "подтверждена" in status:
            confirmed.append((mech, "подтверждена ранее: " + fact))
        else:
            need = MIN_PER_HYPOTHESIS - (d.get("применений") or 0)
            collecting.append((mech, "не решено, добираем %d до четырех: %s"
                               % (max(need, 1), fact)))
    confirmed.sort(key=lambda x: (-_num(dictionary[x[0]].get("медиана")), x[0]))
    # 🔴 Второй ключ - имя. Без него порядок ключей словаря решал, какие
    # гипотезы попадут в партию: при равных показателях состав менялся
    # от порядка строк в листе, и чужой прогон было не воспроизвести.
    collecting.sort(key=lambda x: (-_num(dictionary[x[0]].get("применений")), x[0]))
    return confirmed + collecting


def next_batch_number(plan):
    """Номер партии продолжает прошлую: столкновение ID испортило бы учет."""
    best = 0
    for row in plan:
        m = re.match(r"^P(\d+)-", str(row.get("ID") or "").strip())
        if m:
            best = max(best, int(m.group(1)))
    return best + 1


